//! An instance on disk: `/www/<name>/{conf,htdocs,logs}`, its
//! `httpd.conf`, creating, deleting, reading its ports, replacing its
//! configuration safely.

use std::fmt::Write as _;

use crate::conf::{self, Conf, Scope as _};
use crate::files::Files;
use crate::registry::{self, Registry};
use crate::{Error, Result};

/// The configuration file under the server root.
pub const CONF: &str = "conf/httpd.conf";

/// Check an instance name: 1 to 10 letters and digits, starting with a
/// letter. Returns it upper case.
pub fn check_name(name: &str) -> Result<String> {
    let n = name.trim().to_ascii_uppercase();
    let ok = !n.is_empty()
        && n.len() <= 10
        && n.starts_with(|c: char| c.is_ascii_alphabetic())
        && n.chars().all(|c| c.is_ascii_alphanumeric());
    if ok { Ok(n) } else { Err(Error::BadName(name.trim().to_string())) }
}

/// The default server root of instance `name`.
pub fn default_root(name: &str) -> String {
    format!("/www/{}", name.to_ascii_lowercase())
}

/// The configuration file of the instance rooted at `root`.
pub fn conf_path(root: &str) -> String {
    format!("{}/{CONF}", root.trim_end_matches('/'))
}

/// A path the configuration gives relative to the server root.
pub fn resolve(root: &str, p: &str) -> String {
    if p.starts_with('/') {
        p.to_string()
    } else {
        format!("{}/{p}", root.trim_end_matches('/'))
    }
}

/// Access log formats the wizard offers.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LogFormat {
    /// `combined`.
    Combined,
    /// `common`.
    Common,
    /// `extended` (combined with the response time).
    Extended,
}

impl LogFormat {
    /// The `LogFormat` nickname.
    pub fn nick(self) -> &'static str {
        match self {
            LogFormat::Combined => "combined",
            LogFormat::Common => "common",
            LogFormat::Extended => "extended",
        }
    }

    /// The format string.
    pub fn format(self) -> &'static str {
        match self {
            LogFormat::Combined => "%h %l %u %t \"%r\" %>s %b \"%{Referer}i\" \"%{User-Agent}i\"",
            LogFormat::Common => "%h %l %u %t \"%r\" %>s %b",
            LogFormat::Extended => "%h %l %u %t \"%r\" %>s %b \"%{Referer}i\" \"%{User-Agent}i\" %D",
        }
    }
}

/// What a new instance is made of (the Create wizard's answers).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Spec {
    /// The name.
    pub name: String,
    /// Its text.
    pub description: String,
    /// The server root.
    pub root: String,
    /// The document root.
    pub docroot: String,
    /// Write a sample `index.html`.
    pub sample: bool,
    /// The listening address, `None` for every one.
    pub addr: Option<String>,
    /// The port.
    pub port: u16,
    /// The access log path and format; `None` for no access log.
    pub access_log: Option<(String, LogFormat)>,
    /// Days of logs kept, 0 for no rotation.
    pub keep_days: u32,
    /// The server user profile.
    pub user: String,
    /// Started with `STRTCP`.
    pub autostart: bool,
    /// Another instance whose configuration to copy.
    pub copy_from: Option<String>,
}

/// The configuration file of a new instance. `stamp` is the generation
/// time as the user sees it (`10/27/26 18:40:55`).
pub fn generate(s: &Spec, stamp: &str) -> String {
    let listen = match &s.addr {
        Some(a) => format!("{a}:{}", s.port),
        None => format!("*:{}", s.port),
    };
    let mut out = format!(
        "# Configuration for HTTP server instance {}\n\
         # Generated by QS/400 HTTP Server Administration {stamp}\n\
         ServerRoot {}\n\
         Listen {listen}\n\
         DocumentRoot {}\n\
         ServerUserID {}\n\
         ThreadsPerChild 40\n",
        s.name, s.root, s.docroot, s.user
    );
    if let Some((path, fmt)) = &s.access_log {
        let rel = path.strip_prefix(&format!("{}/", s.root.trim_end_matches('/'))).unwrap_or(path);
        let _ = writeln!(out, "LogFormat {} {}", conf::quote(fmt.format()), fmt.nick());
        let _ = writeln!(out, "CustomLog {rel} {}", fmt.nick());
        if s.keep_days > 0 {
            let _ = writeln!(out, "LogMaint {rel} {} 0", s.keep_days);
        }
    }
    out.push_str("ErrorLog logs/error_log\nLogLevel warn\n");
    if s.keep_days > 0 {
        let _ = writeln!(out, "LogMaint logs/error_log {} 0", s.keep_days);
    }
    let _ = write!(
        out,
        "DirectoryIndex index.html index.htm\nOptions -Indexes +FollowSymLinks\n\n\
         <Directory />\n   Order Deny,Allow\n   Deny From all\n</Directory>\n\
         <Directory {}>\n   Order Allow,Deny\n   Allow From all\n</Directory>\n",
        s.docroot
    );
    out
}

/// The sample page a new instance serves.
pub fn sample_index(name: &str) -> String {
    format!(
        "<!DOCTYPE html>\n<html>\n<head><title>{name}</title></head>\n<body>\n\
         <h1>HTTP server instance {name}</h1>\n\
         <p>This page was created with the instance. Replace it with your own content.</p>\n\
         </body>\n</html>\n"
    )
}

fn io(path: &str) -> impl Fn(std::io::Error) -> Error + '_ {
    move |e| Error::Io(path.to_string(), e.to_string())
}

/// Create an instance: its directories, configuration, optional sample
/// page and registry entry. `now` is seconds since 1970.
pub fn create(files: &dyn Files, s: &Spec, stamp: &str, now: u64) -> Result<()> {
    let name = check_name(&s.name)?;
    let mut reg = Registry::load(files)?;
    if reg.get(&name).is_some() {
        return Err(Error::Exists(name));
    }
    let s = &Spec { name: name.clone(), ..s.clone() };
    let text = match &s.copy_from {
        Some(from) => {
            let src = reg.get(from).ok_or_else(|| Error::NotFound(from.clone()))?;
            let p = conf_path(&src.root);
            let old = String::from_utf8_lossy(&files.read(&p).map_err(io(&p))?).into_owned();
            let mut c = conf::parse(&old).map_err(Error::Conf)?;
            c.set("ServerRoot", &[&s.root]);
            c.set("DocumentRoot", &[&s.docroot]);
            c.print()
        }
        None => generate(s, stamp),
    };
    for d in ["conf", "htdocs", "logs"] {
        let p = format!("{}/{d}", s.root.trim_end_matches('/'));
        files.mkdir_all(&p).map_err(io(&p))?;
    }
    files.mkdir_all(&s.docroot).map_err(io(&s.docroot))?;
    let cp = conf_path(&s.root);
    files.write_atomic(&cp, text.as_bytes()).map_err(io(&cp))?;
    if s.sample {
        let ip = format!("{}/index.html", s.docroot.trim_end_matches('/'));
        if !files.exists(&ip) {
            files.write_atomic(&ip, sample_index(&name).as_bytes()).map_err(io(&ip))?;
        }
    }
    reg.put(registry::Entry {
        name,
        description: s.description.clone(),
        root: s.root.clone(),
        autostart: s.autostart,
        created: now,
        ..registry::Entry::default()
    });
    reg.save(files)
}

/// Delete an instance: its registry entry, then its server root. The
/// instance is gone once the entry is; files that could not be removed
/// are named in the `Some` (the error).
pub fn delete(files: &dyn Files, name: &str) -> Result<Option<String>> {
    let mut reg = Registry::load(files)?;
    let e = reg.get(name).cloned().ok_or_else(|| Error::NotFound(name.to_string()))?;
    reg.remove(name);
    reg.save(files)?;
    if !files.exists(&e.root) {
        return Ok(None);
    }
    Ok(files.remove_tree(&e.root).err().map(|x| x.to_string()))
}

/// An instance's configuration text.
pub fn read_conf(files: &dyn Files, root: &str) -> Result<String> {
    let p = conf_path(root);
    Ok(String::from_utf8_lossy(&files.read(&p).map_err(io(&p))?).into_owned())
}

/// An instance's parsed configuration.
pub fn load_conf(files: &dyn Files, root: &str) -> Result<Conf> {
    conf::parse(&read_conf(files, root)?).map_err(Error::Conf)
}

/// Replace an instance's configuration with `text`: it must parse; the
/// old file is kept as `httpd.conf.bak`; the new one is written to a
/// temporary file and renamed, so an interrupted write leaves the old
/// file in place. Marks the instance as needing a restart when
/// `running`.
pub fn apply_conf(files: &dyn Files, name: &str, root: &str, text: &str, running: bool) -> Result<()> {
    conf::parse(text).map_err(Error::Conf)?;
    let p = conf_path(root);
    let bak = format!("{p}.bak");
    if files.exists(&p) {
        files.copy(&p, &bak).map_err(io(&bak))?;
    }
    files.write_atomic(&p, text.as_bytes()).map_err(io(&p))?;
    if running {
        Registry::update(files, name, |e| e.restart_required = true)?;
    }
    Ok(())
}

/// A listening port and what serves on it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Port {
    /// The address, `None` for every one.
    pub addr: Option<String>,
    /// The port.
    pub port: u16,
    /// A `<VirtualHost>` for the port turns `SSLEngine On`.
    pub tls: bool,
    /// The `ServerName` serving it (the virtual host's, else the
    /// server's), if any.
    pub server_name: Option<String>,
}

/// The ports a configuration listens on, in file order.
pub fn ports(c: &Conf) -> Vec<Port> {
    let main_name = c.get("ServerName").map(conf::Directive::value);
    c.all("Listen")
        .into_iter()
        .filter_map(|d| conf::rules::listen_addr(d.args.first()?).ok())
        .map(|(addr, port)| {
            let vhost = c.sections("VirtualHost").into_iter().find(|v| {
                v.args.iter().any(|a| {
                    conf::rules::listen_addr(a).is_ok_and(|(va, vp)| vp == port && (va.is_none() || va == addr))
                })
            });
            Port {
                tls: vhost.is_some_and(|v| v.value("SSLEngine").eq_ignore_ascii_case("on")),
                server_name: vhost
                    .and_then(|v| v.get("ServerName").map(conf::Directive::value))
                    .or_else(|| main_name.clone()),
                addr,
                port,
            }
        })
        .collect()
}

/// The last `n` lines of `text` holding `filter` (all when empty).
pub fn tail(text: &str, n: usize, filter: &str) -> Vec<String> {
    let lines: Vec<&str> = text.lines().filter(|l| filter.is_empty() || l.contains(filter)).collect();
    lines[lines.len().saturating_sub(n)..].iter().map(ToString::to_string).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::files::MemFiles;

    fn spec() -> Spec {
        Spec {
            name: "webstore".into(),
            description: "Web store front end".into(),
            root: "/www/webstore".into(),
            docroot: "/www/webstore/htdocs".into(),
            sample: true,
            addr: None,
            port: 80,
            access_log: Some(("/www/webstore/logs/access_log".into(), LogFormat::Combined)),
            keep_days: 30,
            user: "QTMHHTTP".into(),
            autostart: false,
            copy_from: None,
        }
    }

    #[test]
    fn names() {
        assert_eq!(check_name(" webstore ").unwrap(), "WEBSTORE");
        for bad in ["", "1ABC", "ABCDEFGHIJK", "A-B"] {
            assert!(check_name(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn create_apply_delete() {
        let f = MemFiles::new();
        create(&f, &spec(), "10/27/26 18:40:55", 1).unwrap();
        let text = read_conf(&f, "/www/webstore").unwrap();
        assert!(text.starts_with("# Configuration for HTTP server instance WEBSTORE\n# Generated by QS/400 HTTP Server Administration 10/27/26 18:40:55\nServerRoot /www/webstore\nListen *:80\n"));
        assert!(text.contains("CustomLog logs/access_log combined\nLogMaint logs/access_log 30 0\n"));
        let c = conf::parse(&text).unwrap();
        assert_eq!(ports(&c), vec![Port { addr: None, port: 80, tls: false, server_name: None }]);
        assert!(f.exists("/www/webstore/htdocs/index.html"));
        assert!(f.exists("/www/webstore/logs"));
        assert!(matches!(create(&f, &spec(), "", 2), Err(Error::Exists(_))));
        let mut copy = spec();
        copy.name = "WEB2".into();
        copy.root = "/www/web2".into();
        copy.docroot = "/www/web2/htdocs".into();
        copy.copy_from = Some("WEBSTORE".into());
        create(&f, &copy, "", 3).unwrap();
        assert!(read_conf(&f, "/www/web2").unwrap().contains("ServerRoot /www/web2\nListen *:80\nDocumentRoot /www/web2/htdocs\n"));

        let bad = apply_conf(&f, "WEBSTORE", "/www/webstore", "Listen x\n", true).unwrap_err();
        assert!(matches!(bad, Error::Conf(ref e) if e.line == 1), "{bad:?}");
        let new = format!("{text}Listen *:443\n<VirtualHost *:443>\n   SSLEngine On\n   ServerName shop\n</VirtualHost>\n");
        apply_conf(&f, "WEBSTORE", "/www/webstore", &new, true).unwrap();
        assert_eq!(f.read("/www/webstore/conf/httpd.conf.bak").unwrap(), text.as_bytes());
        assert!(Registry::load(&f).unwrap().get("WEBSTORE").unwrap().restart_required);
        let p = ports(&load_conf(&f, "/www/webstore").unwrap());
        assert_eq!(p[1], Port { addr: None, port: 443, tls: true, server_name: Some("shop".into()) });

        assert_eq!(delete(&f, "webstore").unwrap(), None);
        assert!(!f.exists("/www/webstore"));
        assert!(Registry::load(&f).unwrap().get("WEBSTORE").is_none());
    }

    #[test]
    fn tails() {
        let t = "a 1\nb 2\na 3\nc 4\na 5\n";
        assert_eq!(tail(t, 2, "a"), vec!["a 3", "a 5"]);
        assert_eq!(tail(t, 10, "").len(), 5);
        assert_eq!(resolve("/www/x", "logs/a"), "/www/x/logs/a");
    }
}
