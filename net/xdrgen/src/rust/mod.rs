//! The Rust writer. What it writes for each definition:
//!
//! - `const`: `pub const NAME: u32` (`i32`, `i64` or `u64` when the value
//!   needs it).
//! - `enum`: a Rust enum (`Copy`, `Eq`, `Hash`) with `value()` and
//!   `from_value()`; an unknown value on decode is an error.
//! - `struct`: a struct with the same field names.
//! - `union`: a Rust enum with one variant per case label, named after
//!   the label (`V5` for the literal 5, `VM5` for -5, `TRUE`/`FALSE`
//!   for bool), and `default` holding the discriminant (and the arm).
//!   A bool union of `TRUE: T` and `FALSE: void` is `Option<T>`.
//! - `typedef`: `pub type` for a plain name, a fixed opaque or an
//!   optional; a newtype `pub struct Name(pub ...)` for a bounded or
//!   variable item, whose bound it then checks.
//! - `program`: constants for the program, each version and each
//!   procedure, and a module per program with a module per version
//!   holding `Args` and `Res` (one variant per procedure) and their
//!   `ProcBody` implementations.
//!
//! The code names the runtime by the path in [`Options::runtime`]: its
//! `Xdr` and `ProcBody` traits, `Encoder`, `Decoder`, `Error`, `Result`.

mod names;
mod program;

use crate::resolve::ir::{Arm, Base, Disc, Kind, Model, Shape, Ty};
use names::ident;

/// What the writer needs to know.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Options {
    /// The path of the runtime module, such as `crate::xdr`.
    pub runtime: String,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            runtime: "crate::xdr".to_string(),
        }
    }
}

/// Lines of output.
pub(crate) struct W {
    out: String,
    pub(crate) rt: String,
    pub(crate) file: String,
}

impl W {
    pub(crate) fn line(&mut self, s: &str) {
        self.out.push_str(s);
        self.out.push('\n');
    }
}

/// The Rust source for `model`, from the description `file`.
pub fn write(model: &Model, file: &str, opts: &Options) -> String {
    let mut w = W {
        out: String::new(),
        rt: opts.runtime.clone(),
        file: file.to_string(),
    };
    w.line(&format!("// Generated by xdrgen from {file}. Do not edit."));
    w.line("");
    for (name, v) in &model.consts {
        let ty = const_type(*v);
        w.line(&format!("/// The constant `{name}` (`{file}`)."));
        w.line(&format!("pub const {}: {ty} = {v};", ident(name)));
    }
    for t in &model.types {
        w.line("");
        ty(&mut w, t, model);
    }
    for p in &model.programs {
        w.line("");
        program::write(&mut w, p);
    }
    w.out
}

/// The type a constant is written with.
pub(crate) fn const_type(v: i128) -> &'static str {
    if u32::try_from(v).is_ok() {
        "u32"
    } else if i32::try_from(v).is_ok() {
        "i32"
    } else if i64::try_from(v).is_ok() {
        "i64"
    } else {
        "u64"
    }
}

/// The Rust type of a shape; named types prefixed with `prefix`.
pub(crate) fn rust_type(s: &Shape, prefix: &str) -> String {
    match s {
        Shape::Base(b) => base_type(*b).to_string(),
        Shape::Named(n) => format!("{prefix}{}", ident(n)),
        Shape::FixedOpaque(n) => format!("[u8; {n}]"),
        Shape::VarOpaque(_) => "Vec<u8>".to_string(),
        Shape::FixedArray(e, _) | Shape::VarArray(e, _) => format!("Vec<{}>", rust_type(e, prefix)),
        Shape::Optional(e, true) => format!("Option<Box<{}>>", rust_type(e, prefix)),
        Shape::Optional(e, false) => format!("Option<{}>", rust_type(e, prefix)),
        Shape::List(n) => format!("Vec<{prefix}{}>", ident(n)),
    }
}

fn base_type(b: Base) -> &'static str {
    match b {
        Base::Int => "i32",
        Base::UInt => "u32",
        Base::Hyper => "i64",
        Base::UHyper => "u64",
        Base::Bool => "bool",
    }
}

fn bound(n: u32) -> String {
    if n == u32::MAX {
        "u32::MAX".to_string()
    } else {
        n.to_string()
    }
}

/// A statement encoding `expr` (a reference) of shape `s`.
pub(crate) fn encode(rt: &str, s: &Shape, expr: &str) -> String {
    match s {
        Shape::VarOpaque(m) => format!("e.put_opaque({expr}, {})?;", bound(*m)),
        Shape::FixedArray(_, n) => format!("e.put_fixed_array({expr}, {n})?;"),
        Shape::VarArray(_, m) => format!("e.put_array({expr}, {})?;", bound(*m)),
        Shape::List(_) => format!("e.put_list({expr})?;"),
        _ => format!("{rt}::Xdr::encode({expr}, e)?;"),
    }
}

/// An expression decoding shape `s`.
pub(crate) fn decode(rt: &str, s: &Shape) -> String {
    match s {
        Shape::VarOpaque(m) => format!("d.get_opaque({})?", bound(*m)),
        Shape::FixedArray(_, n) => format!("d.get_fixed_array({n})?"),
        Shape::VarArray(_, m) => format!("d.get_array({})?", bound(*m)),
        Shape::List(_) => "d.get_list()?".to_string(),
        _ => format!("{rt}::Xdr::decode(d)?"),
    }
}

fn min_size(m: u64) -> u64 {
    m.min(u64::from(u32::MAX))
}

fn impl_head(w: &mut W, name: &str, min: u64) {
    let rt = w.rt.clone();
    w.line(&format!("impl {rt}::Xdr for {name} {{"));
    w.line(&format!("    const MIN_SIZE: usize = {};", min_size(min)));
}

// One emitter per kind, straight-line.
#[allow(clippy::too_many_lines)]
fn ty(w: &mut W, t: &Ty, model: &Model) {
    let name = ident(&t.name);
    let rt = w.rt.clone();
    let at = format!("`{}` line {}", w.file, t.line);
    match &t.kind {
        Kind::Enum(members) => {
            w.line(&format!("/// The enum `{}` ({at}).", t.name));
            w.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
            w.line(&format!("pub enum {name} {{"));
            for (m, v) in members {
                w.line(&format!("    /// `{m}` = {v}."));
                w.line(&format!("    {},", ident(m)));
            }
            w.line("}");
            w.line(&format!("impl {name} {{"));
            w.line("    /// The value on the wire.");
            w.line("    pub fn value(self) -> i32 {");
            w.line("        match self {");
            for (m, v) in members {
                w.line(&format!("            Self::{} => {v},", ident(m)));
            }
            w.line("        }");
            w.line("    }");
            w.line("    /// The member with the value `v`.");
            w.line("    pub fn from_value(v: i32) -> Option<Self> {");
            w.line("        match v {");
            for (m, v) in members {
                w.line(&format!("            {v} => Some(Self::{}),", ident(m)));
            }
            w.line("            _ => None,");
            w.line("        }");
            w.line("    }");
            w.line("}");
            impl_head(w, &name, t.min);
            w.line(&format!(
                "    fn encode(&self, e: &mut {rt}::Encoder) -> {rt}::Result<()> {{"
            ));
            w.line("        e.put_i32(self.value());");
            w.line("        Ok(())");
            w.line("    }");
            w.line(&format!(
                "    fn decode(d: &mut {rt}::Decoder<'_>) -> {rt}::Result<Self> {{"
            ));
            w.line("        let v = d.get_i32()?;");
            w.line(&format!(
                "        Self::from_value(v).ok_or({rt}::Error::Discriminant {{ ty: \"{}\", value: i64::from(v) }})",
                t.name
            ));
            w.line("    }");
            w.line("}");
        }
        Kind::Struct(fields) => {
            w.line(&format!("/// The struct `{}` ({at}).", t.name));
            w.line("#[derive(Debug, Clone, PartialEq, Eq)]");
            w.line(&format!("pub struct {name} {{"));
            for (f, s) in fields {
                w.line(&format!("    /// `{f}`."));
                w.line(&format!("    pub {}: {},", ident(f), rust_type(s, "")));
            }
            w.line("}");
            impl_head(w, &name, t.min);
            w.line(&format!(
                "    fn encode(&self, e: &mut {rt}::Encoder) -> {rt}::Result<()> {{"
            ));
            for (f, s) in fields {
                w.line(&format!(
                    "        {}",
                    encode(&rt, s, &format!("&self.{}", ident(f)))
                ));
            }
            w.line("        Ok(())");
            w.line("    }");
            w.line(&format!(
                "    fn decode(d: &mut {rt}::Decoder<'_>) -> {rt}::Result<Self> {{"
            ));
            w.line("        d.enter()?;");
            w.line("        let v = Self {");
            for (f, s) in fields {
                w.line(&format!("            {}: {},", ident(f), decode(&rt, s)));
            }
            w.line("        };");
            w.line("        d.leave();");
            w.line("        Ok(v)");
            w.line("    }");
            w.line("}");
        }
        Kind::Union {
            disc,
            arms,
            default,
        } => {
            // Every value has its arm: no `other` arm on decode.
            let complete = match disc {
                Disc::Bool => arms.len() == 2,
                Disc::Enum(e) => {
                    matches!(model.ty(e).map(|t| &t.kind), Some(Kind::Enum(m)) if m.len() == arms.len())
                }
                Disc::Int | Disc::UInt => false,
            };
            union(w, t, disc, arms, default.as_ref(), complete);
        }
        Kind::Alias(s) => {
            w.line(&format!("/// The type `{}` ({at}).", t.name));
            w.line(&format!("pub type {name} = {};", rust_type(s, "")));
        }
        Kind::Newtype(s) => {
            let inner = rust_type(s, "");
            w.line(&format!("/// The type `{}` ({at}).", t.name));
            w.line("#[derive(Debug, Clone, PartialEq, Eq)]");
            w.line(&format!("pub struct {name}(pub {inner});"));
            w.line(&format!("impl From<{inner}> for {name} {{"));
            w.line(&format!("    fn from(v: {inner}) -> Self {{"));
            w.line("        Self(v)");
            w.line("    }");
            w.line("}");
            if matches!(s, Shape::VarOpaque(_)) {
                w.line(&format!("impl AsRef<[u8]> for {name} {{"));
                w.line("    fn as_ref(&self) -> &[u8] {");
                w.line("        &self.0");
                w.line("    }");
                w.line("}");
            }
            impl_head(w, &name, t.min);
            w.line(&format!(
                "    fn encode(&self, e: &mut {rt}::Encoder) -> {rt}::Result<()> {{"
            ));
            w.line(&format!("        {}", encode(&rt, s, "&self.0")));
            w.line("        Ok(())");
            w.line("    }");
            w.line(&format!(
                "    fn decode(d: &mut {rt}::Decoder<'_>) -> {rt}::Result<Self> {{"
            ));
            w.line(&format!("        Ok(Self({}))", decode(&rt, s)));
            w.line("    }");
            w.line("}");
        }
    }
}

/// The discriminant's Rust type, and how a value of it is written.
fn disc_type(d: &Disc) -> String {
    match d {
        Disc::Int => "i32".into(),
        Disc::UInt => "u32".into(),
        Disc::Bool => "bool".into(),
        Disc::Enum(e) => ident(e),
    }
}

fn disc_value(d: &Disc, a: &Arm) -> String {
    match d {
        Disc::Int | Disc::UInt => a.value.to_string(),
        Disc::Bool => (a.value == 1).to_string(),
        Disc::Enum(e) => format!(
            "{}::{}",
            ident(e),
            ident(a.member.as_deref().unwrap_or_default())
        ),
    }
}

fn put_disc(rt: &str, d: &Disc, v: &str) -> String {
    match d {
        Disc::Int => format!("e.put_i32({v});"),
        Disc::UInt => format!("e.put_u32({v});"),
        Disc::Bool => format!("e.put_bool({v});"),
        Disc::Enum(_) => format!("{rt}::Xdr::encode(&{v}, e)?;"),
    }
}

#[allow(clippy::too_many_lines)]
fn union(
    w: &mut W,
    t: &Ty,
    disc: &Disc,
    arms: &[Arm],
    default: Option<&Option<Shape>>,
    complete: bool,
) {
    let name = ident(&t.name);
    let rt = w.rt.clone();
    let dt = disc_type(disc);
    w.line(&format!(
        "/// The union `{}` (`{}` line {}).",
        t.name, w.file, t.line
    ));
    w.line("#[derive(Debug, Clone, PartialEq, Eq)]");
    w.line(&format!("pub enum {name} {{"));
    for a in arms {
        w.line(&format!("    /// `case {}` ({}).", a.variant, a.value));
        match &a.shape {
            Some(s) => w.line(&format!("    {}({}),", ident(&a.variant), rust_type(s, ""))),
            None => w.line(&format!("    {},", ident(&a.variant))),
        }
    }
    if let Some(d) = default {
        w.line("    /// `default`: the discriminant, then the arm.");
        match d {
            Some(s) => w.line(&format!("    default({dt}, {}),", rust_type(s, ""))),
            None => w.line(&format!("    default({dt}),")),
        }
    }
    w.line("}");
    w.line(&format!("impl {name} {{"));
    w.line("    /// The discriminant.");
    w.line(&format!("    pub fn discriminant(&self) -> {dt} {{"));
    w.line("        match self {");
    for a in arms {
        let pat = if a.shape.is_some() { "(..)" } else { "" };
        w.line(&format!(
            "            Self::{}{pat} => {},",
            ident(&a.variant),
            disc_value(disc, a)
        ));
    }
    if default.is_some() {
        w.line("            Self::default(v, ..) => *v,");
    }
    w.line("        }");
    w.line("    }");
    w.line("}");
    impl_head(w, &name, t.min);
    w.line(&format!(
        "    fn encode(&self, e: &mut {rt}::Encoder) -> {rt}::Result<()> {{"
    ));
    w.line("        match self {");
    for a in arms {
        let dv = disc_value(disc, a);
        if let Some(s) = &a.shape {
            w.line(&format!("            Self::{}(v) => {{", ident(&a.variant)));
            w.line(&format!("                {}", put_disc(&rt, disc, &dv)));
            w.line(&format!("                {}", encode(&rt, s, "v")));
            w.line("            }");
        } else {
            w.line(&format!("            Self::{} => {{", ident(&a.variant)));
            w.line(&format!("                {}", put_disc(&rt, disc, &dv)));
            w.line("            }");
        }
    }
    if let Some(d) = default {
        let pats: Vec<String> = arms.iter().map(|a| disc_value(disc, a)).collect();
        let bind = if d.is_some() {
            "default(dv, v)"
        } else {
            "default(dv)"
        };
        w.line(&format!("            Self::{bind} => {{"));
        w.line(&format!(
            "                if matches!(*dv, {}) {{",
            pats.join(" | ")
        ));
        w.line(&format!(
            "                    return Err({rt}::Error::DefaultArm {{ ty: \"{}\" }});",
            t.name
        ));
        w.line("                }");
        w.line(&format!("                {}", put_disc(&rt, disc, "*dv")));
        if let Some(s) = d {
            w.line(&format!("                {}", encode(&rt, s, "v")));
        }
        w.line("            }");
    }
    w.line("        }");
    w.line("        Ok(())");
    w.line("    }");
    w.line(&format!(
        "    fn decode(d: &mut {rt}::Decoder<'_>) -> {rt}::Result<Self> {{"
    ));
    w.line("        d.enter()?;");
    match disc {
        Disc::Int => w.line("        let disc = d.get_i32()?;"),
        Disc::UInt => w.line("        let disc = d.get_u32()?;"),
        Disc::Bool | Disc::Enum(_) => {
            w.line(&format!("        let disc: {dt} = {rt}::Xdr::decode(d)?;"))
        }
    }
    w.line("        let v = match disc {");
    for a in arms {
        let arm = match &a.shape {
            Some(s) => format!("Self::{}({})", ident(&a.variant), decode(&rt, s)),
            None => format!("Self::{}", ident(&a.variant)),
        };
        w.line(&format!("            {} => {arm},", disc_value(disc, a)));
    }
    match default {
        _ if complete => {}
        Some(Some(s)) => w.line(&format!(
            "            other => Self::default(other, {}),",
            decode(&rt, s)
        )),
        Some(None) => w.line("            other => Self::default(other),"),
        None => {
            let value = match disc {
                Disc::Enum(_) => "i64::from(other.value())",
                _ => "i64::from(other)",
            };
            w.line("            other => {");
            w.line(&format!(
                "                return Err({rt}::Error::Discriminant {{ ty: \"{}\", value: {value} }});",
                t.name
            ));
            w.line("            }");
        }
    }
    w.line("        };");
    w.line("        d.leave();");
    w.line("        Ok(v)");
    w.line("    }");
    w.line("}");
}
