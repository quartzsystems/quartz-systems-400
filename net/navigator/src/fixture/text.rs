pub fn second_level(id: &str, data: &[&str]) -> Option<SecondLevel> {
    MESSAGES.iter().find(|m| m.0 == id).map(|m| SecondLevel {
        id: m.0.into(),
        severity: m.1,
        text: substitute(m.2, data),
        cause: substitute(m.3, data),
        recovery: substitute(m.4, data),
    })
}
