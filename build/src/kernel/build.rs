//! Configure and compile the kernel. The UKI step is the same build with
//! the initramfs embedded.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, ensure};
use tracing::info;

use crate::ctx::Ctx;
use crate::host::cmd::Cmd;
use crate::host::hash::{sha256_file, short};
use crate::host::paths;
use crate::kernel::{
    CMDLINE, DEFCONFIG, FRAGMENT, KERNEL_ARCH, KERNEL_IMAGE, MAKE_TARGET, config, fetch,
};

/// 2026-01-01T00:00:00Z. Fixed for reproducible builds.
pub const SOURCE_DATE_EPOCH: &str = "1767225600";
const BUILD_TIMESTAMP: &str = "Thu Jan  1 00:00:00 UTC 2026";

/// `build kernel`: configure, verify, build without an initramfs.
pub fn kernel(ctx: &Ctx) -> Result<()> {
    let src = fetch::fetch(ctx)?;
    let cfg = configure(ctx, &src.dir, &[])?;
    config::verify(&cfg, None)?;
    let image = build(ctx, &src.dir)?;
    let size = fs::metadata(&image)?.len();
    info!("kernel: {} ({size} bytes)", image.display());
    Ok(())
}

/// `build uki`: same build with the cpio embedded; copy out as the UKI.
pub fn uki(ctx: &Ctx) -> Result<PathBuf> {
    let src = fetch::fetch(ctx)?;
    let cpio = ctx.paths.initramfs();
    ensure!(
        cpio.is_file(),
        "missing {}; run `initramfs` first",
        cpio.display()
    );

    let frag = ctx.paths.kernel_build().join("uki.config");
    fs::create_dir_all(ctx.paths.kernel_build())?;
    fs::write(
        &frag,
        format!(
            "# Generated by `build uki`.\n\
             CONFIG_INITRAMFS_SOURCE=\"{}\"\n\
             CONFIG_INITRAMFS_COMPRESSION_GZIP=y\n\
             # CONFIG_INITRAMFS_COMPRESSION_NONE is not set\n\
             CONFIG_CMDLINE=\"{CMDLINE}\"\n",
            cpio.display(),
        ),
    )?;

    let cfg = configure(ctx, &src.dir, &[frag])?;
    config::verify(&cfg, Some(&cpio))?;
    let image = build(ctx, &src.dir)?;

    let hash = sha256_file(&image)?;
    let out_dir = ctx.paths.images();
    fs::create_dir_all(&out_dir)?;
    let out = out_dir.join(format!("qs400-{}-{}.efi", src.version, short(&hash)));
    fs::copy(&image, &out).with_context(|| format!("cannot copy UKI to {}", out.display()))?;
    paths::write_pointer(&ctx.paths.uki_pointer(), &out)?;
    let size = fs::metadata(&out)?.len();
    info!("UKI: {} ({size} bytes, sha256 {hash})", out.display());
    Ok(out)
}

/// The out-of-tree build directory.
pub fn build_dir(ctx: &Ctx) -> PathBuf {
    ctx.paths.kernel_build().join("build")
}

/// The final `.config`, if configured.
pub fn config_path(ctx: &Ctx) -> PathBuf {
    build_dir(ctx).join(".config")
}

/// Merge the fragment onto the defconfig and resolve with `olddefconfig`.
fn configure(ctx: &Ctx, src: &Path, extra: &[PathBuf]) -> Result<PathBuf> {
    let out = build_dir(ctx);
    fs::create_dir_all(&out)?;

    let mut merge = Cmd::new("sh", "kernel-merge");
    merge
        .cwd(src)
        .arg(src.join("scripts/kconfig/merge_config.sh"))
        .args(["-m", "-Q", "-O"])
        .arg(&out)
        .arg(src.join(DEFCONFIG))
        .arg(ctx.paths.fragments().join(FRAGMENT))
        .args(extra);
    info!("kernel: merging config fragments");
    merge.run(ctx)?;

    info!("kernel: olddefconfig");
    make(ctx, src, &out, "olddefconfig").run(ctx)?;
    Ok(out.join(".config"))
}

/// Compile the EFI image.
fn build(ctx: &Ctx, src: &Path) -> Result<PathBuf> {
    let out = build_dir(ctx);
    info!("kernel: make {MAKE_TARGET} -j{} LLVM=1", ctx.jobs);
    make(ctx, src, &out, MAKE_TARGET).run(ctx)?;
    let image = out.join(KERNEL_IMAGE);
    ensure!(
        image.is_file(),
        "build finished but {} is missing",
        image.display()
    );
    Ok(image)
}

/// A `make` invocation with the reproducibility knobs fixed.
fn make(ctx: &Ctx, src: &Path, out: &Path, target: &str) -> Cmd {
    let mut c = Cmd::new("make", format!("kernel-{target}"));
    c.arg("-C")
        .arg(src)
        .arg(format!("O={}", out.display()))
        .arg("LLVM=1")
        .arg(format!("ARCH={KERNEL_ARCH}"))
        .arg(format!("-j{}", ctx.jobs))
        .arg("KBUILD_BUILD_USER=qs400")
        .arg("KBUILD_BUILD_HOST=qs400")
        .arg("KBUILD_BUILD_VERSION=1")
        .arg(format!("KBUILD_BUILD_TIMESTAMP={BUILD_TIMESTAMP}"))
        .arg(target)
        .env("SOURCE_DATE_EPOCH", SOURCE_DATE_EPOCH)
        .env("KCONFIG_NOTIMESTAMP", "1");
    c
}
