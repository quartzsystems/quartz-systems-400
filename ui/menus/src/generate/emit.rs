//! The UIM source of one menu panel group.

use std::fmt::Write as _;

/// A menu to write.
pub struct Panel<'a> {
    /// The menu, panel and panel-group name.
    pub name: &'a str,
    /// The title.
    pub title: &'a str,
    /// A `System:` line under the title.
    pub sysname: bool,
    /// `F13=Information Assistant`.
    pub info_key: bool,
    /// F16's action and key text.
    pub f16: (&'a str, &'a str),
    /// A `:MENUGRP.` heading over the items.
    pub group: Option<&'a str>,
    /// `(option, text, action, help)`; an empty text is a blank row.
    pub items: Vec<(u16, String, String, Option<ItemHelp>)>,
    /// The help module's paragraphs.
    pub help: Vec<String>,
}

/// The help of one menu item.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ItemHelp {
    /// A module of another group: a command's help.
    Import {
        /// The module.
        module: String,
        /// Its panel group.
        group: String,
    },
    /// A module of this group, written from the item.
    Text {
        /// Its title.
        title: String,
        /// Its text.
        text: String,
    },
}

/// The help of the menus' function keys.
fn keys_help(p: &Panel<'_>) -> String {
    let mut s = String::from(":HELP NAME=HLPKEYS.Function keys\n:PARML.\n");
    let mut keys = vec![
        (
            "F1=Help",
            "Shows help for the item the cursor is on; on the title, help for the whole menu.",
        ),
        (
            "F3=Exit",
            "Leaves the menu and the menus it was reached from.",
        ),
        (
            "F4=Prompt",
            "Prompts the command on the command line, or the command of the option typed.",
        ),
        (
            "F9=Retrieve",
            "Puts the last command run back on the command line; press it again for the one before.",
        ),
        ("F12=Cancel", "Returns to the previous menu."),
    ];
    if p.info_key {
        keys.push((
            "F13=Information Assistant",
            "Shows the Information Assistant menu.",
        ));
    }
    keys.push((p.f16.1, "Shows that menu."));
    for (k, t) in keys {
        let _ = writeln!(s, ":PT.{}\n:PD.{}", escape(k), escape(t));
    }
    s.push_str(":EPARML.\n:EHELP.\n");
    s
}

/// Text as UIM reads it: a colon before a letter would start a tag,
/// an ampersand a symbol.
#[must_use]
pub fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let chars: Vec<char> = text.chars().collect();
    for (i, c) in chars.iter().enumerate() {
        match c {
            '&' => out.push_str("&amp."),
            ':' if chars.get(i + 1).is_some_and(char::is_ascii_alphabetic) => {
                out.push_str("&colon.");
            }
            c => out.push(*c),
        }
    }
    out
}

/// A `MENUI` text: the item's text, two blanks, the name shown at
/// column 70.
#[must_use]
pub fn item_text(text: &str, name: &str) -> String {
    format!("{}  {name}", escape(text))
}

/// The source.
#[must_use]
pub fn source(p: &Panel<'_>) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        ".* Copyright (C), 2026 Quartz Systems. Some rights reserved. This work is\n\
         .* licensed under the terms of the MIT license which can be found in the\n\
         .* root directory of this project.\n\
         .*\n\
         .* {}: {}. Generated by genmenus from the inventories; do not edit.",
        p.name, p.title
    );
    s.push_str(":PNLGRP.\n");
    s.push_str(":COPYR.(C) Copyright Quartz Systems 2026.\n");
    s.push_str(":CLASS NAME=OPTCL BASETYPE='CHAR 3'.\n:ECLASS.\n");
    s.push_str(":CLASS NAME=NAMECL BASETYPE='CHAR 10'.\n:ECLASS.\n");
    s.push_str(":VAR NAME=OPTION CLASS=OPTCL.\n");
    let _ = writeln!(s, ":VAR NAME=PANELID CLASS=NAMECL VALUE='{}'.", p.name);
    let mut imported = std::collections::BTreeSet::new();
    for (_, text, _, h) in &p.items {
        if let (false, Some(ItemHelp::Import { module, group })) = (text.is_empty(), h)
            && imported.insert(module.clone())
        {
            let _ = writeln!(s, ":IMPORT NAME={module} PNLGRP={group}.");
        }
    }
    s.push_str(":KEYL NAME=MENUKEYS HELP=HLPKEYS.\n");
    s.push_str(":KEYI KEY=ENTER ACTION=ENTER.\n");
    s.push_str(":KEYI KEY=HELP ACTION=HELP.\n");
    s.push_str(":KEYI KEY=F1 ACTION=HELP.\n");
    s.push_str(":KEYI KEY=F3 ACTION=EXIT.F3=Exit\n");
    s.push_str(":KEYI KEY=F4 ACTION='RETURN 4'.F4=Prompt\n");
    s.push_str(":KEYI KEY=F9 ACTION=RETRIEVE.F9=Retrieve\n");
    s.push_str(":KEYI KEY=F12 ACTION=CANCEL.F12=Cancel\n");
    if p.info_key {
        s.push_str(":KEYI KEY=F13 ACTION='MENU INFO'.F13=Information Assistant\n");
    }
    let _ = writeln!(s, ":KEYI KEY=F16 ACTION='{}'.{}", p.f16.0, p.f16.1);
    s.push_str(":EKEYL.\n");
    let topsep = if p.sysname { " TOPSEP=SYSNAM" } else { "" };
    let _ = writeln!(
        s,
        ":PANEL NAME={n} HELP=HLP{n} KEYL=MENUKEYS ENTER='RETURN 1'{topsep} PANELID=PANELID.{t}",
        n = p.name,
        t = escape(p.title)
    );
    s.push_str(":MENU DEPTH='*' SCROLL=YES OPTIONS=OPTION.Select one of the following:\n");
    if let Some(g) = p.group {
        let _ = writeln!(s, ":MENUGRP.{}", escape(g));
    }
    for (option, text, action, h) in &p.items {
        let help = match (text.is_empty(), h) {
            (false, Some(ItemHelp::Import { module, .. })) => format!(" HELP={module}"),
            (false, Some(ItemHelp::Text { .. })) => format!(" HELP=HLPOPT{option}"),
            _ => String::new(),
        };
        let _ = writeln!(s, ":MENUI OPTION={option} ACTION='{action}'{help}.{text}");
    }
    if p.group.is_some() {
        s.push_str(":EMENUGRP.\n");
    }
    s.push_str(":EMENU.\n");
    s.push_str(":CMDLINE SIZE=LONG.Selection or command\n");
    s.push_str(":EPANEL.\n");
    let _ = writeln!(s, ":HELP NAME=HLP{}.{} - Help", p.name, escape(p.title));
    for para in &p.help {
        let _ = writeln!(s, ":P.{}", escape(para));
    }
    s.push_str(":EHELP.\n");
    s.push_str(&keys_help(p));
    for (option, text, _, h) in &p.items {
        if let (false, Some(ItemHelp::Text { title, text: t })) = (text.is_empty(), h) {
            let _ = writeln!(
                s,
                ":HELP NAME=HLPOPT{option}.{}\n:P.{}\n:EHELP.",
                escape(title),
                escape(t)
            );
        }
    }
    s.push_str(":EPNLGRP.\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes() {
        assert_eq!(escape("C++ Commands"), "C++ Commands");
        assert_eq!(escape("Note:x"), "Note&colon.x");
        assert_eq!(escape("Note: x"), "Note: x");
        assert_eq!(escape("A & B"), "A &amp. B");
        assert_eq!(item_text("Change Job", "CHGJOB"), "Change Job  CHGJOB");
    }

    #[test]
    fn shape() {
        let p = Panel {
            name: "CMDX",
            title: "X Commands",
            sysname: true,
            info_key: true,
            f16: ("MENU MAIN", "F16=System main menu"),
            group: Some("Commands"),
            items: vec![
                (
                    1,
                    "A  CMDA".into(),
                    "CMD ?CMDA".into(),
                    Some(ItemHelp::Import {
                        module: "CMDA".into(),
                        group: "QHX".into(),
                    }),
                ),
                (2, String::new(), "CMD ?B".into(), None),
            ],
            help: vec!["Help.".into()],
        };
        let s = source(&p);
        assert!(s.contains(":PANEL NAME=CMDX HELP=HLPCMDX KEYL=MENUKEYS ENTER='RETURN 1' TOPSEP=SYSNAM PANELID=PANELID.X Commands\n"));
        assert!(s.contains(":MENUI OPTION=2 ACTION='CMD ?B'.\n"));
        assert!(s.contains("F13=Information Assistant"));
        assert!(s.ends_with(":EHELP.\n:EPNLGRP.\n"));
        assert!(s.contains(":IMPORT NAME=CMDA PNLGRP=QHX.\n"));
        assert!(s.contains(":MENUI OPTION=1 ACTION='CMD ?CMDA' HELP=CMDA.A  CMDA\n"));
        assert!(s.contains(":KEYL NAME=MENUKEYS HELP=HLPKEYS.\n"));
    }
}
