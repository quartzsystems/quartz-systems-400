//! The options and the layout: logical lines to 80-character records.

use super::super::super::super::SqlContext;
use super::super::Args;
use crate::error::{Result, SqlError};

/// The options that change what is generated.
#[derive(Clone, Debug)]
#[allow(clippy::struct_excessive_bools)]
pub struct Options {
    /// `STATEMENT_FORMATTING_OPTION`: tabs and line feeds.
    pub formatted: bool,
    /// `DROP_OPTION`.
    pub drop: bool,
    /// `HEADER_OPTION`.
    pub header: bool,
    /// `LABEL_OPTION`.
    pub labels: bool,
    /// `CONSTRAINT_OPTION`.
    pub constraints: bool,
    /// `SYSTEM_NAME_OPTION`: `RCDFMT` and `FOR SYSTEM NAME`.
    pub system_names: bool,
    /// `PRIVILEGES_OPTION`.
    pub privileges: bool,
    /// `CCSID_OPTION`.
    pub ccsids: bool,
    /// `CREATE_OR_REPLACE_OPTION`.
    pub or_replace: bool,
    /// `QUALIFIED_NAME_OPTION` `1`: names left unqualified.
    pub unqualified: bool,
}

/// A `CHAR(1)` option: `'0'` or `'1'`.
fn flag(args: &Args, name: &str) -> Result<bool> {
    match args.word(name).as_deref() {
        Some("1") => Ok(true),
        Some("0") | None => Ok(false),
        Some(v) => Err(SqlError::Coded {
            code: -443,
            state: "22023",
            what: format!("{name} {v}: 0 or 1"),
        }),
    }
}

impl Options {
    /// The options of a call. Options that change only what QS/400
    /// cannot vary are checked and refused when set otherwise.
    pub fn of(args: &Args) -> Result<Self> {
        // BLOCKED(rel): the standards, obfuscation, temporal, additional
        // index and index-instead-of-view forms are not generated.
        for (name, shipped) in [
            ("STANDARDS_OPTION", "0"),
            ("OBFUSCATE_OPTION", "0"),
            ("ADDITIONAL_INDEX_OPTION", "0"),
            ("INDEX_INSTEAD_OF_VIEW_OPTION", "0"),
            ("TEMPORAL_OPTION", "0"),
        ] {
            if args.word(name).is_some_and(|v| v != shipped) {
                return Err(SqlError::Coded {
                    code: -84,
                    state: "42612",
                    what: format!("GENERATE_SQL {name} other than {shipped} is not supported"),
                });
            }
        }
        if args
            .text("SOURCE_STREAM_FILE")
            .is_some_and(|s| !s.trim().is_empty())
        {
            return Err(SqlError::Coded {
                code: -84,
                state: "42612",
                what: "GENERATE_SQL SOURCE_STREAM_FILE is not supported".into(),
            });
        }
        flag(args, "COMMENT_OPTION")?;
        // The date, time, naming and decimal point options change only
        // the literals of a view's text, which is kept as given.
        Ok(Self {
            formatted: flag(args, "STATEMENT_FORMATTING_OPTION")?,
            drop: flag(args, "DROP_OPTION")?,
            header: flag(args, "HEADER_OPTION")?,
            // COMMENT_OPTION: QS/400 keeps a comment as the label, so
            // there is never a COMMENT ON to generate.
            labels: flag(args, "LABEL_OPTION")?,
            constraints: flag(args, "CONSTRAINT_OPTION")?,
            system_names: flag(args, "SYSTEM_NAME_OPTION")?,
            privileges: flag(args, "PRIVILEGES_OPTION")?,
            ccsids: flag(args, "CCSID_OPTION")?,
            or_replace: flag(args, "CREATE_OR_REPLACE_OPTION")?,
            unqualified: flag(args, "QUALIFIED_NAME_OPTION")?,
        })
    }
}

/// A logical line: its indent and text (without the trailing blank).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Line {
    /// A line of a statement; `true` when indented.
    Text(bool, String),
    /// The blank line after a statement.
    Blank,
    /// An empty clause line (where IBM writes a clause QS/400 never
    /// has): kept when formatted, dropped otherwise.
    Empty,
}

impl Line {
    /// A line at the left.
    pub fn top(s: impl Into<String>) -> Self {
        Self::Text(false, s.into())
    }

    /// An indented line.
    pub fn tab(s: impl Into<String>) -> Self {
        Self::Text(true, s.into())
    }

    /// The blank after a statement.
    #[must_use]
    pub fn blank() -> Self {
        Self::Blank
    }
}

/// Our header: what generated the SQL, from where, when.
pub fn header(ctx: &SqlContext) -> Vec<Line> {
    let ts = crate::value::Timestamp::new(
        db::record::datetime::Date::from_unix(ctx.clock()),
        db::record::datetime::Time::from_unix(ctx.clock()),
        0,
    );
    vec![
        Line::top("-- SQL generated by QSYS2.GENERATE_SQL on QS/400"),
        Line::top(format!(
            "-- Created: {}",
            ts.render_field().get(..19).unwrap_or_default()
        )),
        Line::top(format!("-- By user: {}", ctx.user)),
        Line::blank(),
    ]
}

/// The records of `lines`: 80 characters each. Formatted, a line ends
/// in a blank and a line feed, an indent is a tab, and a line too long
/// for one record goes on in the next after a tab; unformatted, an
/// indent is two blanks and nothing ends a line.
pub fn records(lines: &[Line], formatted: bool) -> Vec<String> {
    const WIDTH: usize = 80;
    let mut out = Vec::new();
    for l in lines {
        let text = match (l, formatted) {
            (Line::Text(indent, s), true) => format!("{}{s} \n", if *indent { "\t" } else { "" }),
            (Line::Text(indent, s), false) => format!("{}{s}", if *indent { "  " } else { "" }),
            (Line::Blank, true) => "  \n".to_string(),
            (Line::Blank, false) => String::new(),
            (Line::Empty, true) => "\t  \n".to_string(),
            (Line::Empty, false) => continue,
        };
        let mut rest: Vec<char> = text.chars().collect();
        loop {
            if rest.len() <= WIDTH {
                out.push(rest.iter().collect());
                break;
            }
            out.push(rest[..WIDTH].iter().collect());
            let tail = rest.split_off(WIDTH);
            rest = std::iter::once(if formatted { '\t' } else { ' ' })
                .chain(tail)
                .collect();
        }
    }
    out
}

/// A name, quoted when it needs to be.
#[must_use]
pub fn ident(name: &str) -> String {
    let plain = name
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_uppercase() || "$#@".contains(c))
        && name
            .chars()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || "_$#@".contains(c));
    if plain {
        name.to_string()
    } else {
        format!("\"{}\"", name.replace('"', "\"\""))
    }
}

/// A string literal.
#[must_use]
pub fn literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_long_line_goes_on_after_a_tab() {
        let long = format!("CONSTRAINT {} )  ", "X".repeat(65));
        let r = records(&[Line::tab(long), Line::Empty], true);
        assert_eq!(r.len(), 3);
        assert_eq!(r[0].chars().count(), 80);
        assert_eq!(r[1], "\t  \n");
        assert_eq!(r[2], "\t  \n");
    }

    #[test]
    fn unformatted_has_no_tabs_or_feeds() {
        let r = records(
            &[
                Line::top("CREATE X ("),
                Line::tab("A INT )"),
                Line::Empty,
                Line::blank(),
            ],
            false,
        );
        assert_eq!(
            r,
            vec!["CREATE X (".to_string(), "  A INT )".into(), String::new()]
        );
    }
}
