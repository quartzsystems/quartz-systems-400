//! The columns of `QAQQDBMN`, the database monitor's output file, in
//! order: names, types and lengths as the primary's `QSYS/QAQQDBMN`
//! has them (`tools/conformance/oracle/sql-admin/qaqqdbmn-columns.txt`).

/// A column's type.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Ty {
    /// `DECIMAL(15, 0)`.
    Dec15,
    /// `TIMESTAMP`.
    Timestamp,
    /// `CHAR(n)`.
    Char(u16),
    /// `VARCHAR(n)`.
    VarChar(u16),
    /// `INTEGER`.
    Int,
    /// `SMALLINT`.
    SmallInt,
    /// `CLOB(2G)`.
    Clob,
    /// `DBCLOB(1G)`.
    DbClob,
    /// `BLOB(2G)`.
    Blob,
}

impl Ty {
    /// The type as `CREATE TABLE` spells it.
    #[must_use]
    pub fn sql(self) -> String {
        match self {
            Self::Dec15 => "DECIMAL(15, 0)".into(),
            Self::Timestamp => "TIMESTAMP".into(),
            Self::Char(n) => format!("CHAR({n})"),
            Self::VarChar(n) => format!("VARCHAR({n})"),
            Self::Int => "INTEGER".into(),
            Self::SmallInt => "SMALLINT".into(),
            Self::Clob => "CLOB(2G)".into(),
            Self::DbClob => "DBCLOB(1073741823)".into(),
            Self::Blob => "BLOB(2G)".into(),
        }
    }
}

