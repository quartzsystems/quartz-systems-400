//! The oracle's source: an ILE RPG program and the DDS of its input
//! and output files, generated from the same tables as the cases.

use std::fmt::Write as _;

use super::{EDIT_CODES, EDIT_SHAPES, FillKind, SHAPES, WORDS};

/// `QDFUZZIN`: the cases.
#[must_use]
pub fn dds_in() -> String {
    dds(
        "QDFUZZINR",
        &[
            ("IID", "9S 0"),
            ("OP", "2A"),
            ("SA", "2S 0"),
            ("A", "70A"),
            ("SB", "2S 0"),
            ("B", "70A"),
        ],
    )
}

/// `QDFUZZOUT`: the rows.
#[must_use]
pub fn dds_out() -> String {
    dds(
        "QDFUZZOUTR",
        &[
            ("OID", "9S 0"),
            ("INTER", "80A"),
            ("R1T", "80A"),
            ("RHT", "80A"),
            ("RRT", "80A"),
        ],
    )
}

/// A one-format PF in DDS columns: name at 19, length right-aligned to
/// 34, type at 35, decimals at 37.
fn dds(format: &str, fields: &[(&str, &str)]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "     A          R {format}");
    for (name, spec) in fields {
        let (len, rest) =
            spec.split_at(spec.find(|c: char| c.is_ascii_alphabetic()).expect("type"));
        let line = format!("     A            {name:<10}{len:>6}{rest}");
        let _ = writeln!(out, "{}", line.trim_end());
    }
    out
}

/// A `monitor` block: `body` lines, and on any error the status token
/// in `target`. One statement per line keeps every line short enough
/// for a 112-byte source member.
fn monitor(s: &mut String, indent: usize, body: &[String], target: &str) {
    let pad = " ".repeat(indent);
    let _ = writeln!(s, "{pad}monitor;");
    for line in body {
        let _ = writeln!(s, "{pad}  {line}");
    }
    let _ = writeln!(s, "{pad}on-error;");
    let _ = writeln!(s, "{pad}  {target} = 'E' + %editc(%status : 'X');");
    let _ = writeln!(s, "{pad}endmon;");
}

/// `QDFUZZ.RPGLE`.
#[must_use]
pub fn rpg_source() -> String {
    let mut s = String::new();
    s.push_str("**free\n");
    s.push_str("// QDFUZZ: the qdecimal oracle. Generated by `qdfuzz rpg`; do not edit.\n");
    s.push_str(
        "// Reads QDFUZZIN, computes every case with the machine's rules, writes QDFUZZOUT.\n",
    );
    s.push_str(
        "ctl-opt dftactgrp(*no) actgrp(*new) option(*srcstmt : *nodebugio) datedit(*mdy);\n\n",
    );
    s.push_str("dcl-f qdfuzzin usage(*input);\n");
    s.push_str("dcl-f qdfuzzout usage(*output);\n\n");
    s.push_str("dcl-s r1 packed(15 : 5);\n");
    s.push_str("dcl-s rh packed(15 : 5);\n");
    s.push_str("dcl-s rr packed(15 : 5);\n");
    for (i, (d, sc)) in SHAPES.iter().enumerate() {
        let _ = writeln!(s, "dcl-s a{i} packed({d} : {sc});");
        let _ = writeln!(s, "dcl-s b{i} packed({d} : {sc});");
    }
    s.push('\n');
    s.push_str("read qdfuzzin;\n");
    s.push_str("dow not %eof(qdfuzzin);\n");
    s.push_str("  oid = iid;\n");
    // One statement per line: the machine's compiler wants the rest blank.
    for v in ["inter", "r1t", "rht", "rrt"] {
        let _ = writeln!(s, "  {v} = '';");
    }
    s.push_str("  monitor;\n");
    s.push_str("    select;\n");
    arithmetic(&mut s);
    edits(&mut s);
    s.push_str("    other;\n");
    s.push_str("      inter = 'UNKNOWN';\n");
    s.push_str("    endsl;\n");
    s.push_str("  on-error;\n");
    s.push_str("    inter = 'E' + %editc(%status : 'X');\n");
    s.push_str("  endmon;\n");
    s.push_str("  write qdfuzzoutr;\n");
    s.push_str("  read qdfuzzin;\n");
    s.push_str("enddo;\n");
    s.push_str("*inlr = *on;\n");
    s
}

/// One `when` per shape pair and operation.
fn arithmetic(s: &mut String) {
    for (i, (da, sa)) in SHAPES.iter().enumerate() {
        for (j, (db, sb)) in SHAPES.iter().enumerate() {
            for op in ['+', '-', '*', '/'] {
                let _ = writeln!(s, "    when op = '{op}' and sa = {i} and sb = {j};");
                let _ = writeln!(s, "      a{i} = %dec(a : {da} : {sa});");
                let _ = writeln!(s, "      b{j} = %dec(b : {db} : {sb});");
                let expr = format!("a{i} {op} b{j}");
                monitor(s, 6, &[format!("inter = %char({expr});")], "inter");
                monitor(
                    s,
                    6,
                    &[format!("r1 = {expr};"), "r1t = %char(r1);".to_string()],
                    "r1t",
                );
                monitor(
                    s,
                    6,
                    &[
                        format!("eval(h) rh = {expr};"),
                        "rht = %char(rh);".to_string(),
                    ],
                    "rht",
                );
                monitor(
                    s,
                    6,
                    &[
                        format!("eval(r) rr = {expr};"),
                        "rrt = %char(rr);".to_string(),
                    ],
                    "rrt",
                );
            }
        }
    }
}

/// One `when` per edit code, fill and shape, and per edit word.
fn edits(s: &mut String) {
    for &i in &EDIT_SHAPES {
        let (d, sc) = SHAPES[i];
        for code in EDIT_CODES.chars() {
            if code == 'Y' && !matches!(SHAPES[i], (3..=9, 0)) {
                continue;
            }
            let fills: &[(FillKind, &str)] = if "XYZ".contains(code) {
                &[(FillKind::Blank, "")]
            } else {
                &[
                    (FillKind::Blank, ""),
                    (FillKind::Asterisk, " : *astfill"),
                    (FillKind::Currency, " : *cursym"),
                ]
            };
            for (fill, parm) in fills {
                let _ = writeln!(
                    s,
                    "    when op = 'E' and sa = {i} and b = '{code}{}';",
                    fill.suffix()
                );
                let _ = writeln!(s, "      a{i} = %dec(a : {d} : {sc});");
                let _ = writeln!(
                    s,
                    "      inter = '[' + %editc(a{i} : '{code}'{parm}) + ']';"
                );
            }
        }
    }
    for (w, (i, word)) in WORDS.iter().enumerate() {
        let (d, sc) = SHAPES[*i];
        let _ = writeln!(s, "    when op = 'W' and sa = {i} and b = '{w}';");
        let _ = writeln!(s, "      a{i} = %dec(a : {d} : {sc});");
        let _ = writeln!(s, "      inter = '[' + %editw(a{i} : '{word}') + ']';");
    }
}

/// The procedure for the person at the machine.
#[must_use]
pub fn readme() -> String {
    "# qdecimal oracle

The files here let a real IBM i answer the same cases QS/400 computes,
so the two can be compared digit for digit. Everything but
`results.csv` is generated by `cargo run -p qdecimal --bin qdfuzz`:

- `cases.csv`: the cases, `id,op,shape-a,a,shape-b,b`. Shapes index the
  table in `qdecimal/src/fuzz/mod.rs`; `op` is `+ - * /`, `E` (edit
  code in `b`, with `*` for `*ASTFILL` or `$` for `*CURSYM`) or `W`
  (edit word index in `b`).
- `QDFUZZIN.PF`, `QDFUZZOUT.PF`: DDS of the input and output files.
- `QDFUZZ.RPGLE`: the program. One `when` per shape pair and operation,
  so every operand has the declared precision the case names.
- `expected.csv`: what QS/400 computes, for reading alongside.

On the machine, in a library of your choice (here `QDFUZZ`):

```
CRTLIB QDFUZZ
CRTSRCPF QDFUZZ/QDDSSRC RCDLEN(112)
CRTSRCPF QDFUZZ/QRPGLESRC RCDLEN(112)
```

Upload `QDFUZZIN.PF` and `QDFUZZOUT.PF` as members of `QDDSSRC` (type
PF) and `QDFUZZ.RPGLE` as member `QDFUZZ` of `QRPGLESRC` (type RPGLE),
then:

```
CRTPF FILE(QDFUZZ/QDFUZZIN) SRCFILE(QDFUZZ/QDDSSRC)
CRTPF FILE(QDFUZZ/QDFUZZOUT) SRCFILE(QDFUZZ/QDDSSRC) SIZE(*NOMAX)
CRTBNDRPG PGM(QDFUZZ/QDFUZZ) SRCFILE(QDFUZZ/QRPGLESRC)
```

Put `cases.csv` in the IFS (for example `/home/you/cases.csv`) and load,
run, unload:

```
CPYFRMIMPF FROMSTMF('/home/you/cases.csv') TOFILE(QDFUZZ/QDFUZZIN)
           MBROPT(*REPLACE) RCDDLM(*ALL) STRDLM('\"') FLDDLM(',')
CALL QDFUZZ/QDFUZZ
CPYTOIMPF FROMFILE(QDFUZZ/QDFUZZOUT) TOSTMF('/home/you/results.csv')
          STMFCODPAG(*PCASCII) RCDDLM(*CRLF) STRDLM('\"') FLDDLM(',')
          RMVBLANK(*TRAILING)
```

Copy `results.csv` next to this file and run

```
cargo test -p qdecimal --test oracle
cargo run -p qdecimal --bin qdfuzz -- diff conformance/oracle/qdecimal/cases.csv conformance/oracle/qdecimal/results.csv
```

The test is skipped while `results.csv` is absent. A mismatch names the
case, the field (`inter` is `%CHAR` of the intermediate result or the
edited text in brackets, `r1` the result in a 15,5 field, `rh` with
half-adjust, `rr` under `EVAL(R)`), our value and the machine's. Error
tokens are `E` and the RPG status code (`E00103` size error, `E00102`
division by zero).

## Captured 2026-10-22 on pub400.com (IBM i 7.5)

`results.csv` came from pub400 (job CCSID 273). `CRTBNDRPG` needed
`GENLVL(20)`: three edit-word cases (statements 7155, 7176 and 7179)
draw `RNF8004`, not enough replaceable characters, and compile anyway.
`cargo test -p qdecimal --test oracle` reports 590 mismatches, 584 in
`inter` (the `%CHAR` of the intermediate result, mostly fewer decimal
positions than this implementation keeps) and 6 in `rr`.
"
    .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sources_have_the_expected_shape() {
        let rpg = rpg_source();
        assert!(rpg.starts_with("**free\n"));
        assert!(rpg.contains("dcl-s a7 packed(63 : 32);"));
        assert!(rpg.contains("when op = '/' and sa = 3 and sb = 7;"));
        assert!(rpg.contains("        eval(r) rr = a3 / b7;\n        rrt = %char(rr);\n      on-error;\n        rrt = 'E' + %editc(%status : 'X');"));
        assert!(rpg.contains("when op = 'E' and sa = 1 and b = 'Y';"));
        assert!(!rpg.contains("when op = 'E' and sa = 0 and b = 'Y';"));
        assert!(rpg.contains("%editc(a0 : 'J' : *astfill)"));
        assert!(rpg.contains("%editw(a3 : ' ,   ,   ,  0.     ')"));
        assert!(rpg.ends_with("*inlr = *on;\n"));
        assert!(
            rpg.lines().all(|l| l.len() <= 100),
            "a line is too long for the source file"
        );
        let dds = dds_in();
        assert!(dds.contains("     A          R QDFUZZINR"));
        assert!(dds.contains("     A            IID            9S 0"));
        assert!(dds.contains("     A            A             70A"));
        assert!(dds_out().contains("     A            INTER         80A"));
        assert!(readme().contains("CPYFRMIMPF"));
    }
}
