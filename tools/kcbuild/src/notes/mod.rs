//! The release notes' generated blocks (`docs/RELEASE_NOTES_V1R1M0.md`):
//! the SQL refusal list imported from `docs/SQL.md` §10, and the marker
//! inventory of the tree. The prose around them is written by hand; the
//! blocks between their comment lines only by `kcbuild notes --update`.
//! The Knowledge Center build fails when either block is not what the
//! tree gives now, or when a marker of a form other than `BLOCKED(rel)`
//! and `NEEDS-CODY` is left (unless the legacy forms are allowed).

pub mod markers;

use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::Path;

/// The notes, relative to the tree.
pub const NOTES: &str = "docs/RELEASE_NOTES_V1R1M0.md";
/// The SQL document, relative to the tree.
pub const SQL: &str = "docs/SQL.md";
/// Allows the marker forms of before the rename when set to `legacy`.
pub const MARKERS_ENV: &str = "QS400_MARKERS";

const SQL_BEGIN: &str = "<!-- sql-refused:begin: imported from docs/SQL.md section 10 by `cargo run -p kcbuild -- notes --update`; do not edit -->";
const SQL_END: &str = "<!-- sql-refused:end -->";
const INV_BEGIN: &str = "<!-- inventory:begin: generated by `cargo run -p kcbuild -- notes --update`; do not edit -->";
const INV_END: &str = "<!-- inventory:end -->";

/// Whether markers of the old forms are allowed (`QS400_MARKERS=legacy`).
#[must_use]
pub fn legacy_from_env() -> bool {
    std::env::var(MARKERS_ENV).is_ok_and(|v| v == "legacy")
}

/// `SQL.md` §10's body: the lines after its heading, up to the next
/// `## ` heading.
pub fn sql_refused(sql: &str) -> Option<String> {
    let mut lines = sql.lines().skip_while(|l| !l.starts_with("## 10. "));
    lines.next()?;
    let body: Vec<&str> = lines.take_while(|l| !l.starts_with("## ")).collect();
    let text = body.join("\n");
    Some(format!("{}\n", text.trim_matches('\n')))
}

/// The inventory block's body for `found`.
#[must_use]
pub fn inventory(found: &[markers::Marker]) -> String {
    let mut s = format!("{} markers in the tree.\n\n| Marker | Where | Reason |\n|---|---|---|\n", found.len());
    for m in found {
        let _ = writeln!(s, "| `{}` | `{}:{}` | {} |", m.form, m.file, m.line, m.reason);
    }
    s
}

/// The text between `begin` and `end`, or `None` when they are missing.
fn block<'a>(notes: &'a str, begin: &str, end: &str) -> Option<&'a str> {
    let b = notes.find(begin)? + begin.len();
    let e = notes[b..].find(end)? + b;
    Some(notes[b..e].trim_start_matches(['\r', '\n']))
}

fn replace(notes: &str, begin: &str, end: &str, body: &str) -> Option<String> {
    let b = notes.find(begin)? + begin.len();
    let e = notes[b..].find(end)? + b;
    Some(format!("{}\n{body}{}", &notes[..b], &notes[e..]))
}

fn norm(s: &str) -> String {
    s.replace("\r\n", "\n")
}

/// What is wrong with the notes at `repo`: stale or missing blocks, and
/// markers of a form that does not survive the release.
pub fn problems(repo: &Path, legacy: bool) -> io::Result<Vec<String>> {
    let notes = norm(&fs::read_to_string(repo.join(NOTES))?);
    let sql = norm(&fs::read_to_string(repo.join(SQL))?);
    let mut out = Vec::new();
    let want_sql = sql_refused(&sql).unwrap_or_default();
    match block(&notes, SQL_BEGIN, SQL_END) {
        None => out.push(format!("{NOTES} has no SQL refusal block ({SQL_BEGIN} ... {SQL_END})")),
        Some(b) if b != want_sql => out.push(format!("{NOTES}: the SQL refusal list differs from {SQL} section 10")),
        Some(_) => {}
    }
    let found = markers::scan(repo);
    match block(&notes, INV_BEGIN, INV_END) {
        None => out.push(format!("{NOTES} has no marker inventory block ({INV_BEGIN} ... {INV_END})")),
        Some(b) if b != inventory(&found) => out.push(format!("{NOTES}: the marker inventory differs from the tree")),
        Some(_) => {}
    }
    if !legacy {
        for m in found.iter().filter(|m| !m.released()) {
            out.push(format!("{}:{}: {} (only BLOCKED(rel) and NEEDS-CODY survive the release)", m.file, m.line, m.form));
        }
    }
    Ok(out)
}

/// Rewrite both blocks from the tree. Returns how many markers it found.
pub fn update(repo: &Path) -> io::Result<usize> {
    let path = repo.join(NOTES);
    let notes = norm(&fs::read_to_string(&path)?);
    let sql = norm(&fs::read_to_string(repo.join(SQL))?);
    let missing = |what: &str| io::Error::new(io::ErrorKind::InvalidData, format!("{NOTES} has no {what} block markers"));
    let found = markers::scan(repo);
    let notes = replace(&notes, SQL_BEGIN, SQL_END, &sql_refused(&sql).unwrap_or_default()).ok_or_else(|| missing("SQL refusal"))?;
    let notes = replace(&notes, INV_BEGIN, INV_END, &inventory(&found)).ok_or_else(|| missing("inventory"))?;
    fs::write(&path, notes)?;
    Ok(found.len())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn blocks_round_trip() {
        let n = format!("# Notes\n\nprose\n\n{SQL_BEGIN}\nold\n{SQL_END}\n\nmore\n\n{INV_BEGIN}\n{INV_END}\n");
        let n2 = replace(&n, SQL_BEGIN, SQL_END, "- a\n").unwrap();
        assert_eq!(block(&n2, SQL_BEGIN, SQL_END), Some("- a\n"));
        assert!(n2.contains("prose") && n2.contains("more"));
        assert!(block("nothing", INV_BEGIN, INV_END).is_none());
        let sql = "## 9. x\nno\n## 10. Refused\n\nintro\n\n### 2. S\n\n- r\n\n## 11. B\nno\n";
        assert_eq!(sql_refused(sql).unwrap(), "intro\n\n### 2. S\n\n- r\n");
    }
}
