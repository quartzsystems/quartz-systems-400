//! The release notes' generated blocks over a small tree: stale blocks
//! and old marker forms are found, `update` makes them current, and
//! after the rename to `BLOCKED(rel)` the strict check passes.

use std::fs;
use std::path::PathBuf;

use kcbuild::notes;

fn tree(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("kcnotes-{tag}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(dir.join("docs")).unwrap();
    fs::create_dir_all(dir.join("src")).unwrap();
    fs::write(
        dir.join("docs/RELEASE_NOTES_V1R1M0.md"),
        "# Notes\n\nProse the lead writes.\n\n\
         <!-- sql-refused:begin: imported from docs/SQL.md section 10 by `cargo run -p kcbuild -- notes --update`; do not edit -->\n\
         <!-- sql-refused:end -->\n\n\
         <!-- inventory:begin: generated by `cargo run -p kcbuild -- notes --update`; do not edit -->\n\
         <!-- inventory:end -->\n",
    )
    .unwrap();
    fs::write(
        dir.join("docs/SQL.md"),
        "# SQL\n\n## 10. Refused\n\n- `LOCK TABLE`: refused SQL0084\n\n## 11. Benchmarks\n",
    )
    .unwrap();
    fs::write(
        dir.join("src/a.rs"),
        "// BLOCKED(sql): the old form\nfn a() {}\n// NEEDS-CODY: hardware\n",
    )
    .unwrap();
    dir
}

#[test]
fn stale_then_current_then_strict() {
    let dir = tree("flow");
    let p = notes::problems(&dir, true).unwrap();
    assert_eq!(p.len(), 2, "{p:?}");
    assert_eq!(notes::update(&dir).unwrap(), 2);
    assert!(notes::problems(&dir, true).unwrap().is_empty());
    let text = fs::read_to_string(dir.join(notes::NOTES)).unwrap();
    assert!(text.contains("Prose the lead writes."));
    assert!(text.contains("- `LOCK TABLE`: refused SQL0084"));
    assert!(text.contains("| `BLOCKED(sql)` | `src/a.rs:1` | the old form |"));
    assert!(text.contains("| `NEEDS-CODY` | `src/a.rs:3` | hardware |"));
    // Strict: the old form fails.
    let strict = notes::problems(&dir, false).unwrap();
    assert_eq!(
        strict,
        ["src/a.rs:1: BLOCKED(sql) (only BLOCKED(rel) and NEEDS-CODY survive the release)"]
    );
    // The rename makes the inventory stale until it is regenerated.
    fs::write(
        dir.join("src/a.rs"),
        "// BLOCKED(rel): the old form\nfn a() {}\n// NEEDS-CODY: hardware\n",
    )
    .unwrap();
    assert_eq!(notes::problems(&dir, false).unwrap().len(), 1);
    notes::update(&dir).unwrap();
    assert!(notes::problems(&dir, false).unwrap().is_empty());
    // SQL.md §10 changing makes the imported list stale.
    fs::write(dir.join("docs/SQL.md"), "## 10. Refused\n\n- other\n").unwrap();
    assert_eq!(notes::problems(&dir, false).unwrap().len(), 1);
    let out = dir.join("kc");
    assert!(kcbuild::build_checked(&dir, &out, false).is_err());
    let _ = fs::remove_dir_all(&dir);
}
