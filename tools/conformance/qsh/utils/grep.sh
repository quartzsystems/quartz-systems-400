# grep, egrep, fgrep: options, BRE and ERE, statuses, messages.

probe word 'grep an data/fruits.txt'
probe none 'grep zzz data/fruits.txt'
probe invert 'grep -v an data/fruits.txt'
probe count 'grep -c a data/fruits.txt'
probe count-none 'grep -c zzz data/fruits.txt'
probe icase 'grep -i apple data/mixed.txt'
probe numbers 'grep -n e data/fruits.txt'
probe list 'grep -l the data/words.txt data/fruits.txt data/people.txt'
probe quiet 'grep -q cherry data/fruits.txt; echo $?'
probe whole 'grep -x apple data/mixed.txt'
probe names 'grep a data/fruits.txt data/csv.txt'
probe no-names 'grep -h a data/fruits.txt data/csv.txt'
probe with-name 'grep -H cherry data/fruits.txt'
probe patterns 'grep -e apple -e cherry data/fruits.txt'
probe pattern-file 'printf "ban\nche\n" > pats; grep -f pats data/fruits.txt'
probe missing 'grep a data/nosuch data/fruits.txt'
probe silent 'grep -s a data/nosuch data/fruits.txt'
probe quiet-error 'grep -q a data/nosuch data/fruits.txt; echo $?'
probe usage 'grep'
probe bad-option 'grep -Z a data/fruits.txt'
probe bad-pattern 'grep "a[" data/fruits.txt'
probe bad-ere 'grep -E "a(" data/fruits.txt'
probe bad-backref 'grep "\(a\)\2" data/fruits.txt'
probe bad-interval 'grep "a\{1" data/fruits.txt'
probe bre-plus 'echo "a+b" | grep "a+b"'
probe bre-interval 'printf "ab\naab\naaab\n" | grep -x "a\{2,\}b"'
probe bre-backref 'printf "abab\nabba\nxyxy\n" | grep "\(..\)\1"'
probe bre-star-start 'printf "*a\nb\n" | grep "*a"; printf "*a\na\n" | grep "^*a"'
probe bre-anchors-literal 'printf "a^b\na\$b\n" | grep "a^b"; printf "a\$b\n" | grep "a\$b"'
probe ere 'grep -E "apple|cherry" data/fruits.txt'
probe ere-braces 'echo "a{x" | grep -E "a{x"; echo "a{,2}" | grep -E "a{,2}"'
probe ere-star-start 'echo "*a" | grep -E "*a"'
probe egrep 'egrep "an|rr" data/fruits.txt'
probe fixed 'echo "a.c abc" | grep -F "a.c"; echo abc | grep -F "a.c"; echo $?'
probe fgrep 'printf "x*y\nxy\n" | fgrep "*"'
probe empty-pattern 'grep "" data/fruits.txt'
probe stdin-name 'echo hit | grep -l hit; echo hit | grep -H hit'
probe directory 'grep a data/sub'
probe icase-class 'printf "A\na\n" | grep -i "[[:lower:]]"'
probe member 'grep -c . /QSYS.LIB/QGPL.LIB/QCLSRC.FILE/QCLSRC.MBR'
finish
