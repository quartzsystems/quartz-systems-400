# ls: long format columns, total line, classify, /QSYS.LIB objects.

probe plain 'cd data; ls'
probe all 'cd data; ls -a'
probe almost-all 'cd data; ls -A'
probe long 'cd data; ls -l'
probe long-all 'cd data/sub; ls -la'
probe long-file 'ls -l data/fruits.txt'
probe long-link 'ls -l data/link'
probe long-follow 'ls -lL data/link'
probe long-dir 'ls -ld data/sub'
probe numeric 'ls -ln data/fruits.txt'
probe no-owner 'ls -lg data/fruits.txt'
probe no-group 'ls -lo data/fruits.txt'
probe old-date 'ls -l data/old.txt'
probe classify 'cd data; ls -F; ls -F ../bin'
probe classify-long 'ls -lF bin data/link'
probe slash 'cd data; ls -p'
probe columns 'cd data; ls -C'
probe across 'cd data; ls -x'
probe stream 'cd data; ls -m'
probe recursive 'ls -R data/sub'
probe time 'cd data; ls -t'
probe size-sort 'cd data; ls -S'
probe blocks 'cd data; ls -s'
probe blocks-k 'cd data; ls -sk'
probe inode 'ls -i data/fruits.txt'
probe missing 'ls data/nosuch'
probe missing-and-present 'ls data/nosuch data/fruits.txt'
probe bad-option 'ls -Z'
probe empty-dir 'mkdir e; ls -l e; ls -a e'
probe big-total 'ls -l /usr/bin | head -1'
probe root-total 'ls -la / | head -3'
probe qsys-lib 'ls /QSYS.LIB/QGPL.LIB | head -5'
probe qsys-lib-long 'ls -l /QSYS.LIB/QGPL.LIB | head -6'
probe qsys-lib-classify 'ls -F /QSYS.LIB/QGPL.LIB | head -5'
probe qsys-lib-file 'ls -l /QSYS.LIB/QSYS.LIB/QCLSRC.FILE 2>&1 | head -3'
probe qsys-lib-lower 'ls /qsys.lib/qgpl.lib | head -3'
probe qsys-lib-dir 'ls -ld /QSYS.LIB/QGPL.LIB'
probe qopensys 'ls -ld /QOpenSys /QOpenSys/usr'
finish
