SELECT ODOBNM, ODOBTP, ODOBAT, ODSDAT, ODSTIM, ODSCMD, ODSDEV, ODSFIL, ODSFLB, ODSSEQ, ODSVOL, ODSLBL, ODRDAT, ODRTIM, ODUDAT, ODCDAT, ODCTIM, ODLDAT, ODLTIM FROM QSTEST.ZZOBJD ORDER BY ODOBNM, ODOBTP
;;
