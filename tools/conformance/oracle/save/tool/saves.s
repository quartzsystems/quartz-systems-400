case 02-savlib Save the library to a save file
jobs
cl CHGJOB INQMSGRPY(*DFT)
cl CRTSAVF FILE(QSTEST/ZZFULL) TEXT('Save kit full save')
cl CRTSAVF FILE(QSTEST/ZZS1) TEXT('Save kit scratch save file')
note first save: nothing omitted, so the target save file and the tool's ZZ* files are in the saved library
cl SAVLIB LIB(QSTEST) DEV(*SAVF) SAVF(QSTEST/ZZS1)
splf dspsavf-batch DSPSAVF FILE(QSTEST/ZZS1)
splf dspsavf-print DSPSAVF FILE(QSTEST/ZZS1) OUTPUT(*PRINT)
note the saved library with the tool's files omitted; this save file is the one every restore case uses
cl SAVLIB LIB(QSTEST) DEV(*SAVF) SAVF(QSTEST/ZZFULL) OMITOBJ((QSTEST/ZZ*)) UPDHST(*YES)
splf dspsavf-full DSPSAVF FILE(QSTEST/ZZFULL) OUTPUT(*PRINT)
splf dspobjd-savf DSPOBJD OBJ(QSTEST/ZZFULL) OBJTYPE(*FILE) DETAIL(*FULL) OUTPUT(*PRINT)
splf dspfd-savf DSPFD FILE(QSTEST/ZZFULL) TYPE(*ATR) OUTPUT(*PRINT)
splf dspobjd-lib DSPOBJD OBJ(QSYS/QSTEST) OBJTYPE(*LIB) DETAIL(*FULL) OUTPUT(*PRINT)

