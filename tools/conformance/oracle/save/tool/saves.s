note the library itself: SAVLIB UPDHST(*YES) in 02 and UPDHST(*NO) in 03
splf lib-after DSPOBJD OBJ(QSYS/QSTEST) OBJTYPE(*LIB) DETAIL(*FULL) OUTPUT(*PRINT)

