cl SAVOBJ OBJ(DTAC) LIB(QSTEST) OBJTYPE(*DTAARA) DEV(*SAVF) SAVF(QSTEST/ZZS1) CLEAR(*ALL) UPDHST(*NO)
splf dtac-after-no DSPOBJD OBJ(QSTEST/DTAC) OBJTYPE(*DTAARA) DETAIL(*FULL) OUTPUT(*PRINT)
cl SAVOBJ OBJ(DTAC) LIB(QSTEST) OBJTYPE(*DTAARA) DEV(*SAVF) SAVF(QSTEST/ZZS1) CLEAR(*ALL) UPDHST(*YES)
splf dtac-after-yes DSPOBJD OBJ(QSTEST/DTAC) OBJTYPE(*DTAARA) DETAIL(*FULL) OUTPUT(*PRINT)
