SELECT TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE, LENGTH, NUMERIC_SCALE, IS_NULLABLE, CCSID FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA = 'QSYS2' AND TABLE_NAME IN ('SYSCOLUMNS', 'SYSTABLES', 'SYSINDEXES', 'SYSVIEWS', 'SYSSEQUENCES') ORDER BY TABLE_NAME, ORDINAL_POSITION;
