CREATE UNIQUE INDEX {lib}.P5_IXU ON {lib}.P5_T (D);
CREATE VIEW {lib}.P5_V AS SELECT ID, NAME FROM {lib}.P5_T WHERE ID > 0;
CREATE VIEW {lib}.P5_VG AS SELECT NAME, COUNT(*) AS N FROM {lib}.P5_T GROUP BY NAME;
CREATE VIEW {lib}.P5_VJ AS SELECT A.ID, B.NAME FROM {lib}.P5_T A JOIN {lib}.P5_T B ON A.ID = B.ID;
CREATE VIEW {lib}.P5_VE AS SELECT ID, NAME CONCAT 'x' AS NX FROM {lib}.P5_T;
CREATE ALIAS {lib}.P5_A FOR {lib}.P5_T;
