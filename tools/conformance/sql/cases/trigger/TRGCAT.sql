CREATE TRIGGER {lib}.TRG_D1 AFTER INSERT ON {lib}.TRG_T3 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW INSERT INTO {lib}.TRG_L3 VALUES ('ROW ' CONCAT N.NAME, (SELECT COUNT(*) FROM {lib}.TRG_T3));
CREATE TRIGGER {lib}.TRG_D2 BEFORE UPDATE OF AMT ON {lib}.TRG_T3 REFERENCING OLD AS O NEW AS N FOR EACH ROW MODE DB2ROW WHEN (N.AMT < O.AMT) SET N.AMT = O.AMT;
CREATE TRIGGER {lib}.TRG_D3 AFTER DELETE ON {lib}.TRG_T3 REFERENCING OLD AS O FOR EACH ROW MODE DB2ROW INSERT INTO {lib}.TRG_L3 (N) VALUES (O.ID);
