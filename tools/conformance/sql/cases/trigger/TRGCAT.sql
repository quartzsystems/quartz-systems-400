SELECT TRIGGER_NAME, TRIGGERED_UPDATE_COLUMNS FROM QSYS2.SYSTRIGUPD WHERE TRIGGER_SCHEMA = '{lib}' AND TRIGGER_NAME LIKE 'TRG_D%';
