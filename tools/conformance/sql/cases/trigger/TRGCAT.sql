SELECT TRIGGER_NAME, TABLE_NAME, COLUMN_NAME, OBJECT_TYPE FROM QSYS2.SYSTRIGCOL WHERE TRIGGER_SCHEMA = '{lib}' AND TRIGGER_NAME LIKE 'TRG_D%' ORDER BY TRIGGER_NAME, TABLE_NAME, COLUMN_NAME;
