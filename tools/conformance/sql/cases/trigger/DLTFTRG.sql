-- oracle: primary
-- DLTF of a table with an SQL trigger: the trigger and its program go.
CREATE TABLE {lib}.DTT1 (A INT);
CREATE TABLE {lib}.DTTLOG (A INT);
CREATE TRIGGER {lib}.DTTRG1 AFTER INSERT ON {lib}.DTT1 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW INSERT INTO {lib}.DTTLOG VALUES (N.A);
CALL QSYS.QCMDEXC('CHKOBJ OBJ({lib}/DTTRG1) OBJTYPE(*PGM)  ', 0000000040.00000);
CALL QSYS.QCMDEXC('DLTF FILE({lib}/DTT1)                   ', 0000000040.00000);
SELECT COUNT(*) FROM QSYS2.SYSTRIGGERS WHERE TRIGGER_SCHEMA = '{lib}' AND TRIGGER_NAME = 'DTTRG1';
CALL QSYS.QCMDEXC('CHKOBJ OBJ({lib}/DTTRG1) OBJTYPE(*PGM)  ', 0000000040.00000);
CALL QSYS.QCMDEXC('DLTPGM PGM({lib}/DTTRG1)                ', 0000000040.00000);
DROP TABLE {lib}.DTTLOG;
