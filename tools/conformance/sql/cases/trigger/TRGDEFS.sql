CREATE TRIGGER {lib}.TRG_X2 BEFORE INSERT ON {lib}.TRG_T2 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW INSERT INTO {lib}.TRG_T2 VALUES (1, 'X', 1);
CREATE TRIGGER {lib}.TRG_X3 BEFORE INSERT ON {lib}.TRG_T2 FOR EACH STATEMENT MODE DB2SQL SET CURRENT SCHEMA = {lib};
CREATE TRIGGER {lib}.TRG_X4 INSTEAD OF INSERT ON {lib}.TRG_T2 REFERENCING NEW AS N FOR EACH ROW MODE DB2SQL INSERT INTO {lib}.TRG_T2 VALUES (1, 'X', 1);
CREATE TRIGGER {lib}.TRG_X5 AFTER INSERT ON {lib}.TRG_T2 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW SET N.NAME = 'X';
CREATE TRIGGER {lib}.TRG_X6 AFTER INSERT ON {lib}.TRG_T2 REFERENCING NEW TABLE AS NT FOR EACH ROW MODE DB2ROW SET CURRENT SCHEMA = {lib};
CREATE TRIGGER {lib}.TRG_X7 AFTER INSERT ON {lib}.TRG_T2 REFERENCING NEW TABLE AS NT FOR EACH STATEMENT MODE DB2ROW SET CURRENT SCHEMA = {lib};
CREATE TRIGGER {lib}.TRG_X8 BEFORE INSERT ON {lib}.TRG_V2 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW SET N.NAME = 'X';
CREATE TRIGGER {lib}.TRG_C1 BEFORE UPDATE OF NAME, AMT ON {lib}.TRG_T2 REFERENCING NEW AS N FOR EACH ROW SET N.NAME = UPPER(N.NAME);
CREATE TRIGGER {lib}.TRG_C1 AFTER DELETE ON {lib}.TRG_T2 FOR EACH ROW INSERT INTO {lib}.TRG_T2 VALUES (0, 'DUP', 0);
CREATE OR REPLACE TRIGGER {lib}.TRG_C1 BEFORE UPDATE OF NAME ON {lib}.TRG_T2 REFERENCING NEW AS N FOR EACH ROW SET N.NAME = LOWER(N.NAME);
