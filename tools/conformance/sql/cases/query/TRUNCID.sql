-- oracle: pub400
-- TRUNCATE RESTART IDENTITY starts the identity column again at its START; CONTINUE IDENTITY goes on.
CREATE TABLE {lib}.TRID1 (ID INT GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 5), V CHAR(1));
INSERT INTO {lib}.TRID1 (V) VALUES ('a'), ('b');
TRUNCATE {lib}.TRID1 CONTINUE IDENTITY IMMEDIATE;
INSERT INTO {lib}.TRID1 (V) VALUES ('c');
SELECT ID, V FROM {lib}.TRID1 ORDER BY ID;
TRUNCATE {lib}.TRID1 RESTART IDENTITY IMMEDIATE;
INSERT INTO {lib}.TRID1 (V) VALUES ('d'), ('e');
SELECT ID, V FROM {lib}.TRID1 ORDER BY ID;
DROP TABLE {lib}.TRID1;
