-- VOLATILE and NOT VOLATILE on CREATE and ALTER TABLE, as SYSTABLESTAT and SYSPARTITIONSTAT show them (7.5).
CREATE TABLE {lib}.VOLT1 (A INT) VOLATILE;
CREATE TABLE {lib}.VOLT2 (A INT);
CREATE TABLE {lib}.VOLT3 (A INT) NOT VOLATILE CARDINALITY;
SELECT TABLE_NAME, VOLATILE FROM QSYS2.SYSTABLESTAT WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME LIKE 'VOLT%' ORDER BY 1;
SELECT TABLE_NAME, VOLATILE FROM QSYS2.SYSPARTITIONSTAT WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME LIKE 'VOLT%' ORDER BY 1;
ALTER TABLE {lib}.VOLT1 NOT VOLATILE;
ALTER TABLE {lib}.VOLT2 VOLATILE CARDINALITY;
SELECT TABLE_NAME, VOLATILE FROM QSYS2.SYSTABLESTAT WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME LIKE 'VOLT%' ORDER BY 1;
