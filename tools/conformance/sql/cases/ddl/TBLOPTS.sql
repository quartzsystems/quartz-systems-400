-- oracle: primary
-- IN, UNIT and PAGESIZE: IN schema ignored with SQ20367, IN ASP not taken, UNIT ANY or SSD and the index page sizes Db2 for i takes.
CREATE TABLE {lib}.TOPT1 (A INT, B INT, C INT) IN {lib};
CREATE TABLE {lib}.TOPT2 (A INT) IN NOSUCHLIB9;
CREATE TABLE {lib}.TOPT3 (A INT) IN ASP 1;
CREATE TABLE {lib}.TOPT4 (A INT) UNIT SSD;
CREATE TABLE {lib}.TOPT5 (A INT) VOLATILE UNIT ANY;
CREATE TABLE {lib}.TOPT6 (A INT) UNIT FAST;
CREATE INDEX {lib}.TOPTX1 ON {lib}.TOPT1 (A) PAGESIZE 64;
CREATE INDEX {lib}.TOPTX2 ON {lib}.TOPT1 (B) PAGESIZE 512 UNIT SSD;
CREATE INDEX {lib}.TOPTX3 ON {lib}.TOPT1 (C) UNIT ANY PAGESIZE 8;
CREATE INDEX {lib}.TOPTX4 ON {lib}.TOPT1 (A, B) PAGESIZE 4;
CREATE INDEX {lib}.TOPTX5 ON {lib}.TOPT1 (A, C) PAGESIZE 1024;
CREATE INDEX {lib}.TOPTX6 ON {lib}.TOPT1 (B, C) UNIT FAST;
ALTER TABLE {lib}.TOPT1 VOLATILE;
ALTER TABLE {lib}.TOPT1 NOT VOLATILE CARDINALITY;
SELECT TABLE_NAME FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME LIKE 'TOPT%' ORDER BY 1;
SELECT INDEX_NAME FROM QSYS2.SYSINDEXES WHERE INDEX_SCHEMA = '{lib}' AND INDEX_NAME LIKE 'TOPTX%' ORDER BY 1;
DROP TABLE {lib}.TOPT1;
DROP TABLE {lib}.TOPT2;
