-- Tax tables: rates with five decimals, effective ranges checked, a unique index ignoring nulls, money arithmetic in a view.
CREATE TABLE {lib}.D4X_RATE (JURISDICTION CHAR(4) NOT NULL, EFFECTIVE DATE NOT NULL, EXPIRES DATE, RATE DECIMAL(7, 5) NOT NULL, EXEMPT_CODE CHAR(3),
  PRIMARY KEY (JURISDICTION, EFFECTIVE), CHECK (RATE >= 0 AND RATE < 1), CHECK (EXPIRES IS NULL OR EXPIRES > EFFECTIVE));
CREATE UNIQUE WHERE NOT NULL INDEX {lib}.D4X_EXEMPT ON {lib}.D4X_RATE (EXEMPT_CODE);
