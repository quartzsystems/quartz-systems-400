-- oracle: primary
-- GRANT and REVOKE on a table and views; the refusals and SQL0569.
CREATE TABLE {lib}.DDLG1T (ID INT NOT NULL, NAME VARCHAR(20));
CREATE VIEW {lib}.DDLG1V AS SELECT ID FROM {lib}.DDLG1T;
GRANT SELECT ON {lib}.DDLG1T TO QUSER;
GRANT INSERT, UPDATE ON TABLE {lib}.DDLG1T TO QSYSOPR;
GRANT ALL PRIVILEGES ON {lib}.DDLG1T TO QPGMR WITH GRANT OPTION;
GRANT SELECT ON {lib}.DDLG1T TO PUBLIC;
REVOKE SELECT ON {lib}.DDLG1T FROM QSYSOPR;
REVOKE INSERT ON {lib}.DDLG1T FROM QSYSOPR;
REVOKE ALL ON {lib}.DDLG1T FROM QPGMR;
REVOKE ALL ON {lib}.DDLG1T FROM PUBLIC;
GRANT SELECT ON {lib}.DDLG1V TO QUSER;
GRANT INDEX ON {lib}.DDLG1V TO QUSER;
GRANT INSERT ON {lib}.DDLG1V TO QUSER;
GRANT SELECT ON {lib}.DDLG1T TO QNOSUCHUSR;
GRANT SELECT ON {lib}.DDLG1NO TO QUSER;
GRANT USAGE ON SCHEMA {lib} TO QUSER;
DROP TABLE {lib}.DDLG1T;
