-- oracle: primary
-- Privileges on application tables and views: GRANT and REVOKE to the shipped profiles and PUBLIC, SYSTABAUTH.
CREATE TABLE {lib}.D4_PAYROLL (EMPLOYEE_ID INTEGER NOT NULL, PAY_DATE DATE NOT NULL, GROSS DECIMAL(9, 2) NOT NULL);
CREATE VIEW {lib}.D4_PAYROLL_V AS SELECT EMPLOYEE_ID, PAY_DATE FROM {lib}.D4_PAYROLL;
GRANT SELECT ON {lib}.D4_PAYROLL_V TO PUBLIC;
GRANT SELECT, INSERT, UPDATE ON {lib}.D4_PAYROLL TO QPGMR;
GRANT ALL PRIVILEGES ON TABLE {lib}.D4_PAYROLL TO QUSER WITH GRANT OPTION;
GRANT DELETE ON {lib}.D4_PAYROLL TO NOSUCHUSR;
GRANT UPDATE (GROSS) ON {lib}.D4_PAYROLL TO QPGMR;
REVOKE INSERT ON {lib}.D4_PAYROLL FROM QPGMR;
REVOKE ALL ON {lib}.D4_PAYROLL FROM QUSER;
REVOKE SELECT ON {lib}.D4_PAYROLL_V FROM PUBLIC;
REVOKE DELETE ON {lib}.D4_PAYROLL FROM QPGMR;
GRANT SELECT ON {lib}.D4_NO_SUCH_TABLE TO QPGMR;
DROP VIEW {lib}.D4_PAYROLL_V;
DROP TABLE {lib}.D4_PAYROLL;
