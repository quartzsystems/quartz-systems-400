-- oracle: primary
-- requires: QCMDEXC running CL in the job (the storage service; not the in-memory run)
-- One QTEMP per job: what CL makes there SQL sees, and the reverse.
CALL QSYS2.QCMDEXC('CRTPF FILE(QTEMP/QTCLF) RCDLEN(8)', 33);
INSERT INTO QTEMP.QTCLF VALUES ('fromsql');
SELECT * FROM QTEMP.QTCLF;
SELECT COUNT(*) FROM QTCLF;
CREATE TABLE QTEMP.QTSQLT (A CHAR(4) NOT NULL);
CALL QSYS2.QCMDEXC('CHKOBJ OBJ(QTEMP/QTSQLT) OBJTYPE(*FILE)', 39);
CALL QSYS2.QCMDEXC('CPYF FROMFILE(QTEMP/QTCLF) TOFILE(QTEMP/QTSQLT) MBROPT(*ADD) FMTOPT(*NOCHK)', 75);
SELECT * FROM QTEMP.QTSQLT;
CALL QSYS2.QCMDEXC('DLTF FILE(QTEMP/QTSQLT)', 23);
SELECT * FROM QTEMP.QTSQLT;
CALL QSYS2.QCMDEXC('CRTDTAARA DTAARA(QTEMP/QTDTA) TYPE(*CHAR) LEN(10)', 49);
SELECT OBJNAME, OBJTYPE FROM TABLE(QSYS2.OBJECT_STATISTICS('QTEMP', '*FILE *DTAARA')) X WHERE OBJNAME LIKE 'QT%' ORDER BY OBJNAME;
DROP TABLE QTEMP.QTCLF;
CALL QSYS2.QCMDEXC('CHKOBJ OBJ(QTEMP/QTCLF) OBJTYPE(*FILE)', 38);
CALL QSYS2.QCMDEXC('DLTDTAARA DTAARA(QTEMP/QTDTA)', 29);
