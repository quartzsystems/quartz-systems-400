-- oracle: primary
-- RENAME TABLE and RENAME INDEX: the SQL name changes, a generated
-- system name of the same prefix stays.
CREATE TABLE {lib}.DDL_RENAME_SOURCE (X INT);
CREATE TABLE {lib}.DDLR1 (X INT);
CREATE INDEX {lib}.DDL_RENAME_INDEX ON {lib}.DDLR1 (X);
RENAME TABLE {lib}.DDL_RENAME_SOURCE TO DDL_RENAME_TARGET;
RENAME INDEX {lib}.DDL_RENAME_INDEX TO DDL_RENAME_INDEX2;
SELECT TABLE_NAME, SYSTEM_TABLE_NAME FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME LIKE 'DDL_RENAME%';
SELECT INDEX_NAME, SYSTEM_INDEX_NAME FROM QSYS2.SYSINDEXES WHERE INDEX_SCHEMA = '{lib}' AND INDEX_NAME LIKE 'DDL_RENAME%';
SELECT * FROM {lib}.DDL_RENAME_SOURCE;
RENAME TABLE {lib}.DDLR1 TO DDL_RENAME_TARGET;
DROP TABLE {lib}.DDL_RENAME_TARGET;
DROP TABLE {lib}.DDLR1;
