CREATE VIEW {lib}.D4_GL_BALANCE (ACCOUNT_NUMBER, ACCOUNT_NAME, TOTAL_DEBIT, TOTAL_CREDIT, NET) AS
  SELECT A.ACCOUNT_NUMBER, A.ACCOUNT_NAME, SUM(E.DEBIT_AMOUNT), SUM(E.CREDIT_AMOUNT), SUM(E.DEBIT_AMOUNT - E.CREDIT_AMOUNT)
  FROM {lib}.D4_GL_ACCOUNT A JOIN {lib}.D4_GL_ENTRY E ON A.ACCOUNT_NUMBER = E.ACCOUNT_NUMBER
  GROUP BY A.ACCOUNT_NUMBER, A.ACCOUNT_NAME;
