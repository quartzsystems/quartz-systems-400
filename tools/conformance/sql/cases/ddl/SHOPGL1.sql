-- General ledger: chart of accounts and journal lines, balance checks, a summary view with grouping.
CREATE TABLE {lib}.D4_GL_ACCOUNT (
  ACCOUNT_NUMBER CHAR(8) NOT NULL PRIMARY KEY,
  ACCOUNT_NAME VARCHAR(40) NOT NULL,
  ACCOUNT_TYPE CHAR(1) NOT NULL CONSTRAINT D4_GL_TYPE CHECK (ACCOUNT_TYPE IN ('A', 'L', 'E', 'R', 'X')),
  NORMAL_BALANCE CHAR(2) NOT NULL DEFAULT 'DR');
CREATE TABLE {lib}.D4_GL_ENTRY (
  ENTRY_ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  POSTING_DATE DATE NOT NULL,
  ACCOUNT_NUMBER CHAR(8) NOT NULL REFERENCES {lib}.D4_GL_ACCOUNT (ACCOUNT_NUMBER) ON DELETE RESTRICT,
  DEBIT_AMOUNT DECIMAL(15, 2) NOT NULL DEFAULT 0,
  CREDIT_AMOUNT DECIMAL(15, 2) NOT NULL DEFAULT 0,
  MEMO VARCHAR(100),
  PRIMARY KEY (ENTRY_ID),
  CHECK (DEBIT_AMOUNT >= 0 AND CREDIT_AMOUNT >= 0),
  CHECK (DEBIT_AMOUNT = 0 OR CREDIT_AMOUNT = 0));
