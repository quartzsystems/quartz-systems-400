-- oracle: primary
-- Customer master: an identity key, ROW CHANGE TIMESTAMP, a unique e-mail and a view of active customers.
CREATE TABLE {lib}.D4_CUSTOMER (
  CUSTOMER_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 10),
  CUSTOMER_NAME VARCHAR(40) NOT NULL,
  EMAIL_ADDRESS VARCHAR(60),
  CREDIT_LIMIT DECIMAL(9, 2) NOT NULL DEFAULT 1000.00,
  ACTIVE_FLAG CHAR(1) NOT NULL DEFAULT 'Y',
  CHANGED_AT TIMESTAMP NOT NULL GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP,
  PRIMARY KEY (CUSTOMER_ID),
  CONSTRAINT D4_CUSTOMER_EMAIL UNIQUE (EMAIL_ADDRESS));
