-- Long-named sequences and indexes as 7.5 shops name them, ALTER SEQUENCE options, and the catalog's system names.
CREATE SEQUENCE {lib}.D4_CUSTOMER_NUMBER_SEQUENCE AS BIGINT START WITH 1000 INCREMENT BY 1 CACHE 50;
CREATE SEQUENCE {lib}.D4_RETURN_AUTHORIZATION_SEQ AS INTEGER START WITH 1 INCREMENT BY 2 MAXVALUE 7 CYCLE NO CACHE;
VALUES NEXT VALUE FOR {lib}.D4_CUSTOMER_NUMBER_SEQUENCE;
VALUES NEXT VALUE FOR {lib}.D4_RETURN_AUTHORIZATION_SEQ;
VALUES NEXT VALUE FOR {lib}.D4_RETURN_AUTHORIZATION_SEQ;
VALUES NEXT VALUE FOR {lib}.D4_RETURN_AUTHORIZATION_SEQ;
VALUES NEXT VALUE FOR {lib}.D4_RETURN_AUTHORIZATION_SEQ;
VALUES NEXT VALUE FOR {lib}.D4_RETURN_AUTHORIZATION_SEQ;
ALTER SEQUENCE {lib}.D4_CUSTOMER_NUMBER_SEQUENCE RESTART WITH 5000 NO CACHE;
VALUES NEXT VALUE FOR {lib}.D4_CUSTOMER_NUMBER_SEQUENCE;
SELECT SEQUENCE_NAME, SYSTEM_SEQ_NAME, DATA_TYPE, INCREMENT, CYCLE_OPTION FROM QSYS2.SYSSEQUENCES WHERE SEQUENCE_SCHEMA = '{lib}' AND SEQUENCE_NAME LIKE 'D4_%' ORDER BY SEQUENCE_NAME;
CREATE TABLE {lib}.D4_RETURN_AUTHORIZATION (RA_NUMBER INTEGER NOT NULL, CUSTOMER_NUMBER BIGINT NOT NULL);
CREATE INDEX {lib}.D4_RETURN_AUTHORIZATION_BY_CUSTOMER ON {lib}.D4_RETURN_AUTHORIZATION (CUSTOMER_NUMBER);
INSERT INTO {lib}.D4_RETURN_AUTHORIZATION VALUES (NEXT VALUE FOR {lib}.D4_RETURN_AUTHORIZATION_SEQ, NEXT VALUE FOR {lib}.D4_CUSTOMER_NUMBER_SEQUENCE);
SELECT RA_NUMBER, CUSTOMER_NUMBER FROM {lib}.D4_RETURN_AUTHORIZATION;
SELECT INDEX_NAME, SYSTEM_INDEX_NAME FROM QSYS2.SYSINDEXES WHERE INDEX_SCHEMA = '{lib}' AND TABLE_NAME = 'D4_RETURN_AUTHORIZATION';
DROP INDEX {lib}.D4_RETURN_AUTHORIZATION_BY_CUSTOMER;
DROP TABLE {lib}.D4_RETURN_AUTHORIZATION;
DROP SEQUENCE {lib}.D4_CUSTOMER_NUMBER_SEQUENCE;
DROP SEQUENCE {lib}.D4_RETURN_AUTHORIZATION_SEQ;
