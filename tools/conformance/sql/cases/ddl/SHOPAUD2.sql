-- An audited order table as 7.5 shops build it: audit columns, ROW CHANGE TIMESTAMP, identity, a view, and the catalog's generation columns.
CREATE TABLE {lib}.D4_AUDITED_ORDER (
  ORDER_ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  AMOUNT DECIMAL(9, 2) NOT NULL,
  CHANGED_BY VARCHAR(18) GENERATED ALWAYS AS (USER),
  CHANGE_OP CHAR(1) GENERATED ALWAYS AS (DATA CHANGE OPERATION),
  CHANGED_AT TIMESTAMP NOT NULL GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP);
INSERT INTO {lib}.D4_AUDITED_ORDER (AMOUNT) VALUES (10.00), (20.00);
UPDATE {lib}.D4_AUDITED_ORDER SET AMOUNT = AMOUNT + 1 WHERE ORDER_ID = 1;
SELECT ORDER_ID, AMOUNT, CHANGED_BY = USER, CHANGE_OP FROM {lib}.D4_AUDITED_ORDER ORDER BY ORDER_ID;
INSERT INTO {lib}.D4_AUDITED_ORDER (AMOUNT, CHANGE_OP) VALUES (30.00, 'X');
UPDATE {lib}.D4_AUDITED_ORDER SET CHANGED_BY = 'ME';
SELECT COLUMN_NAME, HAS_DEFAULT, IS_GENERATED, GENERATED FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME = 'D4_AUDITED_ORDER' ORDER BY ORDINAL_POSITION;
DROP TABLE {lib}.D4_AUDITED_ORDER;
