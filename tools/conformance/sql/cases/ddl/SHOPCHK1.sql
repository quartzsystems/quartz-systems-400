  NAME VARCHAR(40) NOT NULL CONSTRAINT D4_SUP_NAME CHECK (LENGTH(TRIM(NAME)) > 1),
  COUNTRY CHAR(2) NOT NULL CONSTRAINT D4_SUP_CTRY CHECK (COUNTRY IN ('US', 'CA', 'MX', 'DE')),
  RATING SMALLINT CONSTRAINT D4_SUP_RATE CHECK (RATING BETWEEN 1 AND 5 OR RATING IS NULL),
  DISCOUNT DECIMAL(4, 3) NOT NULL DEFAULT 0 CONSTRAINT D4_SUP_DISC CHECK (DISCOUNT >= 0 AND DISCOUNT < 0.5),
  PHONE VARCHAR(20) CONSTRAINT D4_SUP_PHONE CHECK (SUBSTR(PHONE, 1, 1) = '+'));
