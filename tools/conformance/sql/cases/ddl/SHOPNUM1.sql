-- oracle: primary
-- A rate table with every numeric and date type a shop declares, its catalog lengths and scales, and out-of-range values.
CREATE TABLE {lib}.D4_RATES (R_SMALL SMALLINT, R_INT INTEGER, R_BIG BIGINT, R_DEC DECIMAL(15, 5), R_NUM NUMERIC(8, 2), R_REAL REAL, R_DBL DOUBLE, R_FLT FLOAT(53), R_DATE DATE, R_TIME TIME, R_TS TIMESTAMP, R_CHAR CHAR(12), R_VC VARCHAR(300), R_DEC0 DECIMAL(5), R_INT2 INT);
