SELECT R_SMALL, R_INT, R_BIG, R_DEC, R_NUM, R_REAL, R_DBL, R_FLT, R_DATE, R_TIME, R_TS, R_CHAR, R_VC, R_DEC0, R_INT2 FROM {lib}.D4_RATES ORDER BY R_SMALL;
SELECT COLUMN_NAME, LENGTH, NUMERIC_SCALE, NUMERIC_PRECISION_RADIX, IS_NULLABLE, CCSID FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME = 'D4_RATES' ORDER BY ORDINAL_POSITION;
SELECT R_DEC * R_NUM, R_SMALL + R_BIG, R_INT / 2, R_DEC0 / 3 FROM {lib}.D4_RATES WHERE R_INT IS NOT NULL;
