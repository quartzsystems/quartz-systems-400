CREATE VIEW {lib}.D4_ALL_SALES AS SELECT REGION, SALES_REP, SALE_DATE, AMOUNT FROM {lib}.D4_SALES UNION ALL SELECT REGION, SALES_REP, SALE_DATE, AMOUNT FROM {lib}.D4_SALES_ARCHIVE;
CREATE VIEW {lib}.D4_REGION_TOTALS (REGION, SALES_COUNT, TOTAL_AMOUNT) AS SELECT REGION, COUNT(*), SUM(AMOUNT) FROM {lib}.D4_ALL_SALES GROUP BY REGION;
CREATE VIEW {lib}.D4_EAST_SALES AS SELECT REGION, SALES_REP, SALE_DATE, AMOUNT FROM {lib}.D4_SALES WHERE REGION = 'EAST' WITH CHECK OPTION;
CREATE VIEW {lib}.D4_SALES_MONTH AS SELECT REGION, YEAR(SALE_DATE) AS SALE_YEAR, MONTH(SALE_DATE) AS SALE_MONTH, AMOUNT FROM {lib}.D4_SALES;
