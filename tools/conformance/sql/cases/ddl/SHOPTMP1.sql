-- A batch job's work tables: DECLARE GLOBAL TEMPORARY TABLE in SESSION, filled from a permanent table, summarized, replaced.
CREATE TABLE {lib}.D4_STOCK_MOVE (ITEM CHAR(8) NOT NULL, MOVE_TYPE CHAR(1) NOT NULL, QTY INTEGER NOT NULL);
INSERT INTO {lib}.D4_STOCK_MOVE VALUES ('A', 'R', 10), ('A', 'I', 3), ('B', 'R', 5), ('A', 'I', 2), ('C', 'R', 1);
DECLARE GLOBAL TEMPORARY TABLE SESSION.D4_NET (ITEM CHAR(8) NOT NULL, NET_QTY INTEGER) ON COMMIT PRESERVE ROWS NOT LOGGED;
INSERT INTO SESSION.D4_NET SELECT ITEM, SUM(CASE MOVE_TYPE WHEN 'R' THEN QTY ELSE -QTY END) FROM {lib}.D4_STOCK_MOVE GROUP BY ITEM;
SELECT ITEM, NET_QTY FROM SESSION.D4_NET ORDER BY ITEM;
DECLARE GLOBAL TEMPORARY TABLE SESSION.D4_NET (ITEM CHAR(8)) ON COMMIT PRESERVE ROWS;
DECLARE GLOBAL TEMPORARY TABLE SESSION.D4_NET (ITEM CHAR(8), FLAG CHAR(1)) WITH REPLACE ON COMMIT PRESERVE ROWS;
SELECT COUNT(*) FROM SESSION.D4_NET;
DECLARE GLOBAL TEMPORARY TABLE SESSION.D4_COPY AS (SELECT ITEM, QTY FROM {lib}.D4_STOCK_MOVE WHERE MOVE_TYPE = 'R') WITH DATA ON COMMIT PRESERVE ROWS;
SELECT ITEM, QTY FROM SESSION.D4_COPY ORDER BY ITEM;
DECLARE GLOBAL TEMPORARY TABLE SESSION.D4_LIKE LIKE {lib}.D4_STOCK_MOVE ON COMMIT PRESERVE ROWS;
INSERT INTO SESSION.D4_LIKE VALUES ('Z', 'R', 1);
SELECT * FROM SESSION.D4_LIKE;
DROP TABLE SESSION.D4_NET;
DROP TABLE SESSION.D4_COPY;
DROP TABLE SESSION.D4_LIKE;
SELECT COUNT(*) FROM SESSION.D4_LIKE;
DROP TABLE {lib}.D4_STOCK_MOVE;
