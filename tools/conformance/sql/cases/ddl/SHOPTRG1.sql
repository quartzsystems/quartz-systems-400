-- oracle: primary
-- An audit trail kept by triggers: BEFORE INSERT defaulting a column, AFTER UPDATE and AFTER DELETE writing a history table.
CREATE TABLE {lib}.D4T_ITEM (ITEM CHAR(6) NOT NULL PRIMARY KEY, PRICE DECIMAL(7, 2) NOT NULL, CATEGORY CHAR(3));
CREATE TABLE {lib}.D4T_HIST (ITEM CHAR(6) NOT NULL, ACTION CHAR(1) NOT NULL, OLD_PRICE DECIMAL(7, 2), NEW_PRICE DECIMAL(7, 2));
CREATE TRIGGER {lib}.D4T_BI BEFORE INSERT ON {lib}.D4T_ITEM REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW
  WHEN (N.CATEGORY IS NULL) SET N.CATEGORY = 'GEN';
CREATE TRIGGER {lib}.D4T_AU AFTER UPDATE OF PRICE ON {lib}.D4T_ITEM REFERENCING OLD AS O NEW AS N FOR EACH ROW MODE DB2ROW
  INSERT INTO {lib}.D4T_HIST VALUES (N.ITEM, 'U', O.PRICE, N.PRICE);
CREATE TRIGGER {lib}.D4T_AD AFTER DELETE ON {lib}.D4T_ITEM REFERENCING OLD AS O FOR EACH ROW MODE DB2ROW
  INSERT INTO {lib}.D4T_HIST VALUES (O.ITEM, 'D', O.PRICE, NULL);
INSERT INTO {lib}.D4T_ITEM VALUES ('A1', 10.00, NULL), ('B2', 20.00, 'TOY');
UPDATE {lib}.D4T_ITEM SET PRICE = PRICE * 1.10;
UPDATE {lib}.D4T_ITEM SET CATEGORY = 'X' WHERE ITEM = 'A1';
DELETE FROM {lib}.D4T_ITEM WHERE ITEM = 'B2';
SELECT ITEM, PRICE, CATEGORY FROM {lib}.D4T_ITEM ORDER BY ITEM;
SELECT ITEM, ACTION, OLD_PRICE, NEW_PRICE FROM {lib}.D4T_HIST ORDER BY ITEM, ACTION;
SELECT TRIGGER_NAME, EVENT_MANIPULATION, ACTION_TIMING, ACTION_ORIENTATION FROM QSYS2.SYSTRIGGERS WHERE TRIGGER_SCHEMA = '{lib}' AND TRIGGER_NAME LIKE 'D4T%' ORDER BY TRIGGER_NAME;
DROP TRIGGER {lib}.D4T_BI;
DROP TRIGGER {lib}.D4T_AU;
DROP TRIGGER {lib}.D4T_AD;
DROP TABLE {lib}.D4T_HIST;
DROP TABLE {lib}.D4T_ITEM;
