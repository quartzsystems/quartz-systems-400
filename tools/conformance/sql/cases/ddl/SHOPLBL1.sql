-- oracle: primary
-- Labels and comments as shops document their files: LABEL ON (TABLE, COLUMN, INDEX, VIEW, ALIAS), COMMENT ON, the catalogs.
CREATE TABLE {lib}.D4_PART (PART_NUMBER CHAR(10) NOT NULL, PART_DESCRIPTION VARCHAR(50), UNIT_COST DECIMAL(9, 4), WEIGHT_KG DECIMAL(7, 3));
CREATE INDEX {lib}.D4_PART_IX ON {lib}.D4_PART (PART_NUMBER);
CREATE VIEW {lib}.D4_PART_V AS SELECT PART_NUMBER, UNIT_COST FROM {lib}.D4_PART;
CREATE ALIAS {lib}.D4_PART_A FOR {lib}.D4_PART;
LABEL ON TABLE {lib}.D4_PART IS 'Part master';
LABEL ON INDEX {lib}.D4_PART_IX IS 'Part master by number';
LABEL ON TABLE {lib}.D4_PART_V IS 'Part costs';
LABEL ON ALIAS {lib}.D4_PART_A IS 'Part master alias';
LABEL ON COLUMN {lib}.D4_PART.PART_NUMBER IS 'Part                Number';
LABEL ON COLUMN {lib}.D4_PART.UNIT_COST IS 'Unit                Cost';
LABEL ON COLUMN {lib}.D4_PART (PART_DESCRIPTION TEXT IS 'Description of the part', WEIGHT_KG TEXT IS 'Weight in kilograms');
COMMENT ON TABLE {lib}.D4_PART IS 'Every part the plant buys or makes, one row a part.';
COMMENT ON COLUMN {lib}.D4_PART.UNIT_COST IS 'Standard cost, four decimals.';
COMMENT ON INDEX {lib}.D4_PART_IX IS 'Lookup by part number.';
LABEL ON TABLE {lib}.D4_PART IS 'This label is far longer than the fifty characters a label may have';
LABEL ON COLUMN {lib}.D4_PART.NO_SUCH_COLUMN IS 'x';
SELECT TABLE_NAME, TABLE_TYPE, TABLE_TEXT, LONG_COMMENT FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME LIKE 'D4_PART%' ORDER BY TABLE_NAME;
SELECT COLUMN_NAME, COLUMN_HEADING, COLUMN_TEXT, LONG_COMMENT FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME = 'D4_PART' ORDER BY ORDINAL_POSITION;
SELECT INDEX_NAME, INDEX_TEXT, LONG_COMMENT FROM QSYS2.SYSINDEXES WHERE INDEX_SCHEMA = '{lib}' AND INDEX_NAME = 'D4_PART_IX';
DROP ALIAS {lib}.D4_PART_A;
DROP VIEW {lib}.D4_PART_V;
DROP TABLE {lib}.D4_PART;
