CREATE VIEW {lib}.D4V_INQ (ORD, NAME, REGION_NAME, ODATE, LINES, VALUE, SIZE_CLASS) AS
  SELECT O.ORD, C.NAME, CASE C.REGION WHEN 'N' THEN 'North' WHEN 'S' THEN 'South' ELSE 'Other' END, O.ODATE,
    COUNT(*), SUM(L.QTY * L.PRICE), CASE WHEN SUM(L.QTY * L.PRICE) >= 100 THEN 'L' ELSE 'S' END
  FROM {lib}.D4V_ORD O JOIN {lib}.D4V_CUST C ON C.CUST = O.CUST JOIN {lib}.D4V_LIN L ON L.ORD = O.ORD
  GROUP BY O.ORD, C.NAME, C.REGION, O.ODATE;
SELECT * FROM {lib}.D4V_INQ ORDER BY ORD;
SELECT NAME, SUM(VALUE) FROM {lib}.D4V_INQ WHERE SIZE_CLASS = 'S' GROUP BY NAME ORDER BY NAME;
SELECT ORD, VALUE FROM {lib}.D4V_INQ WHERE MONTH(ODATE) = 2 AND VALUE > 10 ORDER BY ORD;
