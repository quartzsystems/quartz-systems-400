-- An order inquiry view over three tables with CASE and arithmetic, queried with predicates on its derived columns; a view replaced.
CREATE TABLE {lib}.D4V_CUST (CUST INTEGER NOT NULL PRIMARY KEY, NAME VARCHAR(30) NOT NULL, REGION CHAR(1) NOT NULL);
CREATE TABLE {lib}.D4V_ORD (ORD INTEGER NOT NULL PRIMARY KEY, CUST INTEGER NOT NULL, ODATE DATE NOT NULL);
CREATE TABLE {lib}.D4V_LIN (ORD INTEGER NOT NULL, LIN INTEGER NOT NULL, QTY INTEGER NOT NULL, PRICE DECIMAL(7, 2) NOT NULL);
