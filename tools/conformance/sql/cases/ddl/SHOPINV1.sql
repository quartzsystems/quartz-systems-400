CREATE UNIQUE INDEX {lib}.D4_ITEM_MASTER_IX1 ON {lib}.D4_ITEM_MASTER (ITEM_NUMBER, WAREHOUSE);
CREATE INDEX {lib}.D4_ITEM_MASTER_IX2 ON {lib}.D4_ITEM_MASTER (ON_HAND DESC, ITEM_NUMBER);
CREATE INDEX {lib}.D4_ITEM_ACTIVE ON {lib}.D4_ITEM_MASTER (ITEM_NUMBER) WHERE DISCONTINUED = 'N';
CREATE SEQUENCE {lib}.D4_RECEIPT_SEQ AS INTEGER START WITH 5000 INCREMENT BY 1 NO CYCLE CACHE 10;
