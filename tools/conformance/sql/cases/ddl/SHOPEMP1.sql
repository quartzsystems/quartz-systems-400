CREATE TABLE {lib}.D4_EMPLOYEE (
  EMPLOYEE_ID INTEGER NOT NULL PRIMARY KEY,
  LAST_NAME VARCHAR(30) NOT NULL,
  FIRST_NAME VARCHAR(20) NOT NULL,
  HIRE_DATE DATE NOT NULL,
  TERM_DATE DATE,
  MANAGER_ID INTEGER,
  SALARY DECIMAL(9, 2) NOT NULL,
  CONSTRAINT D4_EMP_DATES CHECK (TERM_DATE IS NULL OR TERM_DATE >= HIRE_DATE),
  CONSTRAINT D4_EMP_SALARY CHECK (SALARY BETWEEN 0 AND 500000),
  CONSTRAINT D4_EMP_MGR FOREIGN KEY (MANAGER_ID) REFERENCES {lib}.D4_EMPLOYEE (EMPLOYEE_ID) ON DELETE SET NULL);
