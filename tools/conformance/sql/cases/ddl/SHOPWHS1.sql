-- Warehouse locations: a two-column primary key, a two-column foreign key, SET DEFAULT on delete, defaults of special registers.
CREATE TABLE {lib}.D4_WAREHOUSE (WHS CHAR(3) NOT NULL, ZONE CHAR(2) NOT NULL, ZONE_NAME VARCHAR(30) NOT NULL, PRIMARY KEY (WHS, ZONE));
CREATE TABLE {lib}.D4_BIN (BIN_ID INTEGER NOT NULL PRIMARY KEY, WHS CHAR(3) NOT NULL DEFAULT 'W00', ZONE CHAR(2) NOT NULL DEFAULT 'XX', CREATED_BY VARCHAR(18) NOT NULL DEFAULT USER, CREATED_ON DATE NOT NULL DEFAULT CURRENT DATE,
  CONSTRAINT D4_BIN_ZONE FOREIGN KEY (WHS, ZONE) REFERENCES {lib}.D4_WAREHOUSE (WHS, ZONE) ON DELETE SET DEFAULT);
