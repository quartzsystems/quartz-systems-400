-- oracle: primary
-- Documenting a schema in bulk: COMMENT ON several columns, LABEL ON several column headings, labels on sequences and the long comments.
CREATE TABLE {lib}.D4M_RATE (CODE CHAR(3) NOT NULL, RATE DECIMAL(7, 5) NOT NULL, VALID_FROM DATE NOT NULL, VALID_TO DATE);
CREATE SEQUENCE {lib}.D4M_SEQ;
COMMENT ON {lib}.D4M_RATE (CODE IS 'ISO currency code', RATE IS 'Units per US dollar', VALID_FROM IS 'First day the rate applies');
LABEL ON {lib}.D4M_RATE (CODE IS 'Currency', RATE IS 'Exchange            rate', VALID_TO IS 'Valid               until');
LABEL ON SEQUENCE {lib}.D4M_SEQ IS 'Rate batch numbers';
COMMENT ON SEQUENCE {lib}.D4M_SEQ IS 'One number per rate load.';
COMMENT ON TABLE {lib}.D4M_RATE IS '';
SELECT COLUMN_NAME, COLUMN_HEADING, LONG_COMMENT FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME = 'D4M_RATE' ORDER BY ORDINAL_POSITION;
SELECT SEQUENCE_NAME, SEQUENCE_TEXT, LONG_COMMENT FROM QSYS2.SYSSEQUENCES WHERE SEQUENCE_SCHEMA = '{lib}' AND SEQUENCE_NAME = 'D4M_SEQ';
SELECT TABLE_NAME, LONG_COMMENT FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = '{lib}' AND TABLE_NAME = 'D4M_RATE';
DROP SEQUENCE {lib}.D4M_SEQ;
DROP TABLE {lib}.D4M_RATE;
