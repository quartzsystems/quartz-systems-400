-- oracle: primary
-- A calendar table filled by a recursive INSERT, a fiscal-period view, the date functions shops use on it.
CREATE TABLE {lib}.D4K_CAL (CAL_DATE DATE NOT NULL PRIMARY KEY, DOW SMALLINT NOT NULL, FISCAL_PERIOD SMALLINT NOT NULL, IS_WEEKEND CHAR(1) NOT NULL);
INSERT INTO {lib}.D4K_CAL
  WITH D (X) AS (SELECT DATE('2026-01-01') FROM SYSIBM.SYSDUMMY1 UNION ALL SELECT X + 1 DAY FROM D WHERE X < '2026-03-31')
  SELECT X, DAYOFWEEK(X), MONTH(X), CASE WHEN DAYOFWEEK(X) IN (1, 7) THEN 'Y' ELSE 'N' END FROM D;
SELECT COUNT(*), MIN(CAL_DATE), MAX(CAL_DATE) FROM {lib}.D4K_CAL;
SELECT FISCAL_PERIOD, COUNT(*), SUM(CASE IS_WEEKEND WHEN 'N' THEN 1 ELSE 0 END) FROM {lib}.D4K_CAL GROUP BY FISCAL_PERIOD ORDER BY 1;
CREATE VIEW {lib}.D4K_WEEKS AS SELECT WEEK(CAL_DATE) AS WK, MIN(CAL_DATE) AS FIRST_DAY, MAX(CAL_DATE) AS LAST_DAY FROM {lib}.D4K_CAL GROUP BY WEEK(CAL_DATE);
SELECT WK, FIRST_DAY, LAST_DAY, DAYS(LAST_DAY) - DAYS(FIRST_DAY) FROM {lib}.D4K_WEEKS WHERE WK <= 3 ORDER BY WK;
SELECT CAL_DATE, DAYNAME(CAL_DATE), DAYOFYEAR(CAL_DATE), QUARTER(CAL_DATE) FROM {lib}.D4K_CAL WHERE CAL_DATE IN ('2026-01-01', '2026-02-28', '2026-03-31') ORDER BY 1;
DROP VIEW {lib}.D4K_WEEKS;
DROP TABLE {lib}.D4K_CAL;
