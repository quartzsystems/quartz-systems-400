-- oracle: primary
-- Order entry: header and lines with long names, keys, a foreign key with cascade, defaults and labels.
CREATE TABLE {lib}.D4_ORDER_HEADER (
  ORDER_NUMBER INTEGER NOT NULL,
  CUSTOMER_NUMBER INTEGER NOT NULL,
  ORDER_DATE DATE NOT NULL DEFAULT CURRENT DATE,
  ORDER_STATUS CHAR(1) NOT NULL DEFAULT 'O',
  ORDER_TOTAL DECIMAL(11, 2) NOT NULL DEFAULT 0,
  CONSTRAINT D4_ORDER_HEADER_PK PRIMARY KEY (ORDER_NUMBER),
  CONSTRAINT D4_ORDER_STATUS_CK CHECK (ORDER_STATUS IN ('O', 'S', 'C')));
CREATE TABLE {lib}.D4_ORDER_LINE (
  ORDER_NUMBER INTEGER NOT NULL,
  LINE_NUMBER SMALLINT NOT NULL,
  ITEM_NUMBER CHAR(15) NOT NULL,
  QUANTITY DECIMAL(7, 0) NOT NULL CHECK (QUANTITY > 0),
  UNIT_PRICE DECIMAL(9, 2) NOT NULL,
  PRIMARY KEY (ORDER_NUMBER, LINE_NUMBER),
  CONSTRAINT D4_ORDER_LINE_FK FOREIGN KEY (ORDER_NUMBER) REFERENCES {lib}.D4_ORDER_HEADER (ORDER_NUMBER) ON DELETE CASCADE);
LABEL ON TABLE {lib}.D4_ORDER_HEADER IS 'Order header';
LABEL ON TABLE {lib}.D4_ORDER_LINE IS 'Order lines';
LABEL ON COLUMN {lib}.D4_ORDER_HEADER (ORDER_NUMBER IS 'Order               Number', CUSTOMER_NUMBER IS 'Customer            Number', ORDER_STATUS IS 'Status');
LABEL ON COLUMN {lib}.D4_ORDER_HEADER (ORDER_TOTAL TEXT IS 'Order total amount');
