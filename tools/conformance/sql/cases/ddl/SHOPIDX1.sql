-- Indexes a shop adds for its queries: multi-column, descending, UNIQUE WHERE NOT NULL, an EVI, sparse, and their errors.
CREATE TABLE {lib}.D4_CONTACT (CONTACT_ID INTEGER NOT NULL, LAST_NAME VARCHAR(30) NOT NULL, FIRST_NAME VARCHAR(20), CITY VARCHAR(30), STATE CHAR(2), BADGE CHAR(6), ACTIVE CHAR(1) NOT NULL DEFAULT 'Y');
CREATE INDEX {lib}.D4_CONTACT_NAME ON {lib}.D4_CONTACT (LAST_NAME, FIRST_NAME);
CREATE INDEX {lib}.D4_CONTACT_GEO ON {lib}.D4_CONTACT (STATE ASC, CITY DESC);
CREATE UNIQUE WHERE NOT NULL INDEX {lib}.D4_CONTACT_BADGE ON {lib}.D4_CONTACT (BADGE);
CREATE ENCODED VECTOR INDEX {lib}.D4_CONTACT_EVI ON {lib}.D4_CONTACT (STATE);
CREATE INDEX {lib}.D4_CONTACT_ACT ON {lib}.D4_CONTACT (CONTACT_ID) WHERE ACTIVE = 'Y';
