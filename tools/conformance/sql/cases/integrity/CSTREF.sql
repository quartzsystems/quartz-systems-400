-- oracle: primary
-- Referential constraints: the rule combinations as created, the definition errors, the restrict rules at work,
-- and the delete rules that change dependents refused while the files are not journaled ({lib} is not a schema).
CREATE TABLE {lib}.IRPAR (ID INTEGER NOT NULL PRIMARY KEY, AMT DECIMAL(7,2) CHECK (AMT >= 0));
CREATE TABLE {lib}.IRCH1 (CID INTEGER NOT NULL, PID INTEGER, CONSTRAINT IRCH1_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR ON DELETE CASCADE);
CREATE TABLE {lib}.IRCH2 (CID INTEGER NOT NULL, PID INTEGER, CONSTRAINT IRCH2_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR ON DELETE SET NULL ON UPDATE RESTRICT);
CREATE TABLE {lib}.IRCH3 (CID INTEGER NOT NULL, PID INTEGER NOT NULL DEFAULT 0, CONSTRAINT IRCH3_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR ON DELETE SET DEFAULT ON UPDATE NO ACTION);
CREATE TABLE {lib}.IRCH4 (CID INTEGER NOT NULL, PID INTEGER NOT NULL, CONSTRAINT IRCH4_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR ON DELETE SET NULL);
CREATE TABLE {lib}.IRCH5 (CID INTEGER NOT NULL, PID INTEGER, CONSTRAINT IRCH5_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR ON UPDATE CASCADE);
CREATE TABLE {lib}.IRCH6 (CID INTEGER NOT NULL, PID INTEGER, CONSTRAINT IRCH6_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR ON DELETE NO ACTION ON UPDATE NO ACTION);
CREATE TABLE {lib}.IRCH7 (CID INTEGER NOT NULL, PID CHAR(4), CONSTRAINT IRCH7_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR);
CREATE TABLE {lib}.IRCH8 (CID INTEGER NOT NULL, PID INTEGER, CONSTRAINT IRCH8_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR (AMT));
CREATE TABLE {lib}.IRCH9 (CID INTEGER NOT NULL, PID INTEGER, CONSTRAINT IRCH9_FK FOREIGN KEY (PID) REFERENCES {lib}.IRPAR ON DELETE RESTRICT);
