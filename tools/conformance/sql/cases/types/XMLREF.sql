-- oracle: pub400
-- XML and array forms QS/400 refuses (SQL0084) and what pub400 answers: XMLAGG, XMLEXISTS, XMLQUERY, XMLELEMENT, an XML column, ARRAY_EXISTS outside a routine.
CREATE TABLE {lib}.D4X_T (ID INTEGER NOT NULL, NAME VARCHAR(10));
INSERT INTO {lib}.D4X_T VALUES (1, 'a'), (2, 'b');
SELECT XMLSERIALIZE(XMLAGG(XMLELEMENT(NAME "n", NAME) ORDER BY ID) AS VARCHAR(100)) FROM {lib}.D4X_T;
SELECT ID FROM {lib}.D4X_T WHERE XMLEXISTS('$d/a' PASSING XMLPARSE(DOCUMENT '<a/>') AS "d");
SELECT XMLSERIALIZE(XMLQUERY('$d/a' PASSING XMLPARSE(DOCUMENT '<a>1</a>') AS "d") AS VARCHAR(20)) FROM SYSIBM.SYSDUMMY1;
CREATE TABLE {lib}.D4X_X (ID INTEGER, DOC XML);
VALUES ARRAY_EXISTS(ARRAY[1, 2], 1);
SELECT XMLSERIALIZE(XMLPARSE(CONTENT 'text') AS VARCHAR(10)) FROM SYSIBM.SYSDUMMY1;
DROP TABLE {lib}.D4X_X;
DROP TABLE {lib}.D4X_T;
