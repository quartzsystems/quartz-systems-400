-- XMLPARSE and XMLSERIALIZE; the XML functions QS/400 refuses.
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a><b>x</b></a>') AS VARCHAR(100)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a>  <b x="1"  y=''2''>x &amp; y</b>  </a>') AS CLOB(1K)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a>  <b>x</b>  </a>' PRESERVE WHITESPACE) AS VARCHAR(100)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<?xml version="1.0"?><a/>') AS VARCHAR(100)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a/>') AS VARCHAR(100) INCLUDING XMLDECLARATION) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a><!-- c --><?pi x?><![CDATA[<z>]]>&lt;&#65;</a>') AS VARCHAR(100)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a>x</b>') AS VARCHAR(100)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT 'text') AS VARCHAR(100)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a>x</a>') AS VARCHAR(3)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT '<a b="&quot;"/>') AS VARCHAR(100)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLPARSE(DOCUMENT '<a/>') FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLPARSE(DOCUMENT CAST(NULL AS VARCHAR(10))) AS VARCHAR(10)) FROM SYSIBM.SYSDUMMY1;
SELECT XMLSERIALIZE(XMLELEMENT(NAME "a", 'x') AS VARCHAR(20)) FROM SYSIBM.SYSDUMMY1;
