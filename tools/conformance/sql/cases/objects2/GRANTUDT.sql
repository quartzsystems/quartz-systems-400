-- oracle: primary
-- GRANT and REVOKE on global variables and types as object authorities.
CREATE TYPE {lib}.GTYP AS DECIMAL(5,2);
CREATE VARIABLE {lib}.GVAR INTEGER DEFAULT 1;
CREATE VARIABLE {lib}.GVAR2 INTEGER DEFAULT 1;
CREATE VARIABLE {lib}.GVAR3 INTEGER DEFAULT 1;
GRANT USAGE ON TYPE {lib}.GTYP TO QUSER;
GRANT ALL ON TYPE {lib}.GTYP TO QPGMR;
GRANT SELECT ON TYPE {lib}.GTYP TO QUSER;
GRANT READ ON VARIABLE {lib}.GVAR TO QUSER;
GRANT WRITE ON VARIABLE {lib}.GVAR TO QPGMR;
GRANT ALL ON VARIABLE {lib}.GVAR2 TO QUSER;
GRANT ALTER ON VARIABLE {lib}.GVAR2 TO QPGMR WITH GRANT OPTION;
GRANT READ, WRITE ON VARIABLE {lib}.GVAR3 TO PUBLIC;
GRANT USAGE ON VARIABLE {lib}.GVAR TO QUSER;
CALL QSYS.QCMDEXC('DSPOBJAUT OBJ({lib}/GTYP) OBJTYPE(*SQLUDT) OUTPUT(*OUTFILE) OUTFILE({lib}/GAUT)                              ', 0000000086.00000);
CALL QSYS.QCMDEXC('DSPOBJAUT OBJ({lib}/GVAR) OBJTYPE(*SRVPGM) OUTPUT(*OUTFILE) OUTFILE({lib}/GAUT) OUTMBR(*FIRST *ADD)                              ', 0000000106.00000);
CALL QSYS.QCMDEXC('DSPOBJAUT OBJ({lib}/GVAR2) OBJTYPE(*SRVPGM) OUTPUT(*OUTFILE) OUTFILE({lib}/GAUT) OUTMBR(*FIRST *ADD)                              ', 0000000107.00000);
CALL QSYS.QCMDEXC('DSPOBJAUT OBJ({lib}/GVAR3) OBJTYPE(*SRVPGM) OUTPUT(*OUTFILE) OUTFILE({lib}/GAUT) OUTMBR(*FIRST *ADD)                              ', 0000000107.00000);
SELECT OANAME, OAUSR, OAOBJA, OAOPR, OAOMGT, OAEXS, OAALT, OAREF, OAREAD, OAADD, OAUPD, OADLT, OAEXEC FROM {lib}.GAUT WHERE OAUSR <> USER ORDER BY OANAME, OAUSR;
REVOKE USAGE ON TYPE {lib}.GTYP FROM QUSER;
REVOKE WRITE ON VARIABLE {lib}.GVAR FROM QPGMR;
REVOKE ALL ON VARIABLE {lib}.GVAR2 FROM QUSER;
REVOKE READ ON VARIABLE {lib}.GVAR FROM QSYSOPR;
CALL QSYS.QCMDEXC('DSPOBJAUT OBJ({lib}/GTYP) OBJTYPE(*SQLUDT) OUTPUT(*OUTFILE) OUTFILE({lib}/GAUT)                              ', 0000000086.00000);
CALL QSYS.QCMDEXC('DSPOBJAUT OBJ({lib}/GVAR) OBJTYPE(*SRVPGM) OUTPUT(*OUTFILE) OUTFILE({lib}/GAUT) OUTMBR(*FIRST *ADD)                              ', 0000000106.00000);
CALL QSYS.QCMDEXC('DSPOBJAUT OBJ({lib}/GVAR2) OBJTYPE(*SRVPGM) OUTPUT(*OUTFILE) OUTFILE({lib}/GAUT) OUTMBR(*FIRST *ADD)                              ', 0000000107.00000);
SELECT OANAME, OAUSR, OAOBJA, OAOPR, OAOMGT, OAEXS, OAALT, OAREF, OAREAD, OAADD, OAUPD, OADLT, OAEXEC FROM {lib}.GAUT WHERE OAUSR <> USER ORDER BY OANAME, OAUSR;
DROP TABLE {lib}.GAUT;
DROP VARIABLE {lib}.GVAR;
DROP VARIABLE {lib}.GVAR2;
DROP VARIABLE {lib}.GVAR3;
DROP TYPE {lib}.GTYP;
