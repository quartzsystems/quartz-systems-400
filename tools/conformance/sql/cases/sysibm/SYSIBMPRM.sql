-- oracle: primary
-- The parameters of the SYSIBM procedures.
SELECT SPECIFIC_NAME, ORDINAL_POSITION, PARAMETER_MODE, PARAMETER_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE FROM QSYS2.SYSPARMS WHERE SPECIFIC_SCHEMA = 'SYSIBM' ORDER BY SPECIFIC_NAME, ORDINAL_POSITION;
