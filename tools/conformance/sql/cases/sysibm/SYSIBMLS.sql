-- oracle: primary
-- The SYSIBM and SYSIBMADM catalog: its tables and views, and its routines.
SELECT TABLE_NAME, TABLE_TYPE, SYSTEM_TABLE_NAME FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = 'SYSIBM' ORDER BY TABLE_NAME;
SELECT TABLE_NAME, TABLE_TYPE, SYSTEM_TABLE_NAME FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = 'SYSIBMADM' ORDER BY TABLE_NAME;
SELECT ROUTINE_NAME, ROUTINE_TYPE, SPECIFIC_NAME, EXTERNAL_NAME FROM QSYS2.SYSROUTINES WHERE ROUTINE_SCHEMA = 'SYSIBM' ORDER BY ROUTINE_NAME, SPECIFIC_NAME;
