-- oracle: pub400
CREATE TABLE {lib}.QPD_OUT (A INTEGER, B VARCHAR(10), C INTEGER);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPD_P1 (IN A INTEGER, IN B VARCHAR(10) DEFAULT 'dft', IN C INTEGER DEFAULT 7)
  LANGUAGE SQL
BEGIN
  INSERT INTO {lib}.QPD_OUT VALUES (A, B, C);
END@
CREATE PROCEDURE {lib}.QPD_P2 (IN A INTEGER DEFAULT 1, OUT B INTEGER DEFAULT 2)
  LANGUAGE SQL
BEGIN
END@
CREATE PROCEDURE {lib}.QPD_P3 (IN A INTEGER DEFAULT NULL, IN D DATE DEFAULT CURRENT DATE)
  LANGUAGE SQL
BEGIN
  INSERT INTO {lib}.QPD_OUT VALUES (A, CASE WHEN D = CURRENT DATE THEN 'today' END, NULL);
END@
--#SET TERMINATOR ;
CALL {lib}.QPD_P1(1);
CALL {lib}.QPD_P1(2, 'x');
CALL {lib}.QPD_P1(3, 'y', 9);
CALL {lib}.QPD_P1(4, C => 5);
CALL {lib}.QPD_P1(C => 6, A => 5);
CALL {lib}.QPD_P1(6, DEFAULT, 8);
CALL {lib}.QPD_P1();
CALL {lib}.QPD_P1(7, D => 1);
CALL {lib}.QPD_P1(8, 'z', 9, 10);
CALL {lib}.QPD_P3();
SELECT A, B, C FROM {lib}.QPD_OUT ORDER BY A;
SELECT ORDINAL_POSITION, PARAMETER_NAME, DEFAULT FROM QSYS2.SYSPARMS WHERE SPECIFIC_SCHEMA = '{lib}' AND SPECIFIC_NAME = 'QPD_P1' ORDER BY ORDINAL_POSITION;
DROP PROCEDURE {lib}.QPD_P1;
