-- oracle: primary
CREATE TABLE {lib}.QPP_CUST (CUSTNO INTEGER NOT NULL PRIMARY KEY, NAME VARCHAR(30) NOT NULL, ORDERS INTEGER NOT NULL);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPP_SAVE (IN P_NO INTEGER, IN P_NAME VARCHAR(30))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_ROWS INTEGER;
  UPDATE {lib}.QPP_CUST SET NAME = P_NAME, ORDERS = ORDERS + 1 WHERE CUSTNO = P_NO;
  GET DIAGNOSTICS V_ROWS = ROW_COUNT;
  IF V_ROWS = 0 THEN
    INSERT INTO {lib}.QPP_CUST VALUES (P_NO, P_NAME, 1);
  END IF;
END@
CREATE PROCEDURE {lib}.QPP_SAVE2 (IN P_NO INTEGER, IN P_NAME VARCHAR(30))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_FOUND INTEGER DEFAULT 1;
  DECLARE V_N INTEGER;
  DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_FOUND = 0;
  SELECT ORDERS INTO V_N FROM {lib}.QPP_CUST WHERE CUSTNO = P_NO;
  IF V_FOUND = 1 THEN
    UPDATE {lib}.QPP_CUST SET ORDERS = V_N + 10 WHERE CUSTNO = P_NO;
  ELSE
    INSERT INTO {lib}.QPP_CUST VALUES (P_NO, UPPER(P_NAME), 0);
  END IF;
END@
