-- oracle: primary
CREATE TABLE {lib}.QPR_TXT (K VARCHAR(10) NOT NULL, V VARCHAR(60));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPR_REVERSE (IN P_IN VARCHAR(40))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_OUT VARCHAR(40) DEFAULT '';
  DECLARE I INTEGER;
  SET I = LENGTH(P_IN);
  WHILE I > 0 DO
    SET V_OUT = V_OUT || SUBSTR(P_IN, I, 1);
    SET I = I - 1;
  END WHILE;
  INSERT INTO {lib}.QPR_TXT VALUES ('REVERSE', V_OUT);
END@
CREATE PROCEDURE {lib}.QPR_WORDS (IN P_IN VARCHAR(60))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_REST VARCHAR(60);
  DECLARE V_POS INTEGER;
  DECLARE V_N INTEGER DEFAULT 0;
  SET V_REST = TRIM(P_IN);
  WHILE LENGTH(V_REST) > 0 DO
    SET V_POS = LOCATE(' ', V_REST);
    SET V_N = V_N + 1;
    IF V_POS = 0 THEN
      INSERT INTO {lib}.QPR_TXT VALUES ('WORD' || TRIM(CHAR(V_N)), V_REST);
      SET V_REST = '';
    ELSE
      INSERT INTO {lib}.QPR_TXT VALUES ('WORD' || TRIM(CHAR(V_N)), SUBSTR(V_REST, 1, V_POS - 1));
      SET V_REST = TRIM(SUBSTR(V_REST, V_POS + 1));
    END IF;
  END WHILE;
END@
CREATE PROCEDURE {lib}.QPR_PAD (IN P_NAME CHAR(10), IN P_N INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V CHAR(12);
  SET V = P_NAME;
  INSERT INTO {lib}.QPR_TXT VALUES ('PAD', '[' || V || ']');
  INSERT INTO {lib}.QPR_TXT VALUES ('RTRIM', '[' || RTRIM(V) || ']');
  INSERT INTO {lib}.QPR_TXT VALUES ('DIGITS', DIGITS(CAST(P_N AS DECIMAL(7,0))));
  INSERT INTO {lib}.QPR_TXT VALUES ('UPPER', UPPER(P_NAME) || LOWER(P_NAME));
END@
--#SET TERMINATOR ;
CALL {lib}.QPR_REVERSE('stressed');
CALL {lib}.QPR_WORDS('  the quick  brown fox ');
CALL {lib}.QPR_PAD('Abc', 42);
SELECT K, V FROM {lib}.QPR_TXT ORDER BY K;
DROP PROCEDURE {lib}.QPR_REVERSE;
DROP PROCEDURE {lib}.QPR_WORDS;
DROP PROCEDURE {lib}.QPR_PAD;
DROP TABLE {lib}.QPR_TXT;
