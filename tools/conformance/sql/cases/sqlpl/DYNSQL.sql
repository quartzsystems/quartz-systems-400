-- oracle: primary
CREATE TABLE {lib}.QPL_CFG (KEYNAME VARCHAR(10) NOT NULL, VAL VARCHAR(20));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPL_PUT (IN P_KEY VARCHAR(10), IN P_VAL VARCHAR(20))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_SQL VARCHAR(200);
  SET V_SQL = 'INSERT INTO {lib}.QPL_CFG VALUES (?, ?)';
  PREPARE S1 FROM V_SQL;
  EXECUTE S1 USING P_KEY, P_VAL;
END@
CREATE PROCEDURE {lib}.QPL_FIX (IN P_TABLE VARCHAR(20), IN P_KEY VARCHAR(10))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_STMT VARCHAR(200);
  SET V_STMT = 'UPDATE {lib}.' || P_TABLE || ' SET VAL = UPPER(VAL) WHERE KEYNAME = ''' || P_KEY || '''';
  EXECUTE IMMEDIATE V_STMT;
END@
CREATE PROCEDURE {lib}.QPL_LIST (IN P_LIKE VARCHAR(10))
  LANGUAGE SQL
  DYNAMIC RESULT SETS 1
BEGIN
  DECLARE V_SQL VARCHAR(200);
  DECLARE C1 CURSOR WITH RETURN FOR S2;
  SET V_SQL = 'SELECT KEYNAME, VAL FROM {lib}.QPL_CFG WHERE KEYNAME LIKE ? ORDER BY KEYNAME';
  PREPARE S2 FROM V_SQL;
  OPEN C1 USING P_LIKE;
END@
--#SET TERMINATOR ;
CALL {lib}.QPL_PUT('COLOR', 'blue');
CALL {lib}.QPL_PUT('CITY', 'oslo');
CALL {lib}.QPL_PUT('SIZE', 'large');
CALL {lib}.QPL_FIX('QPL_CFG', 'CITY');
CALL {lib}.QPL_LIST('C%');
CALL {lib}.QPL_FIX('QPL_NONE', 'X');
DROP PROCEDURE {lib}.QPL_PUT;
DROP PROCEDURE {lib}.QPL_FIX;
DROP PROCEDURE {lib}.QPL_LIST;
DROP TABLE {lib}.QPL_CFG;
