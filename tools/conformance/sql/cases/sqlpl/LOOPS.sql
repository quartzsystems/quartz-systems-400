-- oracle: primary
CREATE TABLE {lib}.QPD_SEQ (KIND CHAR(6) NOT NULL, N INTEGER NOT NULL);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPD_WHILE (IN P_MAX INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE I INTEGER DEFAULT 0;
  WHILE I < P_MAX DO
    SET I = I + 1;
    INSERT INTO {lib}.QPD_SEQ VALUES ('WHILE', I * I);
  END WHILE;
END@
CREATE PROCEDURE {lib}.QPD_REPEAT (IN P_START INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE N INTEGER;
  SET N = P_START;
  REPEAT
    INSERT INTO {lib}.QPD_SEQ VALUES ('REPEAT', N);
    IF MOD(N, 2) = 0 THEN
      SET N = N / 2;
    ELSE
      SET N = 3 * N + 1;
    END IF;
  UNTIL N = 1
  END REPEAT;
END@
CREATE PROCEDURE {lib}.QPD_LOOP ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE I INTEGER DEFAULT 0;
  SCAN: LOOP
    SET I = I + 1;
    IF I > 20 THEN
      LEAVE SCAN;
    END IF;
    IF MOD(I, 3) <> 0 THEN
      ITERATE SCAN;
    END IF;
    INSERT INTO {lib}.QPD_SEQ VALUES ('LOOP', I);
  END LOOP SCAN;
END@
--#SET TERMINATOR ;
CALL {lib}.QPD_WHILE(4);
CALL {lib}.QPD_REPEAT(6);
CALL {lib}.QPD_LOOP;
SELECT KIND, N FROM {lib}.QPD_SEQ ORDER BY KIND, N;
SELECT KIND, COUNT(*), SUM(N) FROM {lib}.QPD_SEQ GROUP BY KIND ORDER BY KIND;
DROP PROCEDURE {lib}.QPD_WHILE;
DROP PROCEDURE {lib}.QPD_REPEAT;
DROP PROCEDURE {lib}.QPD_LOOP;
DROP TABLE {lib}.QPD_SEQ;
