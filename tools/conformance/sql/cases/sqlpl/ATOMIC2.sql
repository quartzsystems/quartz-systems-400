  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  L1: BEGIN ATOMIC
    INSERT INTO QPYSCH.QPY_S VALUES (P);
    IF P > 0 THEN
      LEAVE L1;
    END IF;
    INSERT INTO QPYSCH.QPY_S VALUES (P + 1);
  END L1;
  BEGIN ATOMIC
    INSERT INTO QPYSCH.QPY_S VALUES (P + 2);
    IF P > 0 THEN
      RETURN;
    END IF;
  END;
END@
