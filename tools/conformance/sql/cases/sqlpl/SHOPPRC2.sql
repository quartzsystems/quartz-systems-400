-- Business-day logic as shops write it: scalar functions with loops, a FOR loop over a calendar table, a RETURN status.
CREATE TABLE {lib}.D4Q_HOL (HDATE DATE NOT NULL PRIMARY KEY, HNAME VARCHAR(30) NOT NULL);
INSERT INTO {lib}.D4Q_HOL VALUES ('2026-01-01', 'New year'), ('2026-05-25', 'Memorial day'), ('2026-07-03', 'Independence observed');
CREATE TABLE {lib}.D4Q_OUT (K VARCHAR(20) NOT NULL, V VARCHAR(40));
--#SET TERMINATOR @
CREATE FUNCTION {lib}.D4Q_ISWORK (P_D DATE) RETURNS CHAR(1)
LANGUAGE SQL READS SQL DATA NOT DETERMINISTIC
BEGIN
  IF DAYOFWEEK(P_D) IN (1, 7) THEN
    RETURN 'N';
  END IF;
  IF EXISTS (SELECT 1 FROM {lib}.D4Q_HOL WHERE HDATE = P_D) THEN
    RETURN 'N';
  END IF;
  RETURN 'Y';
END@
CREATE FUNCTION {lib}.D4Q_ADDWORK (P_D DATE, P_N INTEGER) RETURNS DATE
LANGUAGE SQL READS SQL DATA NOT DETERMINISTIC
BEGIN
  DECLARE V_D DATE;
  DECLARE V_LEFT INTEGER;
  SET V_D = P_D;
  SET V_LEFT = P_N;
  WHILE V_LEFT > 0 DO
    SET V_D = V_D + 1 DAY;
    IF {lib}.D4Q_ISWORK(V_D) = 'Y' THEN
      SET V_LEFT = V_LEFT - 1;
    END IF;
  END WHILE;
  RETURN V_D;
END@
CREATE PROCEDURE {lib}.D4Q_LIST (IN P_YEAR INTEGER)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_N INTEGER DEFAULT 0;
  FOR H AS C1 CURSOR FOR SELECT HDATE, HNAME FROM {lib}.D4Q_HOL WHERE YEAR(HDATE) = P_YEAR ORDER BY HDATE DO
    SET V_N = V_N + 1;
    INSERT INTO {lib}.D4Q_OUT VALUES ('hol' CONCAT CHAR(V_N), CHAR(H.HDATE, ISO) CONCAT ' ' CONCAT H.HNAME);
  END FOR;
  IF V_N = 0 THEN
    RETURN 4;
  END IF;
  RETURN 0;
END@
CREATE PROCEDURE {lib}.D4Q_DRIVE ()
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_RC INTEGER;
  CALL {lib}.D4Q_LIST(2026);
  GET DIAGNOSTICS V_RC = RETURN_STATUS;
  INSERT INTO {lib}.D4Q_OUT VALUES ('rc2026', CHAR(V_RC));
  CALL {lib}.D4Q_LIST(1999);
  GET DIAGNOSTICS V_RC = RETURN_STATUS;
  INSERT INTO {lib}.D4Q_OUT VALUES ('rc1999', CHAR(V_RC));
END@
