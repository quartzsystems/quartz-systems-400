-- oracle: primary
CREATE TABLE {lib}.QPC_LOG (CODE CHAR(2) NOT NULL, TXT VARCHAR(20));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPC_STATUS (IN P_CODE CHAR(2))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_TXT VARCHAR(20);
  CASE P_CODE
    WHEN 'OP' THEN SET V_TXT = 'open';
    WHEN 'CL' THEN SET V_TXT = 'closed';
    WHEN 'HD' THEN SET V_TXT = 'held';
    ELSE SET V_TXT = 'unknown';
  END CASE;
  INSERT INTO {lib}.QPC_LOG VALUES (P_CODE, V_TXT);
END@
CREATE PROCEDURE {lib}.QPC_SIZE (IN P_N INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  CASE
    WHEN P_N < 10 THEN INSERT INTO {lib}.QPC_LOG VALUES ('SZ', 'small');
    WHEN P_N < 100 THEN INSERT INTO {lib}.QPC_LOG VALUES ('SZ', 'medium');
    WHEN P_N < 1000 THEN INSERT INTO {lib}.QPC_LOG VALUES ('SZ', 'large');
  END CASE;
END@
--#SET TERMINATOR ;
CALL {lib}.QPC_STATUS('OP');
CALL {lib}.QPC_STATUS('HD');
CALL {lib}.QPC_STATUS('XX');
CALL {lib}.QPC_SIZE(5);
CALL {lib}.QPC_SIZE(500);
CALL {lib}.QPC_SIZE(5000);
SELECT CODE, TXT FROM {lib}.QPC_LOG ORDER BY CODE, TXT;
DROP PROCEDURE {lib}.QPC_STATUS;
DROP PROCEDURE {lib}.QPC_SIZE;
DROP TABLE {lib}.QPC_LOG;
