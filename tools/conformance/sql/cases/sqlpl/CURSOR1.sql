CREATE PROCEDURE {lib}.QPF_REORDER ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_ITEM CHAR(5);
  DECLARE V_ON INTEGER;
  DECLARE V_RE INTEGER;
  DECLARE V_EOF INTEGER DEFAULT 0;
  DECLARE C_ITEMS CURSOR FOR SELECT ITEM, ONHAND, REORDER FROM {lib}.QPF_ITEM ORDER BY ITEM;
  DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_EOF = 1;
  OPEN C_ITEMS;
  FETCH C_ITEMS INTO V_ITEM, V_ON, V_RE;
  WHILE V_EOF = 0 DO
    IF V_ON < V_RE THEN
      INSERT INTO {lib}.QPF_PO VALUES (V_ITEM, V_RE * 2 - V_ON);
    END IF;
    FETCH C_ITEMS INTO V_ITEM, V_ON, V_RE;
  END WHILE;
  CLOSE C_ITEMS;
END@
CREATE PROCEDURE {lib}.QPF_COUNT (IN P_MIN INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_QTY INTEGER;
  DECLARE V_N INTEGER DEFAULT 0;
  DECLARE V_SUM INTEGER DEFAULT 0;
  DECLARE AT_END CHAR(1) DEFAULT 'N';
  DECLARE C2 CURSOR FOR SELECT QTY FROM {lib}.QPF_PO WHERE QTY >= P_MIN;
  DECLARE CONTINUE HANDLER FOR SQLSTATE '02000' SET AT_END = 'Y';
  OPEN C2;
  READ_LOOP: LOOP
    FETCH C2 INTO V_QTY;
    IF AT_END = 'Y' THEN
      LEAVE READ_LOOP;
    END IF;
    SET V_N = V_N + 1;
    SET V_SUM = V_SUM + V_QTY;
  END LOOP;
  CLOSE C2;
  INSERT INTO {lib}.QPF_PO VALUES ('TOTAL', V_SUM);
  INSERT INTO {lib}.QPF_PO VALUES ('COUNT', V_N);
END@
