  RETURNS CHAR(6)
  LANGUAGE SQL
  DETERMINISTIC
BEGIN
  DECLARE V_TIER CHAR(6);
  IF P_AMT >= 100 THEN
    SET V_TIER = 'GOLD';
  ELSEIF P_AMT >= 20 THEN
    SET V_TIER = 'SILVER';
  ELSE
    SET V_TIER = 'BRONZE';
  END IF;
  RETURN V_TIER;
END@
CREATE FUNCTION {lib}.QF1_FACT (N INTEGER) RETURNS BIGINT
  LANGUAGE SQL
BEGIN
  DECLARE R BIGINT DEFAULT 1;
  DECLARE I INTEGER DEFAULT 2;
  WHILE I <= N DO
    SET R = R * I;
    SET I = I + 1;
  END WHILE;
  RETURN R;
END@
CREATE FUNCTION {lib}.QF1_STOCK (P_ITEM CHAR(4)) RETURNS INTEGER
