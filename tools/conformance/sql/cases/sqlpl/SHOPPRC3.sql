-- oracle: primary
-- Error handling in a transfer procedure: SIGNAL with a shop's SQLSTATEs, EXIT and CONTINUE handlers, RESIGNAL, GET DIAGNOSTICS.
CREATE TABLE {lib}.D4R_ACCT (ACCT INTEGER NOT NULL PRIMARY KEY, BAL DECIMAL(11, 2) NOT NULL CHECK (BAL >= 0));
INSERT INTO {lib}.D4R_ACCT VALUES (1, 100.00), (2, 50.00);
CREATE TABLE {lib}.D4R_AUDIT (SEQ INTEGER NOT NULL, NOTE VARCHAR(100) NOT NULL);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.D4R_XFER (IN P_FROM INTEGER, IN P_TO INTEGER, IN P_AMT DECIMAL(11, 2))
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_N INTEGER;
  IF P_AMT <= 0 THEN
    SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'amount must be positive';
  END IF;
  SELECT COUNT(*) INTO V_N FROM {lib}.D4R_ACCT WHERE ACCT IN (P_FROM, P_TO);
  IF V_N < 2 THEN
    SIGNAL SQLSTATE '75002' SET MESSAGE_TEXT = 'no such account';
  END IF;
  UPDATE {lib}.D4R_ACCT SET BAL = BAL - P_AMT WHERE ACCT = P_FROM;
  UPDATE {lib}.D4R_ACCT SET BAL = BAL + P_AMT WHERE ACCT = P_TO;
END@
CREATE PROCEDURE {lib}.D4R_SAFE (IN P_SEQ INTEGER, IN P_FROM INTEGER, IN P_TO INTEGER, IN P_AMT DECIMAL(11, 2))
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_STATE CHAR(5);
  DECLARE V_CODE INTEGER;
  DECLARE V_MSG VARCHAR(70);
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 V_STATE = RETURNED_SQLSTATE, V_MSG = MESSAGE_TEXT;
    GET DIAGNOSTICS CONDITION 1 V_CODE = DB2_RETURNED_SQLCODE;
    INSERT INTO {lib}.D4R_AUDIT VALUES (P_SEQ, V_STATE CONCAT ' ' CONCAT CHAR(V_CODE) CONCAT ' ' CONCAT CASE WHEN V_STATE LIKE '75%' THEN V_MSG ELSE '' END);
  END;
  CALL {lib}.D4R_XFER(P_FROM, P_TO, P_AMT);
  INSERT INTO {lib}.D4R_AUDIT VALUES (P_SEQ, 'ok');
END@
CREATE PROCEDURE {lib}.D4R_STRICT (IN P_AMT DECIMAL(11, 2))
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE EXIT HANDLER FOR SQLSTATE '23513'
    RESIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'insufficient funds';
  CALL {lib}.D4R_XFER(2, 1, P_AMT);
END@
--#SET TERMINATOR ;
CALL {lib}.D4R_SAFE(1, 1, 2, 30.00);
CALL {lib}.D4R_SAFE(2, 1, 2, -5.00);
CALL {lib}.D4R_SAFE(3, 1, 9, 5.00);
CALL {lib}.D4R_SAFE(4, 2, 1, 500.00);
CALL {lib}.D4R_XFER(1, 2, 0);
CALL {lib}.D4R_STRICT(1000.00);
CALL {lib}.D4R_STRICT(10.00);
SELECT SEQ, NOTE FROM {lib}.D4R_AUDIT ORDER BY SEQ;
SELECT ACCT, BAL FROM {lib}.D4R_ACCT ORDER BY ACCT;
DROP PROCEDURE {lib}.D4R_STRICT;
DROP PROCEDURE {lib}.D4R_SAFE;
DROP PROCEDURE {lib}.D4R_XFER;
DROP TABLE {lib}.D4R_AUDIT;
DROP TABLE {lib}.D4R_ACCT;
