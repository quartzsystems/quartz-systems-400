-- oracle: primary
CREATE TABLE {lib}.QPM_RES (WHO VARCHAR(10) NOT NULL, A INTEGER, B VARCHAR(20));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPM_CALC (IN P_X INTEGER, OUT P_SQ INTEGER, INOUT P_ACC INTEGER, OUT P_TXT VARCHAR(20))
  LANGUAGE SQL
BEGIN
  SET P_SQ = P_X * P_X;
  SET P_ACC = P_ACC + P_SQ;
  SET P_TXT = 'x=' || TRIM(CHAR(P_X));
END@
CREATE PROCEDURE {lib}.QPM_DRIVER (IN P_N INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE I INTEGER DEFAULT 1;
  DECLARE V_SQ INTEGER;
  DECLARE V_ACC INTEGER DEFAULT 0;
  DECLARE V_TXT VARCHAR(20);
  WHILE I <= P_N DO
    CALL {lib}.QPM_CALC(I, V_SQ, V_ACC, V_TXT);
    INSERT INTO {lib}.QPM_RES VALUES ('STEP', V_SQ, V_TXT);
    SET I = I + 1;
  END WHILE;
  INSERT INTO {lib}.QPM_RES VALUES ('TOTAL', V_ACC, NULL);
END@
CREATE PROCEDURE {lib}.QPM_NULLS ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_SQ INTEGER DEFAULT 7;
  DECLARE V_ACC INTEGER;
  DECLARE V_TXT VARCHAR(20) DEFAULT 'kept';
  CALL {lib}.QPM_CALC(NULL, V_SQ, V_ACC, V_TXT);
  INSERT INTO {lib}.QPM_RES VALUES ('NULLS', V_SQ, COALESCE(V_TXT, 'null text'));
  INSERT INTO {lib}.QPM_RES VALUES ('NULLACC', COALESCE(V_ACC, -1), NULL);
END@
--#SET TERMINATOR ;
CALL {lib}.QPM_DRIVER(4);
CALL {lib}.QPM_NULLS;
SELECT WHO, A, B FROM {lib}.QPM_RES ORDER BY WHO, A;
DROP PROCEDURE {lib}.QPM_DRIVER;
DROP PROCEDURE {lib}.QPM_NULLS;
DROP PROCEDURE {lib}.QPM_CALC;
DROP TABLE {lib}.QPM_RES;
