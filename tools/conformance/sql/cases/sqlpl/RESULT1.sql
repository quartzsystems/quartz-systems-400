CREATE PROCEDURE {lib}.QPG_BY_DEPT (IN P_DEPT CHAR(3))
  LANGUAGE SQL
  READS SQL DATA
  DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR
    SELECT EMPNO, NAME, SALARY FROM {lib}.QPG_EMP WHERE DEPT = P_DEPT ORDER BY EMPNO;
  OPEN C1;
END@
CREATE PROCEDURE {lib}.QPG_SUMMARY ()
  LANGUAGE SQL
  DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C2 CURSOR WITH RETURN TO CALLER FOR
    SELECT DEPT, COUNT(*) AS HEADS, SUM(SALARY) AS PAYROLL FROM {lib}.QPG_EMP GROUP BY DEPT ORDER BY DEPT;
  OPEN C2;
END@
CREATE PROCEDURE {lib}.QPG_NONE ()
  LANGUAGE SQL
  DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C3 CURSOR WITH RETURN FOR SELECT EMPNO FROM {lib}.QPG_EMP;
  DECLARE V CHAR(4);
  OPEN C3;
  FETCH C3 INTO V;
  CLOSE C3;
END@
