CREATE PROCEDURE {lib}.QPZ_BUILD (IN P_ROWS INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE I INTEGER DEFAULT 0;
  DECLARE CONTINUE HANDLER FOR SQLSTATE '42704' BEGIN END;
  DROP TABLE {lib}.QPZ_WORK;
  CREATE TABLE {lib}.QPZ_WORK (N INTEGER NOT NULL, SQUARE INTEGER, LABEL VARCHAR(12));
  WHILE I < P_ROWS DO
    SET I = I + 1;
    INSERT INTO {lib}.QPZ_WORK VALUES (I, I * I, 'row ' || TRIM(CHAR(I)));
  END WHILE;
  CREATE INDEX {lib}.QPZ_WORKX ON {lib}.QPZ_WORK (SQUARE DESC);
END@
CREATE PROCEDURE {lib}.QPZ_SHOW ()
  LANGUAGE SQL
  DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR SELECT N, SQUARE, LABEL FROM {lib}.QPZ_WORK WHERE SQUARE > 4 ORDER BY SQUARE DESC;
  OPEN C1;
END@
--#SET TERMINATOR ;
CALL {lib}.QPZ_BUILD(3);
CALL {lib}.QPZ_BUILD(5);
CALL {lib}.QPZ_SHOW;
DROP PROCEDURE {lib}.QPZ_BUILD;
DROP PROCEDURE {lib}.QPZ_SHOW;
DROP TABLE {lib}.QPZ_WORK;
