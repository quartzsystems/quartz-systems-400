-- oracle: primary
CREATE TABLE {lib}.QPS_LOG (WHAT VARCHAR(20) NOT NULL, N INTEGER, ST CHAR(5));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPS_P1 ()
  LANGUAGE SQL
BEGIN
  DECLARE V_CODE INTEGER;
  DECLARE V_STATE CHAR(5);
  DECLARE V_N INTEGER;
  DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
    BEGIN
      GET STACKED DIAGNOSTICS CONDITION 1 V_CODE = DB2_RETURNED_SQLCODE, V_STATE = RETURNED_SQLSTATE;
      INSERT INTO {lib}.QPS_LOG VALUES ('stacked1', V_CODE, V_STATE);
      GET DIAGNOSTICS V_N = ROW_COUNT;
      INSERT INTO {lib}.QPS_LOG VALUES ('current', V_N, NULL);
      GET STACKED DIAGNOSTICS EXCEPTION 1 V_CODE = DB2_RETURNED_SQLCODE, V_STATE = RETURNED_SQLSTATE;
      INSERT INTO {lib}.QPS_LOG VALUES ('stacked2', V_CODE, V_STATE);
    END;
  INSERT INTO {lib}.QPS_LOG VALUES (NULL, 1, NULL);
  SET V_N = 1 / 0;
END@
CREATE PROCEDURE {lib}.QPS_P2 ()
  LANGUAGE SQL
BEGIN
  DECLARE V_CODE INTEGER DEFAULT 7;
  GET STACKED DIAGNOSTICS CONDITION 1 V_CODE = DB2_RETURNED_SQLCODE;
  INSERT INTO {lib}.QPS_LOG VALUES ('outside', V_CODE, NULL);
END@
--#SET TERMINATOR ;
CALL {lib}.QPS_P1();
CALL {lib}.QPS_P2();
SELECT WHAT, N, ST FROM {lib}.QPS_LOG ORDER BY WHAT;
DROP PROCEDURE {lib}.QPS_P1;
DROP PROCEDURE {lib}.QPS_P2;
DROP TABLE {lib}.QPS_LOG;
