-- oracle: pub400
CREATE TABLE {lib}.QPB_OUT (K VARCHAR(10) NOT NULL, B BOOLEAN, N INTEGER);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPB_P1 ()
  LANGUAGE SQL
BEGIN
  DECLARE F BOOLEAN DEFAULT FALSE;
  DECLARE T BOOLEAN;
  INSERT INTO {lib}.QPB_OUT VALUES ('NULL', T, NULL);
  SET T = 1 < 2;
  INSERT INTO {lib}.QPB_OUT VALUES ('T', T, NULL);
  IF T AND NOT F THEN
    INSERT INTO {lib}.QPB_OUT VALUES ('IF', T, 1);
  END IF;
  SET F = T;
  INSERT INTO {lib}.QPB_OUT VALUES ('F', F, NULL);
  SET T = 'no';
  INSERT INTO {lib}.QPB_OUT VALUES ('NO', T, NULL);
END@
--#SET TERMINATOR ;
CALL {lib}.QPB_P1();
SELECT K, B, N FROM {lib}.QPB_OUT ORDER BY K;
DROP PROCEDURE {lib}.QPB_P1;
DROP TABLE {lib}.QPB_OUT;
