-- oracle: primary
CREATE TABLE {lib}.QPO_TRACE (SEQ INTEGER NOT NULL, TXT VARCHAR(30));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPO_NEST (IN P_STOP INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
OUTER_BLOCK: BEGIN
  DECLARE N INTEGER DEFAULT 0;
  INNER_BLOCK: BEGIN
    DECLARE N INTEGER DEFAULT 100;
    SET N = N + 1;
    INSERT INTO {lib}.QPO_TRACE VALUES (1, 'inner n ' || TRIM(CHAR(N)));
    SET OUTER_BLOCK.N = 5;
    IF P_STOP = 1 THEN
      LEAVE OUTER_BLOCK;
    END IF;
    INSERT INTO {lib}.QPO_TRACE VALUES (2, 'inner continued');
  END INNER_BLOCK;
  INSERT INTO {lib}.QPO_TRACE VALUES (3, 'outer n ' || TRIM(CHAR(N)));
END OUTER_BLOCK@
CREATE PROCEDURE {lib}.QPO_GOTO (IN P INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  IF P > 0 THEN
    GOTO POSITIVE;
  END IF;
  INSERT INTO {lib}.QPO_TRACE VALUES (10 + P, 'not positive');
  GOTO DONE;
  POSITIVE: INSERT INTO {lib}.QPO_TRACE VALUES (20 + P, 'positive');
  DONE: INSERT INTO {lib}.QPO_TRACE VALUES (30 + P, 'done');
END@
CREATE PROCEDURE {lib}.QPO_PARMQ (IN COUNT INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE COUNT INTEGER DEFAULT 7;
  INSERT INTO {lib}.QPO_TRACE VALUES (40, 'local ' || TRIM(CHAR(COUNT)) || ' parm ' || TRIM(CHAR(QPO_PARMQ.COUNT)));
END@
--#SET TERMINATOR ;
CALL {lib}.QPO_NEST(0);
CALL {lib}.QPO_NEST(1);
CALL {lib}.QPO_GOTO(1);
CALL {lib}.QPO_GOTO(0);
CALL {lib}.QPO_PARMQ(3);
SELECT SEQ, TXT FROM {lib}.QPO_TRACE ORDER BY SEQ, TXT;
DROP PROCEDURE {lib}.QPO_NEST;
DROP PROCEDURE {lib}.QPO_GOTO;
DROP PROCEDURE {lib}.QPO_PARMQ;
DROP TABLE {lib}.QPO_TRACE;
