-- oracle: primary
-- Housekeeping procedures with dynamic SQL: purge by a built statement, EXECUTE IMMEDIATE, PREPARE and EXECUTE USING, labels and LEAVE.
CREATE TABLE {lib}.D4S_HIST (ID INTEGER NOT NULL, KIND CHAR(1) NOT NULL, AGE INTEGER NOT NULL);
INSERT INTO {lib}.D4S_HIST VALUES (1, 'A', 10), (2, 'A', 400), (3, 'B', 800), (4, 'B', 20), (5, 'C', 999);
CREATE TABLE {lib}.D4S_LOG (STEP INTEGER NOT NULL, TXT VARCHAR(100) NOT NULL);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.D4S_PURGE (IN P_KIND CHAR(1), IN P_DAYS INTEGER, OUT P_GONE INTEGER)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_SQL VARCHAR(200);
  SET V_SQL = 'DELETE FROM {lib}.D4S_HIST WHERE KIND = ? AND AGE > ?';
  PREPARE S1 FROM V_SQL;
  EXECUTE S1 USING P_KIND, P_DAYS;
  GET DIAGNOSTICS P_GONE = ROW_COUNT;
END@
CREATE PROCEDURE {lib}.D4S_RUN ()
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_I INTEGER DEFAULT 0;
  DECLARE V_GONE INTEGER;
  DECLARE V_K CHAR(1);
  DECLARE V_SQL VARCHAR(100);
  L1: LOOP
    SET V_I = V_I + 1;
    IF V_I > 5 THEN
      LEAVE L1;
    END IF;
    SET V_K = SUBSTR('ABCXY', V_I, 1);
    IF V_K = 'X' THEN
      ITERATE L1;
    END IF;
    CALL {lib}.D4S_PURGE(V_K, 365, V_GONE);
    INSERT INTO {lib}.D4S_LOG VALUES (V_I, 'kind ' CONCAT V_K CONCAT ' purged ' CONCAT CHAR(V_GONE));
  END LOOP L1;
  SET V_SQL = 'INSERT INTO {lib}.D4S_LOG VALUES (99, ''done'')';
  EXECUTE IMMEDIATE V_SQL;
END@
--#SET TERMINATOR ;
CALL {lib}.D4S_RUN();
SELECT STEP, TXT FROM {lib}.D4S_LOG ORDER BY STEP;
SELECT ID, KIND, AGE FROM {lib}.D4S_HIST ORDER BY ID;
DROP PROCEDURE {lib}.D4S_RUN;
DROP PROCEDURE {lib}.D4S_PURGE;
DROP TABLE {lib}.D4S_LOG;
DROP TABLE {lib}.D4S_HIST;
