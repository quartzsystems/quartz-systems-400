DROP PROCEDURE {lib}.D4G_EXI;
DROP FUNCTION {lib}.D4G_FCUR;
DROP PROCEDURE {lib}.D4G_AUT;
DROP PROCEDURE {lib}.D4G_LOC;
DROP PROCEDURE {lib}.D4G_RS;
DROP TABLE {lib}.D4G_T;
