-- oracle: primary
-- SQL PL forms QS/400 refuses (each with its SQLCODE) next to what the primary does: ALLOCATE and ASSOCIATE LOCATORS, AUTONOMOUS, cursors in functions, EXECUTE ... INTO.
CREATE TABLE {lib}.D4G_T (K INTEGER);
INSERT INTO {lib}.D4G_T VALUES (1), (2);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.D4G_RS () LANGUAGE SQL DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR SELECT K FROM {lib}.D4G_T ORDER BY K;
  OPEN C1;
END@
CREATE PROCEDURE {lib}.D4G_LOC (OUT P_K INTEGER) LANGUAGE SQL
BEGIN
  DECLARE V_RS RESULT_SET_LOCATOR VARYING;
  CALL {lib}.D4G_RS();
  ASSOCIATE RESULT SET LOCATOR (V_RS) WITH PROCEDURE {lib}.D4G_RS;
  ALLOCATE C2 CURSOR FOR RESULT SET V_RS;
  FETCH C2 INTO P_K;
  CLOSE C2;
END@
CREATE PROCEDURE {lib}.D4G_AUT () LANGUAGE SQL AUTONOMOUS
BEGIN
  INSERT INTO {lib}.D4G_T VALUES (3);
END@
CREATE FUNCTION {lib}.D4G_FCUR () RETURNS INTEGER LANGUAGE SQL
BEGIN
  DECLARE V INTEGER DEFAULT 0;
  DECLARE C3 CURSOR FOR SELECT K FROM {lib}.D4G_T;
  OPEN C3;
  FETCH C3 INTO V;
  CLOSE C3;
  RETURN V;
END@
CREATE PROCEDURE {lib}.D4G_EXI (OUT P_N INTEGER) LANGUAGE SQL
BEGIN
  DECLARE V_SQL VARCHAR(100);
  SET V_SQL = 'SELECT COUNT(*) FROM {lib}.D4G_T';
  PREPARE S1 FROM V_SQL;
  EXECUTE S1 INTO P_N;
END@
