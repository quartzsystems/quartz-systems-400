CREATE TABLE {lib}.QPA_OUT (K VARCHAR(10) NOT NULL, N DECIMAL(11,2), S VARCHAR(40));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPA_SET1 (IN P_QTY INTEGER, IN P_PRICE DECIMAL(9,2))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_TOTAL DECIMAL(11,2) DEFAULT 0;
  DECLARE V_DISC DECIMAL(5,2) DEFAULT 0.10;
  DECLARE V_LABEL VARCHAR(40);
  SET V_TOTAL = P_QTY * P_PRICE;
  SET V_TOTAL = V_TOTAL - V_TOTAL * V_DISC;
  SET V_LABEL = 'qty ' || CHAR(P_QTY) || ' at ' || CHAR(P_PRICE);
  INSERT INTO {lib}.QPA_OUT VALUES ('SET1', V_TOTAL, V_LABEL);
END@
CREATE PROCEDURE {lib}.QPA_SET2 ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE A INTEGER DEFAULT 1;
  DECLARE B INTEGER DEFAULT 2;
  DECLARE C INTEGER;
  DECLARE T VARCHAR(40);
  SET (A, B) = (B, A);
  SET C = A * 10 + B;
  VALUES 'swapped ' || TRIM(CHAR(C)) INTO T;
  INSERT INTO {lib}.QPA_OUT VALUES ('SET2', C, T);
  SET C = NULL;
  INSERT INTO {lib}.QPA_OUT VALUES ('SET2N', C, COALESCE(CHAR(C), 'was null'));
END@
--#SET TERMINATOR ;
CALL {lib}.QPA_SET1(3, 12.50);
CALL {lib}.QPA_SET1(10, 1.99);
CALL {lib}.QPA_SET2;
SELECT K, N, S FROM {lib}.QPA_OUT ORDER BY K, N;
DROP PROCEDURE {lib}.QPA_SET1;
DROP PROCEDURE {lib}.QPA_SET2;
DROP TABLE {lib}.QPA_OUT;
