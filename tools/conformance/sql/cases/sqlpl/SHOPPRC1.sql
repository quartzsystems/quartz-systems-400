-- oracle: primary
-- Shop procedures over an order table: post an order, price it with a cursor loop, close stale orders, report with a result set.
CREATE TABLE {lib}.D4P_ORD (ORD_NO INTEGER NOT NULL PRIMARY KEY, CUST CHAR(6) NOT NULL, STATUS CHAR(1) NOT NULL DEFAULT 'O', TOTAL DECIMAL(11, 2) NOT NULL DEFAULT 0, ORD_DATE DATE NOT NULL);
CREATE TABLE {lib}.D4P_LIN (ORD_NO INTEGER NOT NULL, LIN SMALLINT NOT NULL, QTY INTEGER NOT NULL, PRICE DECIMAL(9, 2) NOT NULL, PRIMARY KEY (ORD_NO, LIN));
CREATE TABLE {lib}.D4P_LOG (MSG VARCHAR(80) NOT NULL);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.D4P_POST (IN P_ORD INTEGER, IN P_CUST CHAR(6), IN P_DATE DATE, OUT P_RC INTEGER)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE CONTINUE HANDLER FOR SQLSTATE '23505' SET P_RC = -1;
  SET P_RC = 0;
  INSERT INTO {lib}.D4P_ORD (ORD_NO, CUST, ORD_DATE) VALUES (P_ORD, P_CUST, P_DATE);
  IF P_RC = 0 THEN
    INSERT INTO {lib}.D4P_LOG VALUES ('posted ' CONCAT CHAR(P_ORD));
  ELSE
    INSERT INTO {lib}.D4P_LOG VALUES ('duplicate ' CONCAT CHAR(P_ORD));
  END IF;
END@
CREATE PROCEDURE {lib}.D4P_PRICE (IN P_ORD INTEGER, OUT P_TOTAL DECIMAL(11, 2), OUT P_LINES INTEGER)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_QTY INTEGER;
  DECLARE V_PRICE DECIMAL(9, 2);
  DECLARE V_EOF INTEGER DEFAULT 0;
  DECLARE C1 CURSOR FOR SELECT QTY, PRICE FROM {lib}.D4P_LIN WHERE ORD_NO = P_ORD ORDER BY LIN;
  DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_EOF = 1;
  SET P_TOTAL = 0;
  SET P_LINES = 0;
  OPEN C1;
  FETCH C1 INTO V_QTY, V_PRICE;
  WHILE V_EOF = 0 DO
    SET P_TOTAL = P_TOTAL + V_QTY * V_PRICE;
    SET P_LINES = P_LINES + 1;
    FETCH C1 INTO V_QTY, V_PRICE;
  END WHILE;
  CLOSE C1;
  UPDATE {lib}.D4P_ORD SET TOTAL = P_TOTAL WHERE ORD_NO = P_ORD;
END@
CREATE PROCEDURE {lib}.D4P_CLOSE (IN P_BEFORE DATE, OUT P_CLOSED INTEGER)
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  UPDATE {lib}.D4P_ORD SET STATUS = 'C' WHERE STATUS = 'O' AND ORD_DATE < P_BEFORE;
  GET DIAGNOSTICS P_CLOSED = ROW_COUNT;
END@
CREATE PROCEDURE {lib}.D4P_REPORT (IN P_CUST CHAR(6))
LANGUAGE SQL READS SQL DATA DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C2 CURSOR WITH RETURN FOR SELECT ORD_NO, STATUS, TOTAL FROM {lib}.D4P_ORD WHERE CUST = P_CUST ORDER BY ORD_NO;
  OPEN C2;
END@
CREATE PROCEDURE {lib}.D4P_DRIVE ()
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_RC INTEGER;
  DECLARE V_TOT DECIMAL(11, 2);
  DECLARE V_N INTEGER;
  CALL {lib}.D4P_POST(1, 'C00001', '2026-01-10', V_RC);
  INSERT INTO {lib}.D4P_LOG VALUES ('rc ' CONCAT CHAR(V_RC));
  CALL {lib}.D4P_POST(2, 'C00001', '2026-03-01', V_RC);
  CALL {lib}.D4P_POST(1, 'C00002', '2026-01-10', V_RC);
  INSERT INTO {lib}.D4P_LOG VALUES ('rc again ' CONCAT CHAR(V_RC));
  INSERT INTO {lib}.D4P_LIN VALUES (1, 1, 2, 10.00), (1, 2, 1, 5.50), (2, 1, 4, 1.25);
  CALL {lib}.D4P_PRICE(1, V_TOT, V_N);
  INSERT INTO {lib}.D4P_LOG VALUES ('order 1 ' CONCAT CHAR(V_TOT) CONCAT ' lines ' CONCAT CHAR(V_N));
  CALL {lib}.D4P_PRICE(3, V_TOT, V_N);
  INSERT INTO {lib}.D4P_LOG VALUES ('order 3 ' CONCAT CHAR(V_TOT) CONCAT ' lines ' CONCAT CHAR(V_N));
  CALL {lib}.D4P_CLOSE('2026-02-01', V_N);
  INSERT INTO {lib}.D4P_LOG VALUES ('closed ' CONCAT CHAR(V_N));
END@
