  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
  DECLARE SQLCODE INTEGER DEFAULT 0;
  DECLARE V_ST CHAR(5);
  DECLARE V_CODE INTEGER;
  DECLARE V INTEGER;
  DECLARE CONTINUE HANDLER FOR SQLEXCEPTION, SQLWARNING, NOT FOUND
    SET (V_ST, V_CODE) = (SQLSTATE, SQLCODE);
  INSERT INTO {lib}.QPX_T VALUES (1);
  INSERT INTO {lib}.QPX_LOG VALUES (1, SQLSTATE, SQLCODE);
  INSERT INTO {lib}.QPX_T VALUES (1);
  INSERT INTO {lib}.QPX_LOG VALUES (2, V_ST, V_CODE);
  SELECT ID INTO V FROM {lib}.QPX_T WHERE ID = 99;
  INSERT INTO {lib}.QPX_LOG VALUES (3, V_ST, V_CODE);
END@
--#SET TERMINATOR ;
CALL {lib}.QPX_STATES;
