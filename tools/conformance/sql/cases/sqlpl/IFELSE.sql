CREATE TABLE {lib}.QPB_SCORE (ID INTEGER NOT NULL, SCORE INTEGER, GRADE CHAR(1));
INSERT INTO {lib}.QPB_SCORE (ID, SCORE) VALUES (1, 95), (2, 82), (3, 71), (4, 40), (5, NULL);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPB_GRADE (IN P_ID INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_SCORE INTEGER;
  DECLARE V_GRADE CHAR(1);
  SELECT SCORE INTO V_SCORE FROM {lib}.QPB_SCORE WHERE ID = P_ID;
  IF V_SCORE IS NULL THEN
    SET V_GRADE = '-';
  ELSEIF V_SCORE >= 90 THEN
    SET V_GRADE = 'A';
  ELSEIF V_SCORE >= 80 THEN
    SET V_GRADE = 'B';
  ELSEIF V_SCORE >= 70 THEN
    SET V_GRADE = 'C';
  ELSE
    SET V_GRADE = 'F';
  END IF;
  UPDATE {lib}.QPB_SCORE SET GRADE = V_GRADE WHERE ID = P_ID;
END@
CREATE PROCEDURE {lib}.QPB_ALL ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE I INTEGER DEFAULT 1;
  WHILE I <= 5 DO
    CALL {lib}.QPB_GRADE(I);
    SET I = I + 1;
  END WHILE;
END@
--#SET TERMINATOR ;
CALL {lib}.QPB_ALL();
SELECT ID, SCORE, GRADE FROM {lib}.QPB_SCORE ORDER BY ID;
DROP PROCEDURE {lib}.QPB_ALL;
DROP PROCEDURE {lib}.QPB_GRADE;
