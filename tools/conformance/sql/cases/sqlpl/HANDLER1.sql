-- oracle: primary
CREATE TABLE {lib}.QPH_KEYS (ID INTEGER NOT NULL PRIMARY KEY, NAME VARCHAR(10));
CREATE TABLE {lib}.QPH_LOG (STEP VARCHAR(10) NOT NULL, INFO VARCHAR(40));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPH_LOAD (IN P_FROM INTEGER, IN P_TO INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE I INTEGER;
  DECLARE V_DUPS INTEGER DEFAULT 0;
  DECLARE CONTINUE HANDLER FOR SQLSTATE '23505'
    SET V_DUPS = V_DUPS + 1;
  SET I = P_FROM;
  WHILE I <= P_TO DO
    INSERT INTO {lib}.QPH_KEYS VALUES (I, 'row ' || TRIM(CHAR(I)));
    SET I = I + 1;
  END WHILE;
  INSERT INTO {lib}.QPH_LOG VALUES ('LOAD', 'dups ' || TRIM(CHAR(V_DUPS)));
END@
CREATE PROCEDURE {lib}.QPH_LOAD2 (IN P_FROM INTEGER, IN P_TO INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE I INTEGER;
  DECLARE V_DUPS INTEGER DEFAULT 0;
  DECLARE DUP_KEY CONDITION FOR SQLSTATE '23505';
  DECLARE CONTINUE HANDLER FOR DUP_KEY
    BEGIN
      SET V_DUPS = V_DUPS + 1;
      INSERT INTO {lib}.QPH_LOG VALUES ('DUP', 'key ' || TRIM(CHAR(I)));
    END;
  SET I = P_FROM;
  WHILE I <= P_TO DO
    INSERT INTO {lib}.QPH_KEYS VALUES (I, 'again');
    SET I = I + 1;
  END WHILE;
  INSERT INTO {lib}.QPH_LOG VALUES ('LOAD2', 'dups ' || TRIM(CHAR(V_DUPS)));
END@
CREATE PROCEDURE {lib}.QPH_STOP (IN P_ID INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
    INSERT INTO {lib}.QPH_LOG VALUES ('STOP', 'failed at ' || TRIM(CHAR(P_ID)));
  INSERT INTO {lib}.QPH_LOG VALUES ('STOP', 'before');
  INSERT INTO {lib}.QPH_KEYS VALUES (P_ID, 'stop');
  INSERT INTO {lib}.QPH_LOG VALUES ('STOP', 'after ' || TRIM(CHAR(P_ID)));
END@
