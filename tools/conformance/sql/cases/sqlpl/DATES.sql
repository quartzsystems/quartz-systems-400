CREATE PROCEDURE {lib}.QPQ_DUEDATES (IN P_TODAY DATE)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_DUE DATE;
  FOR R AS SELECT INV, ISSUED, TERMS FROM {lib}.QPQ_DUE DO
    SET V_DUE = ISSUED + TERMS DAYS;
    UPDATE {lib}.QPQ_DUE
      SET DUE = V_DUE, LATE = CASE WHEN V_DUE < P_TODAY THEN 'Y' ELSE 'N' END
      WHERE INV = R.INV;
  END FOR;
END@
CREATE PROCEDURE {lib}.QPQ_MONTHS (IN P_START DATE, IN P_N INTEGER)
  LANGUAGE SQL
  DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C1 CURSOR WITH RETURN FOR
    SELECT INV, DUE, DAYS(DUE) - DAYS(P_START) AS DAYS_LEFT, YEAR(DUE) AS Y, MONTH(DUE) AS M
      FROM {lib}.QPQ_DUE WHERE DUE <= P_START + P_N MONTHS ORDER BY INV;
  OPEN C1;
END@
