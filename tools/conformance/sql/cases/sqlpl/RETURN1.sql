-- oracle: primary
CREATE TABLE {lib}.QPN_RC (P INTEGER, RC INTEGER);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPN_CHECK (IN P INTEGER)
  LANGUAGE SQL
BEGIN
  IF P IS NULL THEN
    RETURN -1;
  END IF;
  IF P > 100 THEN
    RETURN 2;
  END IF;
  IF P > 10 THEN
    RETURN 1;
  END IF;
  RETURN 0;
END@
CREATE PROCEDURE {lib}.QPN_CALLER ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_RC INTEGER;
  DECLARE V INTEGER DEFAULT 5;
  WHILE V < 1000 DO
    CALL {lib}.QPN_CHECK(V);
    GET DIAGNOSTICS V_RC = DB2_RETURN_STATUS;
    INSERT INTO {lib}.QPN_RC VALUES (V, V_RC);
    SET V = V * 5;
  END WHILE;
  CALL {lib}.QPN_CHECK(NULL);
  GET DIAGNOSTICS V_RC = DB2_RETURN_STATUS;
  INSERT INTO {lib}.QPN_RC VALUES (NULL, V_RC);
END@
CREATE PROCEDURE {lib}.QPN_EARLY (IN P INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  INSERT INTO {lib}.QPN_RC VALUES (P, 100);
  IF P = 0 THEN
    RETURN;
  END IF;
  INSERT INTO {lib}.QPN_RC VALUES (P, 200);
END@
--#SET TERMINATOR ;
CALL {lib}.QPN_CALLER;
CALL {lib}.QPN_EARLY(0);
CALL {lib}.QPN_EARLY(1);
CALL {lib}.QPN_CHECK(50);
SELECT P, RC FROM {lib}.QPN_RC ORDER BY P, RC;
DROP PROCEDURE {lib}.QPN_CALLER;
DROP PROCEDURE {lib}.QPN_CHECK;
DROP PROCEDURE {lib}.QPN_EARLY;
DROP TABLE {lib}.QPN_RC;
