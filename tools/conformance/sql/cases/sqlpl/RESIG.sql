CREATE PROCEDURE {lib}.QPJ_INNER (IN P INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE EXIT HANDLER FOR SQLSTATE '23505'
    BEGIN
      INSERT INTO {lib}.QPJ_LOG VALUES ('inner saw a duplicate');
      RESIGNAL SQLSTATE '75100' SET MESSAGE_TEXT = 'duplicate order';
    END;
  INSERT INTO {lib}.QPJ_T VALUES (P);
END@
CREATE PROCEDURE {lib}.QPJ_OUTER (IN P INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_MSG VARCHAR(60);
  DECLARE V_STATE CHAR(5);
  DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
    BEGIN
      GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT, V_STATE = RETURNED_SQLSTATE;
      INSERT INTO {lib}.QPJ_LOG VALUES ('outer caught ' || V_STATE || ': ' || V_MSG);
    END;
  CALL {lib}.QPJ_INNER(P);
  INSERT INTO {lib}.QPJ_LOG VALUES ('outer done ' || TRIM(CHAR(P)));
END@
CREATE PROCEDURE {lib}.QPJ_BARE ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
      INSERT INTO {lib}.QPJ_LOG VALUES ('bare resignal');
      RESIGNAL;
    END;
  INSERT INTO {lib}.QPJ_T VALUES (1);
END@
