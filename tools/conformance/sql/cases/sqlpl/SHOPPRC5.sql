--#SET TERMINATOR @
CREATE FUNCTION {lib}.D4W_PHONE (P CHAR(10)) RETURNS VARCHAR(14) LANGUAGE SQL DETERMINISTIC
  RETURN CASE WHEN P IS NULL THEN NULL ELSE '(' CONCAT SUBSTR(P, 1, 3) CONCAT ') ' CONCAT SUBSTR(P, 4, 3) CONCAT '-' CONCAT SUBSTR(P, 7, 4) END@
CREATE FUNCTION {lib}.D4W_MASK (P CHAR(16)) RETURNS CHAR(16) LANGUAGE SQL DETERMINISTIC
  RETURN REPEAT('*', 12) CONCAT SUBSTR(P, 13, 4)@
CREATE FUNCTION {lib}.D4W_NICKEL (P DECIMAL(9, 2)) RETURNS DECIMAL(9, 2) LANGUAGE SQL DETERMINISTIC
BEGIN
  DECLARE V DECIMAL(11, 4);
  SET V = ROUND(P * 20, 0) / 20;
  RETURN V;
END@
CREATE FUNCTION {lib}.D4W_FY (D DATE) RETURNS SMALLINT LANGUAGE SQL DETERMINISTIC
BEGIN
  IF MONTH(D) >= 7 THEN
    RETURN YEAR(D) + 1;
  END IF;
  RETURN YEAR(D);
END@
CREATE FUNCTION {lib}.D4W_BYFY (P_FY SMALLINT) RETURNS TABLE (ID INTEGER, BAL DECIMAL(9, 2)) LANGUAGE SQL READS SQL DATA
  RETURN SELECT ID, BAL FROM {lib}.D4W_CUST WHERE {lib}.D4W_FY(OPENED) = P_FY@
