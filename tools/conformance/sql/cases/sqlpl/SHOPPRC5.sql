SELECT ID, {lib}.D4W_PHONE(PHONE), {lib}.D4W_MASK(CARD), {lib}.D4W_NICKEL(BAL), {lib}.D4W_FY(OPENED) FROM {lib}.D4W_CUST ORDER BY ID;
SELECT ID FROM {lib}.D4W_CUST WHERE {lib}.D4W_FY(OPENED) = 2026 ORDER BY ID;
SELECT T.ID, T.BAL FROM TABLE({lib}.D4W_BYFY(2027)) AS T ORDER BY T.ID;
CREATE VIEW {lib}.D4W_V AS SELECT ID, {lib}.D4W_PHONE(PHONE) AS PHONE_TEXT FROM {lib}.D4W_CUST;
SELECT * FROM {lib}.D4W_V ORDER BY ID;
