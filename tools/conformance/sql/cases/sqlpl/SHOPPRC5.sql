-- A shop's function library: formatting and rounding scalar functions, a table function, their use in a view and in WHERE.
CREATE TABLE {lib}.D4W_CUST (ID INTEGER NOT NULL, PHONE CHAR(10), CARD CHAR(16), BAL DECIMAL(9, 2), OPENED DATE);
