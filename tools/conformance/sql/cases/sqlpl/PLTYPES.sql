-- oracle: pub400
CREATE TABLE {lib}.QPT_OUT (K VARCHAR(10) NOT NULL, D DECFLOAT(34), G VARGRAPHIC(10) CCSID 1200, B VARBINARY(10), N INTEGER);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPT_ADD (IN A DECFLOAT(16), INOUT T DECFLOAT(34), OUT B VARBINARY(10))
  LANGUAGE SQL
BEGIN
  SET T = T + A;
  SET B = CAST(X'C1C2' AS VARBINARY(10));
END@
CREATE PROCEDURE {lib}.QPT_D ()
  LANGUAGE SQL
BEGIN
  DECLARE DV DECFLOAT(34) DEFAULT 1.10;
  SET DV = DV * 3;
  INSERT INTO {lib}.QPT_OUT VALUES ('D', DV, NULL, NULL, NULL);
END@
CREATE PROCEDURE {lib}.QPT_D16 ()
  LANGUAGE SQL
BEGIN
  DECLARE D16 DECFLOAT(16);
  SET D16 = 1E400;
  INSERT INTO {lib}.QPT_OUT VALUES ('D16', D16, NULL, NULL, NULL);
END@
CREATE PROCEDURE {lib}.QPT_G ()
  LANGUAGE SQL
BEGIN
  DECLARE G GRAPHIC(4) CCSID 1200;
  SET G = 'xy';
  INSERT INTO {lib}.QPT_OUT VALUES ('G', NULL, G, NULL, LENGTH(G));
END@
CREATE PROCEDURE {lib}.QPT_VG ()
  LANGUAGE SQL
BEGIN
  DECLARE VG VARGRAPHIC(10) CCSID 1200 DEFAULT 'ab';
  SET VG = VG CONCAT 'cd';
  INSERT INTO {lib}.QPT_OUT VALUES ('VG', NULL, VG, NULL, LENGTH(VG));
END@
CREATE PROCEDURE {lib}.QPT_BN ()
  LANGUAGE SQL
BEGIN
  DECLARE BN BINARY(3);
  SET BN = CAST(X'0102' AS BINARY(3));
  INSERT INTO {lib}.QPT_OUT VALUES ('BN', NULL, NULL, BN, LENGTH(BN));
END@
CREATE PROCEDURE {lib}.QPT_VB ()
  LANGUAGE SQL
BEGIN
  DECLARE VB VARBINARY(10);
  SET VB = CAST(X'FF' AS VARBINARY(1));
  SET VB = VB CONCAT CAST(X'00EE' AS VARBINARY(2));
  INSERT INTO {lib}.QPT_OUT VALUES ('VB', NULL, NULL, VB, LENGTH(VB));
END@
CREATE PROCEDURE {lib}.QPT_BL ()
  LANGUAGE SQL
BEGIN
  DECLARE BL BLOB(100);
  SET BL = CAST(X'ABCD' AS BLOB(2));
  INSERT INTO {lib}.QPT_OUT VALUES ('BL', NULL, NULL, CAST(BL AS VARBINARY(10)), LENGTH(BL));
END@
CREATE PROCEDURE {lib}.QPT_IN ()
  LANGUAGE SQL
BEGIN
  DECLARE D16 DECFLOAT(16);
  SELECT D INTO D16 FROM {lib}.QPT_OUT WHERE K = 'D';
  INSERT INTO {lib}.QPT_OUT VALUES ('INTO', D16, NULL, NULL, NULL);
END@
CREATE PROCEDURE {lib}.QPT_CL ()
  LANGUAGE SQL
BEGIN
  DECLARE DV DECFLOAT(34) DEFAULT 2;
  DECLARE VB VARBINARY(10);
  CALL {lib}.QPT_ADD(0.5, DV, VB);
  INSERT INTO {lib}.QPT_OUT VALUES ('CALL', DV, NULL, VB, NULL);
END@
