CREATE PROCEDURE {lib}.QPE_TOTALS ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_LAST CHAR(4) DEFAULT '';
  DECLARE V_N INTEGER DEFAULT 0;
  DECLARE V_SUM DECIMAL(11,2) DEFAULT 0;
  DECLARE V_MAX DECIMAL(9,2) DEFAULT 0;
  DECLARE V_BIG INTEGER;
  DELETE FROM {lib}.QPE_TOT;
  FOR R AS SELECT ORDNO, CUST, AMT FROM {lib}.QPE_ORD ORDER BY CUST, ORDNO DO
    IF R.CUST <> V_LAST AND V_LAST <> '' THEN
      INSERT INTO {lib}.QPE_TOT VALUES (V_LAST, V_N, V_SUM, V_BIG);
      SET (V_N, V_SUM, V_MAX) = (0, 0, 0);
    END IF;
    SET V_LAST = CUST;
    SET V_N = V_N + 1;
    SET V_SUM = V_SUM + AMT;
    IF AMT > V_MAX THEN
      SET V_MAX = AMT;
      SET V_BIG = ORDNO;
    END IF;
  END FOR;
  IF V_LAST <> '' THEN
    INSERT INTO {lib}.QPE_TOT VALUES (V_LAST, V_N, V_SUM, V_BIG);
  END IF;
END@
CREATE PROCEDURE {lib}.QPE_RAISE (IN P_PCT DECIMAL(5,2))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  FOR C1 AS CUR1 CURSOR FOR SELECT ORDNO, AMT FROM {lib}.QPE_ORD WHERE CUST = 'BETA' DO
    UPDATE {lib}.QPE_ORD SET AMT = AMT + AMT * P_PCT / 100 WHERE ORDNO = C1.ORDNO;
  END FOR;
END@
