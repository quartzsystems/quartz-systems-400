CREATE TABLE {lib}.QPS_LOAN (MONTH INTEGER NOT NULL, BAL DECIMAL(11,2), INTEREST DECIMAL(9,2), PAID DECIMAL(9,2));
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPS_SCHEDULE (IN P_PRINCIPAL DECIMAL(11,2), IN P_RATE DECIMAL(5,3), IN P_PAY DECIMAL(9,2))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_BAL DECIMAL(11,2);
  DECLARE V_INT DECIMAL(9,2);
  DECLARE V_M INTEGER DEFAULT 0;
  SET V_BAL = P_PRINCIPAL;
  WHILE V_BAL > 0 AND V_M < 24 DO
    SET V_M = V_M + 1;
    SET V_INT = ROUND(V_BAL * P_RATE / 1200, 2);
    IF V_BAL + V_INT < P_PAY THEN
      INSERT INTO {lib}.QPS_LOAN VALUES (V_M, 0, V_INT, V_BAL + V_INT);
      SET V_BAL = 0;
    ELSE
      SET V_BAL = V_BAL + V_INT - P_PAY;
      INSERT INTO {lib}.QPS_LOAN VALUES (V_M, V_BAL, V_INT, P_PAY);
    END IF;
  END WHILE;
END@
CREATE PROCEDURE {lib}.QPS_MIXED ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE D1 DECIMAL(7,3) DEFAULT 1.0005;
  DECLARE N1 NUMERIC(5,1);
  DECLARE I1 SMALLINT;
  DECLARE B1 BIGINT DEFAULT 9000000000;
  DECLARE F1 DOUBLE DEFAULT 2.5E0;
  SET N1 = D1 * 3;
  SET I1 = D1 * 100;
  SET B1 = B1 * 2 + I1;
  INSERT INTO {lib}.QPS_LOAN VALUES (100, N1, I1, D1);
  INSERT INTO {lib}.QPS_LOAN VALUES (101, B1 / 1000000, F1 * 2, NULL);
END@
--#SET TERMINATOR ;
CALL {lib}.QPS_SCHEDULE(1000.00, 6.5, 260.00);
CALL {lib}.QPS_MIXED;
SELECT MONTH, BAL, INTEREST, PAID FROM {lib}.QPS_LOAN ORDER BY MONTH;
DROP PROCEDURE {lib}.QPS_SCHEDULE;
DROP PROCEDURE {lib}.QPS_MIXED;
DROP TABLE {lib}.QPS_LOAN;
