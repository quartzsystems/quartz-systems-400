CREATE PROCEDURE {lib}.QP0_EXT2 (IN P_A INTEGER) LANGUAGE CL EXTERNAL NAME '{lib}/QP0NOCL' PARAMETER STYLE SQL NOT DETERMINISTIC NO SQL;
CREATE PROCEDURE {lib}.QP0_EXT3 (IN P_A INTEGER) LANGUAGE RPGLE EXTERNAL NAME {lib}/QP0NOSRV(DOIT) PARAMETER STYLE GENERAL WITH NULLS PROGRAM TYPE SUB;
CREATE PROCEDURE {lib}.QP0_EXT4 (IN P_A INTEGER) LANGUAGE JAVA EXTERNAL NAME 'Cls.meth' PARAMETER STYLE JAVA;
