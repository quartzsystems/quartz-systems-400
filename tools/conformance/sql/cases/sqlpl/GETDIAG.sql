CREATE TABLE {lib}.QPK_STOCK (ITEM CHAR(3) NOT NULL, QTY INTEGER NOT NULL);
CREATE TABLE {lib}.QPK_LOG (WHAT VARCHAR(20) NOT NULL, N INTEGER, TXT VARCHAR(60));
INSERT INTO {lib}.QPK_STOCK VALUES ('AAA', 1), ('BBB', 2), ('CCC', 3), ('DDD', 4);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPK_ADJUST (IN P_MIN INTEGER, IN P_BY INTEGER)
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_ROWS INTEGER;
  UPDATE {lib}.QPK_STOCK SET QTY = QTY + P_BY WHERE QTY >= P_MIN;
  GET DIAGNOSTICS V_ROWS = ROW_COUNT;
  INSERT INTO {lib}.QPK_LOG VALUES ('updated', V_ROWS, NULL);
  DELETE FROM {lib}.QPK_STOCK WHERE QTY > 100;
  GET DIAGNOSTICS V_ROWS = ROW_COUNT;
  INSERT INTO {lib}.QPK_LOG VALUES ('deleted', V_ROWS, NULL);
END@
CREATE PROCEDURE {lib}.QPK_FAIL ()
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_CODE INTEGER;
  DECLARE V_STATE CHAR(5);
  DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
    BEGIN
      GET DIAGNOSTICS CONDITION 1 V_CODE = DB2_RETURNED_SQLCODE, V_STATE = RETURNED_SQLSTATE;
      INSERT INTO {lib}.QPK_LOG VALUES ('error ' || V_STATE, V_CODE, NULL);
    END;
  INSERT INTO {lib}.QPK_STOCK VALUES ('EEE', NULL);
  INSERT INTO {lib}.QPK_STOCK VALUES ('TOOLONG', 1);
  SELECT QTY INTO V_CODE FROM {lib}.QPK_STOCK;
END@
