CALL {lib}.QPK_ADJUST(3, 10);
CALL {lib}.QPK_ADJUST(1000, 1);
CALL {lib}.QPK_FAIL;
SELECT WHAT, N FROM {lib}.QPK_LOG ORDER BY WHAT, N;
SELECT ITEM, QTY FROM {lib}.QPK_STOCK ORDER BY ITEM;
DROP PROCEDURE {lib}.QPK_ADJUST;
DROP PROCEDURE {lib}.QPK_FAIL;
