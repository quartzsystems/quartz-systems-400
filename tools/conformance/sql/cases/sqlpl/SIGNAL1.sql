-- oracle: primary
CREATE TABLE {lib}.QPI_ACCT (ACCT INTEGER NOT NULL PRIMARY KEY, BAL DECIMAL(11,2) NOT NULL);
INSERT INTO {lib}.QPI_ACCT VALUES (100, 500.00), (200, 20.00);
--#SET TERMINATOR @
CREATE PROCEDURE {lib}.QPI_WITHDRAW (IN P_ACCT INTEGER, IN P_AMT DECIMAL(11,2))
  LANGUAGE SQL
  SET OPTION COMMIT = *NONE
BEGIN
  DECLARE V_BAL DECIMAL(11,2);
  DECLARE V_MSG VARCHAR(70);
  DECLARE NO_ACCT CONDITION FOR SQLSTATE '75002';
  IF P_AMT <= 0 THEN
    SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'amount must be positive';
  END IF;
  SELECT BAL INTO V_BAL FROM {lib}.QPI_ACCT WHERE ACCT = P_ACCT;
  IF V_BAL IS NULL THEN
    SIGNAL NO_ACCT SET MESSAGE_TEXT = 'no such account';
  END IF;
  IF V_BAL < P_AMT THEN
    SET V_MSG = 'insufficient funds in ' || TRIM(CHAR(P_ACCT));
    SIGNAL SQLSTATE VALUE '75003' SET MESSAGE_TEXT = V_MSG;
  END IF;
  UPDATE {lib}.QPI_ACCT SET BAL = BAL - P_AMT WHERE ACCT = P_ACCT;
END@
CREATE PROCEDURE {lib}.QPI_WARN ()
  LANGUAGE SQL
BEGIN
  SIGNAL SQLSTATE '01H01' SET MESSAGE_TEXT = 'just a warning';
END@
--#SET TERMINATOR ;
CALL {lib}.QPI_WITHDRAW(100, 50.25);
CALL {lib}.QPI_WITHDRAW(100, -1);
CALL {lib}.QPI_WITHDRAW(300, 1);
CALL {lib}.QPI_WITHDRAW(200, 25);
CALL {lib}.QPI_WARN();
SELECT ACCT, BAL FROM {lib}.QPI_ACCT ORDER BY ACCT;
DROP PROCEDURE {lib}.QPI_WITHDRAW;
DROP PROCEDURE {lib}.QPI_WARN;
DROP TABLE {lib}.QPI_ACCT;
