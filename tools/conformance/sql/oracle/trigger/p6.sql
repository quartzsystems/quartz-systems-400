-- Sixth probe: SQL trigger names and replacement, the default mode of a BEFORE
-- trigger, SYSTRIGUPD, the program a trigger makes and whether it goes with it,
-- LABEL ON TRIGGER, a statement trigger over OLD TABLE, and an AFTER trigger
-- failing in the middle of a multiple-row insert.
-- cmd DLTF FILE(QSTEST/STRG2)
-- cmd DLTF FILE(QSTEST/STRGLOG)
CREATE TABLE QSTEST.STRG2 (ID INT NOT NULL, NAME CHAR(10), AMT DECIMAL(7, 2));
CREATE TABLE QSTEST.STRGLOG (TXT VARCHAR(100), N INT);
CREATE TRIGGER QSTEST.TRC1 BEFORE UPDATE OF NAME, AMT ON QSTEST.STRG2 REFERENCING NEW AS N FOR EACH ROW SET N.NAME = UPPER(N.NAME);
CREATE TRIGGER QSTEST.TRC1 AFTER DELETE ON QSTEST.STRG2 FOR EACH ROW INSERT INTO QSTEST.STRGLOG VALUES ('DUP', 0);
CREATE OR REPLACE TRIGGER QSTEST.TRC1 BEFORE UPDATE OF NAME ON QSTEST.STRG2 REFERENCING NEW AS N FOR EACH ROW SET N.NAME = LOWER(N.NAME);
SELECT TRIGGER_NAME, EVENT_MANIPULATION, ACTION_TIMING, TRIGGER_MODE, ACTION_ORDER, TRIGGER_PROGRAM_NAME, ALLOW_REPEATED_CHANGE, TRIGGER_UPDATE_CONDITION FROM QSYS2.SYSTRIGGERS WHERE TRIGGER_SCHEMA = 'QSTEST' AND EVENT_OBJECT_TABLE = 'STRG2';
SELECT * FROM QSYS2.SYSTRIGUPD WHERE TRIGGER_SCHEMA = 'QSTEST';
SELECT * FROM QSYS2.SYSPROGRAMSTAT WHERE PROGRAM_SCHEMA = 'QSTEST' AND PROGRAM_NAME LIKE 'TRC%';
CREATE TRIGGER QSTEST.TRC2 AFTER DELETE ON QSTEST.STRG2 REFERENCING OLD TABLE AS OT FOR EACH STATEMENT MODE DB2SQL INSERT INTO QSTEST.STRGLOG SELECT 'DEL ' CONCAT NAME, ID FROM OT;
CREATE TRIGGER QSTEST.TRC3 AFTER INSERT ON QSTEST.STRG2 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW WHEN (N.ID = 3) SIGNAL SQLSTATE '75002' SET MESSAGE_TEXT = 'three';
CREATE TRIGGER QSTEST.TRC4 AFTER UPDATE ON QSTEST.STRG2 REFERENCING OLD AS O NEW AS N FOR EACH ROW MODE DB2SQL INSERT INTO QSTEST.STRGLOG VALUES (O.NAME CONCAT '>' CONCAT N.NAME, N.ID);
LABEL ON TRIGGER QSTEST.TRC2 IS 'deleted rows';
COMMENT ON TRIGGER QSTEST.TRC2 IS 'a long comment';
SELECT TRIGGER_NAME, TRIGGER_TEXT, LONG_COMMENT FROM QSYS2.SYSTRIGGERS WHERE TRIGGER_NAME = 'TRC2';
INSERT INTO QSTEST.STRG2 VALUES (1, 'a', 1), (2, 'b', 2), (3, 'c', 3), (4, 'd', 4);
SELECT ID, NAME FROM QSTEST.STRG2 ORDER BY ID;
UPDATE QSTEST.STRG2 SET NAME = 'NEW' WHERE ID = 1;
UPDATE QSTEST.STRG2 SET AMT = 9 WHERE ID = 2;
SELECT ID, NAME, AMT FROM QSTEST.STRG2 ORDER BY ID;
DELETE FROM QSTEST.STRG2;
SELECT TXT, N FROM QSTEST.STRGLOG ORDER BY TXT;
DROP TRIGGER QSTEST.TRC1;
SELECT PROGRAM_NAME FROM QSYS2.SYSPROGRAMSTAT WHERE PROGRAM_SCHEMA = 'QSTEST' AND PROGRAM_NAME LIKE 'TRC%' ORDER BY PROGRAM_NAME;
DROP TABLE QSTEST.STRG2;
SELECT PROGRAM_NAME FROM QSYS2.SYSPROGRAMSTAT WHERE PROGRAM_SCHEMA = 'QSTEST' AND PROGRAM_NAME LIKE 'TRC%' ORDER BY PROGRAM_NAME;
DROP TABLE QSTEST.STRGLOG;
