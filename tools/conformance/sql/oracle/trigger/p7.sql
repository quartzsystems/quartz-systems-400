-- Read triggers and SQL on the primary: which rows a query's reads fire for (every row
-- read, or only those it keeps), through an index, a view, a join, COUNT, FETCH FIRST,
-- UPDATE and DELETE, INSERT ... SELECT. TRGDUMP sends each buffer to QSTEST/TRGQ.
-- cmd DLTF FILE(QSTEST/RDTV)
-- cmd DLTF FILE(QSTEST/RDTIX)
-- cmd DLTF FILE(QSTEST/RDT)
-- cmd DLTF FILE(QSTEST/RDT2)
-- cmd DLTPGM PGM(QSTEST/TRGDUMP)
-- cmd DLTDTAQ DTAQ(QSTEST/TRGQ)
-- cmd DLTF FILE(QSTEST/QTRGSRC)
-- cmd CRTSRCPF FILE(QSTEST/QTRGSRC) RCDLEN(92)
-- cmd ADDPFM FILE(QSTEST/QTRGSRC) MBR(TRGDUMP) SRCTYPE(CLLE)
-- cmd CRTDTAQ DTAQ(QSTEST/TRGQ) MAXLEN(4000)
CREATE ALIAS QSTEST.TRGSRCM FOR QSTEST.QTRGSRC(TRGDUMP);
INSERT INTO QSTEST.TRGSRCM VALUES
 (1, 0, '             PGM        PARM(&BUF &LEN)'),
 (2, 0, '             DCL        VAR(&BUF) TYPE(*CHAR) LEN(3000)'),
 (3, 0, '             DCL        VAR(&LEN) TYPE(*CHAR) LEN(4)'),
 (4, 0, '             DCL        VAR(&N) TYPE(*DEC) LEN(5 0)'),
 (5, 0, '             DCL        VAR(&OFF) TYPE(*DEC) LEN(9 0)'),
 (6, 0, '             DCL        VAR(&ST) TYPE(*DEC) LEN(9 0)'),
 (7, 0, '             DCL        VAR(&ONE) TYPE(*CHAR) LEN(16)'),
 (8, 0, '             CHGVAR     VAR(&OFF) VALUE(%BIN(&BUF 49 4))'),
 (9, 0, '             CHGVAR     VAR(&ST) VALUE(&OFF + 1)'),
 (10, 0, '             CHGVAR     VAR(&ONE) VALUE(%SST(&BUF 31 1) *CAT %SST(&BUF &ST 9))'),
 (11, 0, '             CHGVAR     VAR(&N) VALUE(10)'),
 (12, 0, '             CALL       PGM(QSNDDTAQ) PARM(''TRGQ'' ''QSTEST'' &N &ONE)'),
 (13, 0, '             ENDPGM');
DROP ALIAS QSTEST.TRGSRCM;
-- cmd CRTBNDCL PGM(QSTEST/TRGDUMP) SRCFILE(QSTEST/QTRGSRC) SRCMBR(TRGDUMP)
-- joblog
CREATE TABLE QSTEST.RDT (K INT NOT NULL, V CHAR(5));
CREATE TABLE QSTEST.RDT2 (K INT NOT NULL, V CHAR(5));
INSERT INTO QSTEST.RDT VALUES (1, 'aaaaa'), (2, 'bbbbb'), (3, 'ccccc');
-- cmd ADDPFTRG FILE(QSTEST/RDT) TRGTIME(*AFTER) TRGEVENT(*READ) PGM(QSTEST/TRGDUMP) TRG(RD1)
-- joblog
SELECT K, V FROM QSTEST.RDT ORDER BY K;
-- dtaq TRGQ
SELECT V FROM QSTEST.RDT WHERE K = 2;
-- dtaq TRGQ
SELECT COUNT(*) FROM QSTEST.RDT;
-- dtaq TRGQ
SELECT K FROM QSTEST.RDT FETCH FIRST 1 ROW ONLY;
-- dtaq TRGQ
SELECT A.K FROM QSTEST.RDT A JOIN QSTEST.RDT B ON A.K = B.K WHERE A.K < 3 ORDER BY 1;
-- dtaq TRGQ
VALUES (SELECT V FROM QSTEST.RDT WHERE K = 1);
-- dtaq TRGQ
CREATE INDEX QSTEST.RDTIX ON QSTEST.RDT (K);
SELECT V FROM QSTEST.RDT WHERE K = 3;
-- dtaq TRGQ
CREATE VIEW QSTEST.RDTV AS SELECT K, V FROM QSTEST.RDT WHERE K > 1;
SELECT K FROM QSTEST.RDTV ORDER BY K;
-- dtaq TRGQ
UPDATE QSTEST.RDT SET V = 'uuuuu' WHERE K = 1;
-- dtaq TRGQ
DELETE FROM QSTEST.RDT WHERE K = 99;
-- dtaq TRGQ
INSERT INTO QSTEST.RDT2 SELECT K, V FROM QSTEST.RDT WHERE K > 2;
-- dtaq TRGQ
