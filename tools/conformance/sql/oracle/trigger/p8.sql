-- after trigger with ALWREPCHG(*NO) beside one with *YES, on the primary.
-- cmd DLTF FILE(QSTEST/TRGQF)
-- cmd DLTF FILE(QSTEST/TRGFD8)
-- cmd DLTPGM PGM(QSTEST/TRGDUMP)
-- cmd DLTDTAQ DTAQ(QSTEST/TRGQ)
-- cmd DLTF FILE(QSTEST/QTRGSRC)
-- cmd CRTSRCPF FILE(QSTEST/QTRGSRC) RCDLEN(92)
-- cmd ADDPFM FILE(QSTEST/QTRGSRC) MBR(TRGDUMP) SRCTYPE(CLLE)
-- cmd CRTDTAQ DTAQ(QSTEST/TRGQ) MAXLEN(4000)
CREATE ALIAS QSTEST.TRGSRCM FOR QSTEST.QTRGSRC(TRGDUMP);
INSERT INTO QSTEST.TRGSRCM VALUES
 (1, 0, '             PGM        PARM(&BUF &LEN)'),
 (2, 0, '             DCL        VAR(&BUF) TYPE(*CHAR) LEN(3000)'),
 (3, 0, '             DCL        VAR(&LEN) TYPE(*CHAR) LEN(4)'),
 (4, 0, '             ENDPGM');
DROP ALIAS QSTEST.TRGSRCM;
-- cmd CRTBNDCL PGM(QSTEST/TRGDUMP) SRCFILE(QSTEST/QTRGSRC) SRCMBR(TRGDUMP)
CREATE TABLE QSTEST.TRGQF (K INT NOT NULL, V CHAR(5), W INT);
-- cmd ADDPFTRG FILE(QSTEST/TRGQF) TRGTIME(*AFTER) TRGEVENT(*UPDATE) PGM(QSTEST/TRGDUMP) TRG(EXTOFF) ALWREPCHG(*NO)
-- cmd CHGPFTRG FILE(QSTEST/TRGQF) TRG(EXTOFF) TRGLIB(QSTEST) STATE(*DISABLED)
CREATE TRIGGER QSTEST.SQLROW AFTER UPDATE OF V, W ON QSTEST.TRGQF REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW BEGIN END;
CREATE TRIGGER QSTEST.SQLSTMT AFTER INSERT ON QSTEST.TRGQF FOR EACH STATEMENT MODE DB2SQL BEGIN END;
CREATE TRIGGER QSTEST.SQLBEF BEFORE DELETE ON QSTEST.TRGQF REFERENCING OLD AS O FOR EACH ROW MODE DB2SQL BEGIN END;
-- cmd DSPFD FILE(QSTEST/TRGQF) TYPE(*TRG) OUTPUT(*OUTFILE) OUTFILE(QSTEST/TRGFD8)
SELECT TRTRTM, TRTREV, TRTRCN, TRTRIG, TRTRLB, TRTARC, TRTTSF, TRTMJA, TRNAM, TRLB, TRST, TRSTAT, TRTYP, TRMOD, TRORNT, TRUCN, TRUC FROM QSTEST.TRGFD8;
-- cmd DSPFD FILE(QSTEST/TRGQF) TYPE(*TRG) OUTPUT(*OUTFILE) OUTFILE(QSTEST/TRGFD8) OUTMBR(*FIRST *ADD)
SELECT COUNT(*) FROM QSTEST.TRGFD8;
-- cmd DSPFFD FILE(QSYS/QAFDTRG) OUTPUT(*OUTFILE) OUTFILE(QSTEST/TRGFFD)
SELECT WHFLDE, WHFLDT, WHFLDB, WHFLDD, WHFLDP, WHFOBO FROM QSTEST.TRGFFD ORDER BY WHFOBO;
