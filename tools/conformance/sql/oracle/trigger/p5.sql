-- Fifth probe: SQL triggers on the primary. The program each makes, the catalogs,
-- BEFORE changing NEW, AFTER writing a log, SIGNAL and an error in a body, DB2SQL
-- against DB2ROW, FOR EACH STATEMENT with a transition table, WHEN, UPDATE OF,
-- INSTEAD OF on a view, CPYF firing an SQL trigger, CHGPFTRG and the refusals.
-- cmd DLTF FILE(QSTEST/STRGV)
-- cmd DLTF FILE(QSTEST/STRG1)
-- cmd DLTF FILE(QSTEST/STRGLOG)
-- cmd DLTF FILE(QSTEST/STRGSRC)
CREATE TABLE QSTEST.STRG1 (ID INT NOT NULL, NAME CHAR(10), AMT DECIMAL(7, 2), D DATE);
CREATE TABLE QSTEST.STRGLOG (TXT VARCHAR(100), N INT);
CREATE TRIGGER QSTEST.TRB1 BEFORE INSERT ON QSTEST.STRG1 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW BEGIN ATOMIC SET N.NAME = UPPER(N.NAME); SET N.AMT = COALESCE(N.AMT, 0) + 1; END;
CREATE TRIGGER QSTEST.TRIGGER_WITH_A_LONG_NAME_A1 AFTER INSERT ON QSTEST.STRG1 REFERENCING NEW AS N FOR EACH ROW MODE DB2ROW INSERT INTO QSTEST.STRGLOG VALUES ('ROW ' CONCAT N.NAME, (SELECT COUNT(*) FROM QSTEST.STRG1));
CREATE TRIGGER QSTEST.TRA2 AFTER INSERT ON QSTEST.STRG1 REFERENCING NEW AS N FOR EACH ROW INSERT INTO QSTEST.STRGLOG VALUES ('SQL ' CONCAT N.NAME, (SELECT COUNT(*) FROM QSTEST.STRG1));
CREATE TRIGGER QSTEST.TRS3 AFTER INSERT ON QSTEST.STRG1 REFERENCING NEW TABLE AS NT FOR EACH STATEMENT INSERT INTO QSTEST.STRGLOG VALUES ('STMT', (SELECT COUNT(*) FROM NT));
CREATE TRIGGER QSTEST.TRB4 BEFORE UPDATE OF AMT ON QSTEST.STRG1 REFERENCING OLD AS O NEW AS N FOR EACH ROW MODE DB2ROW WHEN (N.AMT < 0) SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'negative amount';
CREATE TRIGGER QSTEST.TRB5 BEFORE DELETE ON QSTEST.STRG1 REFERENCING OLD AS O FOR EACH ROW MODE DB2ROW WHEN (O.ID = 99) BEGIN DECLARE X INT; SET X = 1 / (O.ID - 99); END;
