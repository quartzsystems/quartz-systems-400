-- The trigger buffer, ALWREPCHG, TRGUPDCND, a refusing trigger, the catalogs and DSPFD's
-- outfile, on the primary. TRGDUMP sends its buffer to QSTEST/TRGQ; a new record whose
-- first byte is X is refused with CPF9898, one starting R becomes Z (ALWREPCHG).
-- cmd DLTF FILE(QSTEST/TRGT)
-- cmd DLTPGM PGM(QSTEST/TRGDUMP)
-- cmd DLTDTAQ DTAQ(QSTEST/TRGQ)
-- cmd DLTF FILE(QSTEST/QTRGSRC)
-- cmd DLTF FILE(QSTEST/TRGFD)
-- cmd CRTSRCPF FILE(QSTEST/QTRGSRC) RCDLEN(92)
-- cmd ADDPFM FILE(QSTEST/QTRGSRC) MBR(TRGDUMP) SRCTYPE(CLLE)
-- cmd CRTDTAQ DTAQ(QSTEST/TRGQ) MAXLEN(4000)
CREATE ALIAS QSTEST.TRGSRCM FOR QSTEST.QTRGSRC(TRGDUMP);
INSERT INTO QSTEST.TRGSRCM VALUES
 (1, 0, '             PGM        PARM(&BUF &LEN)'),
 (2, 0, '             DCL        VAR(&BUF) TYPE(*CHAR) LEN(3000)'),
 (3, 0, '             DCL        VAR(&LEN) TYPE(*CHAR) LEN(4)'),
 (4, 0, '             DCL        VAR(&N) TYPE(*DEC) LEN(5 0)'),
 (5, 0, '             DCL        VAR(&OFF) TYPE(*DEC) LEN(9 0)'),
 (6, 0, '             DCL        VAR(&ST) TYPE(*DEC) LEN(9 0)'),
 (7, 0, '             DCL        VAR(&C) TYPE(*CHAR) LEN(1)'),
 (8, 0, '             CHGVAR     VAR(&N) VALUE(%BIN(&LEN))'),
 (9, 0, '             CALL       PGM(QSNDDTAQ) PARM(''TRGQ'' ''QSTEST'' &N &BUF)'),
 (10, 0, '             CHGVAR     VAR(&OFF) VALUE(%BIN(&BUF 65 4))'),
 (11, 0, '             IF         COND(&OFF *GT 0) THEN(DO)'),
 (12, 0, '             CHGVAR     VAR(&ST) VALUE(&OFF + 1)'),
 (13, 0, '             CHGVAR     VAR(&C) VALUE(%SST(&BUF &ST 1))'),
 (14, 0, '             IF         COND(&C *EQ ''X'') THEN(SNDPGMMSG MSGID(CPF9898) +'),
 (15, 0, '                          MSGF(QCPFMSG) MSGDTA(''refused'') MSGTYPE(*ESCAPE))'),
 (16, 0, '             IF         COND(&C *EQ ''R'') THEN(CHGVAR +'),
 (17, 0, '                          VAR(%SST(&BUF &ST 1)) VALUE(''Z''))'),
 (18, 0, '             ENDDO'),
 (19, 0, '             ENDPGM');
DROP ALIAS QSTEST.TRGSRCM;
