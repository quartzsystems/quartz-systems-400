-- QSTEST fixed queries; each becomes Qnn.csv in order, without a header.
SELECT CUSNO, NAME, STATUS, BAL, SINCE, CREDIT, NOTE FROM QSTEST/CUSTOMER ORDER BY CUSNO;
SELECT C.NAME, COUNT(*), SUM(O.AMOUNT) FROM QSTEST/CUSTOMER C JOIN QSTEST/ORDERS O ON C.CUSNO = O.CUSNO GROUP BY C.NAME ORDER BY C.NAME;
SELECT C.CUSNO, C.NAME FROM QSTEST/CUSTOMER C LEFT JOIN QSTEST/ORDERS O ON C.CUSNO = O.CUSNO WHERE O.ORDNO IS NULL ORDER BY C.CUSNO;
SELECT ORDNO, AMOUNT FROM QSTEST/ORDERS WHERE AMOUNT BETWEEN 50 AND 500 ORDER BY AMOUNT DESC, ORDNO;
SELECT L.PRODID, SUM(L.QTY * L.PRICE) FROM QSTEST/ORDLINE L GROUP BY L.PRODID HAVING SUM(L.QTY * L.PRICE) > 20 ORDER BY 2 DESC;
SELECT NAME FROM QSTEST/CUSTOMER WHERE NAME LIKE '%a%' AND STATUS = 'A' ORDER BY NAME;
SELECT CUSNO, COALESCE(NOTE, 'none'), LENGTH(TRIM(NAME)), SUBSTR(NAME, 1, 2) FROM QSTEST/CUSTOMER WHERE SINCE IS NOT NULL ORDER BY CUSNO;
SELECT EVTID, DMDY, DJUL, DUSA, TUSA, DAYS(DJIS) - DAYS(DATE '2000-01-01'), DAYOFWEEK(DEUR) FROM QSTEST/EVENTS ORDER BY EVTID;
SELECT TID, FA, FS, FP, FB, FB18, FL, FT, FZ FROM QSTEST/TYPES ORDER BY TID;
SELECT ORDNO, CUSNO, NAME, AMOUNT FROM QSTEST/ORDJOIN ORDER BY ORDNO;
SELECT CUSNO, NAME FROM QSTEST/CUSTOMER WHERE CUSNO IN (SELECT CUSNO FROM QSTEST/ORDERS WHERE AMOUNT > 100) ORDER BY CUSNO;
SELECT PRODID, SUM(ONHAND) FROM QSTEST/INVENTORY GROUP BY PRODID ORDER BY PRODID;
